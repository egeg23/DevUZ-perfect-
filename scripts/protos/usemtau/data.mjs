const num = (s) => Number(String(s).replace(",", "."));
const r3 = (x) => Math.round(x * 1000) / 1000;
const RHO = 0.00785; // кг на мм² сечения на метр длины

/* Разбор названия: размеры, вес метра (kgm) или квадратного метра (kgm2), марка. */
function parse(name, cat, desc) {
  const s = name.replace(/\s+/g, " ").trim();
  const nums = (s.match(/\d+(?:,\d+)?/g) || []).map(num);
  const o = { dims: nums, kgm: null, kgm2: null, main: nums[0] ?? null, bar: null };
  const mark = /09Г2С/i.test(s + desc) ? "09Г2С" : /СТ3СП\/ПС|СТ3/i.test(s + desc) ? "Ст3сп/пс" : null;
  o.mark = mark;
  if (/^(Арматура|Круг|Катанка)/.test(s)) {
    const d = nums[0];
    o.kgm = r3(0.0061654 * d * d);
    o.bar = /бухт/.test(s) ? null : 11.7;
    o.form = /бухт/.test(s) ? "бухта" : /тян/.test(s) ? "тянутая" : null;
  } else if (/^Проволока/.test(s)) {
    const dd = nums[/ВР-1/.test(s) ? 1 : 0];
    o.main = dd;
    o.kgm = r3(0.0061654 * dd * dd);
    o.dims = [dd];
  } else if (/^Квадрат/.test(s)) {
    o.kgm = r3(nums[0] * nums[0] * RHO);
    o.bar = 6;
  } else if (/^Труба профильная/.test(s)) {
    const [a, b, t] = nums;
    o.kgm = r3((2 * (a + b) - 4 * t) * t * RHO);
    o.bar = 6;
  } else if (/^Труба/.test(s)) {
    const [D, t] = nums;
    o.kgm = r3((D - t) * t * 0.02466);
    o.dims = [D, t];
    o.bar = 6;
  } else if (/^Уголок/.test(s)) {
    const [b, t] = nums;
    o.kgm = r3((2 * b - t) * t * RHO);
    o.dims = [b, t];
    o.bar = 11.7;
  } else if (/^Швеллер гнутый/.test(s)) {
    const [h, b, t] = nums;
    o.kgm = r3((h + 2 * b - 2 * t) * t * RHO);
    o.bar = 11.7;
  } else if (/^Швеллер/.test(s)) {
    o.kgm = CHANNEL[nums[0]] ?? null;
    o.bar = 11.7;
  } else if (/^Балка/.test(s)) {
    const key = s.replace(/^Балка\s*/, "").replace(/\s+/g, "").toUpperCase();
    o.kgm = BEAM[key] ?? null;
    o.key = key;
    o.bar = 12;
  } else if (/^Полоса/.test(s) && !/\//.test(s)) {
    o.kgm = r3(nums[0] * nums[1] * RHO);
    o.bar = 6;
  } else if (/^ЛИСТ (г\/к|х\/к|оцинк)/.test(s)) {
    o.kgm2 = r3(nums[0] * 7.85);
    o.dims = [nums[0]];
  } else if (/^Сетка/.test(s)) {
    const d = nums[0], c = nums[1];
    o.kgm2 = r3(2 * (1000 / (c * 10)) * 0.0061654 * d * d);
    o.dims = [d, c];
  }
  return o;
}

