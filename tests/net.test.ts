import assert from "node:assert/strict";
import { test } from "node:test";

import { asInet } from "@/lib/net";

test("настоящие адреса проходят", () => {
  for (const value of [
    "127.0.0.1",
    "10.0.0.255",
    "255.255.255.255",
    "0.0.0.0",
    "::1",
    "fe80::1",
    "2001:db8:85a3::8a2e:370:7334",
    "2001:0db8:85a3:0000:0000:8a2e:0370:7334",
    "::ffff:192.168.0.1",
  ]) {
    assert.equal(asInet(value), value, `${value} должен пройти`);
  }
});

/**
 * Ровно те строки, которые пропускала прежняя проверка «цифры и точки».
 *
 * Каждая из них роняла вставку целиком: Postgres отвергает всю строку, если
 * значение не годится для inet. Заявка на покупку теряла запись в базе, а
 * строка журнала не появлялась вовсе — и оба раза молча, потому что ошибку
 * вставки мы намеренно не показываем пользователю.
 */
test("мусор, который валил вставку, больше не проходит", () => {
  for (const value of [
    "1.2.3.4.5",
    "999.1.1.1",
    "1.2.3",
    "01.2.3.4",
    "unknown",
    "",
    "...",
    "1.2.3.4abc",
    "::ffff:999.1.1.1",
    "1::2::3",
    "gggg::1",
    "12345::1",
    "a".repeat(60),
  ]) {
    assert.equal(asInet(value), null, `${JSON.stringify(value)} не должен пройти`);
  }
});

test("пустое значение — это null, а не ошибка", () => {
  assert.equal(asInet(null), null);
  assert.equal(asInet(undefined), null);
  assert.equal(asInet("   "), null);
});
