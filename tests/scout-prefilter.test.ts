import assert from "node:assert/strict";
import { test } from "node:test";

import { prefilter } from "@/lib/scout/prefilter";

/**
 * Настоящие сообщения — то, ради чего фильтр и написан.
 */
test("спрос проходит", () => {
  const samples = [
    "Ребят, нужен интернет-магазин для сети аптек, кто может взяться?",
    "Подскажите, кто делает мобильные приложения в Ташкенте, нужен Android и iOS",
    "Ищем разработчика на сайт компании, бюджет обсудим",
    "Сколько стоит разработать сайт с каталогом и корзиной?",
    "Хотим автоматизировать заказы, нужна CRM и интеграция с 1С",
    "Kompaniya uchun sayt kerak, kim qiladi?",
  ];

  for (const text of samples) {
    const verdict = prefilter(text);
    assert.equal(verdict.pass, true, `не прошло: ${text}`);
    assert.ok(verdict.topics.length, `нет темы: ${text}`);
  }
});

/**
 * Главная проверка файла.
 *
 * В любом чате про разработку девять из десяти сообщений о сайтах пишут те,
 * кто их делает. Фильтр, который этого не видит, приносит оператору ленту
 * чужой рекламы — и оператор перестаёт её открывать через неделю.
 */
test("предложение не проходит, даже когда похоже на спрос", () => {
  const samples = [
    "Делаем сайты под ключ, от 500$, портфолио в личке",
    "Наша студия разрабатывает мобильные приложения на Flutter",
    "Ищу работу, опыт работы 5 лет, делаю интернет-магазины",
    "Предлагаем услуги по разработке сайтов и ботов",
    "Верстаю лендинги, нужен заказ, пишите в личку",
    "Bizning jamoa sayt va ilova ishlab chiqadi, portfolio bor",
  ];

  for (const text of samples) {
    const verdict = prefilter(text);
    assert.equal(verdict.pass, false, `ошибочно прошло: ${text}`);

    // Причина проверяется отдельно, и это не придирка.
    //
    // Первая версия фильтра была написана на \b, который в JavaScript не
    // знает кириллицы, — не срабатывало вообще ни одно правило. Этот тест
    // был зелёным: не проходило ничего, в том числе предложение. Проверка
    // «отклонено именно как предложение» — единственное, что отличает
    // работающее правило от неработающего движка.
    assert.equal(
      verdict.reason,
      "supply",
      `отклонено, но не как предложение (${verdict.reason}): ${text}`,
    );
  }
});

test("шум отсеивается до вызова модели", () => {
  const cases: [string, string][] = [
    ["ок", "too_short"],
    ["Спасибо большое!", "too_short"],
    ["Всем привет, как дела у вас сегодня в этом прекрасном чате?", "no_topic"],
    ["Инвестиции в крипту, доход 300% в месяц, переходи по ссылке прямо сейчас", "spam"],
    [`нужен сайт ${"а".repeat(1600)}`, "too_long"],
  ];

  for (const [text, reason] of cases) {
    const verdict = prefilter(text);
    assert.equal(verdict.pass, false, `ошибочно прошло: ${text.slice(0, 40)}`);
    assert.equal(verdict.reason, reason, `неверная причина для: ${text.slice(0, 40)}`);
  }
});

test("тема определяется и попадает в вердикт", () => {
  assert.deepEqual(prefilter("Нужен интернет-магазин для аптеки, кто возьмётся").topics, [
    "магазин",
  ]);

  const both = prefilter("Нужен сайт и мобильное приложение для доставки, ищем команду");
  assert.ok(both.topics.includes("сайт"));
  assert.ok(both.topics.includes("приложение"));
});

/**
 * Тема без спроса — это разговор о технологиях, а не заказ. Такие
 * сообщения составляют основную массу тематических чатов, и пропускать их
 * в модель значит платить за обсуждение фреймворков.
 */
test("разговор на тему без запроса не проходит", () => {
  const verdict = prefilter(
    "Кстати, на Flutter приложения собираются гораздо быстрее, чем на нативе",
  );
  assert.equal(verdict.pass, false);
  assert.ok(verdict.topics.includes("приложение"), "тема-то есть");
});
