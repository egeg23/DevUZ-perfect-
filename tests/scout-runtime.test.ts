import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";

/**
 * Скаут — единственная часть проекта, которая работает вне образа.
 *
 * Всё остальное живёт в контейнере, и настройки рантайма ему достаются из
 * Dockerfile. Скаут запускается systemd прямо на хосте, и любая такая
 * настройка до него не доходит — молча. Три проверки ниже сторожат ровно те
 * три места, где эта разница уже стоила бы рабочего дня: каждая падает
 * только на невидимой поломке, у которой в журнале нет ни одной строки со
 * словом «ошибка».
 */
const read = (path: string) => readFileSync(new URL(`../${path}`, import.meta.url), "utf8");

/**
 * Прокси для fetch.
 *
 * Без флага скаут читает чаты (MTProto идёт через собственный мост) и
 * ничего больше: разбор сообщений и сигнал оператору — это обычный fetch к
 * Anthropic и к api.telegram.org, а с этого сервера напрямую не отвечает ни
 * один из них. Поломка выглядит как «модель ничего не нашла», а не как
 * недоступная сеть, — и ищут её в промпте.
 */
test("скаут ходит наружу через прокси", () => {
  const unit = read("deploy/devuz-scout.service");

  assert.match(
    unit,
    /^Environment=NODE_OPTIONS=.*--use-env-proxy/m,
    "в юните скаута нет --use-env-proxy: разбор и сигнал оператору работать не будут",
  );

  // systemd применяет источники переменных сверху вниз. Стоя выше
  // EnvironmentFile, флаг молча проиграл бы строке NODE_OPTIONS из .env.
  assert.ok(
    unit.indexOf("Environment=NODE_OPTIONS=") > unit.indexOf("EnvironmentFile="),
    "Environment= стоит выше EnvironmentFile= — .env перебьёт флаг",
  );
});

/**
 * Пакеты сайта на хосте.
 *
 * Скаут берёт отсев, разбор и запись из lib/, а тот импортирует
 * @anthropic-ai/sdk и @supabase/supabase-js. Node ищет пакет от файла,
 * который его импортирует: для lib/… это корневой node_modules, и
 * scout/node_modules он не увидит, сколько туда ни клади (проверено
 * отдельно на голом каталоге). Сайт собирается внутри образа, поэтому на
 * хосте корневой node_modules не появляется сам.
 */
test("выкатка ставит на хост пакеты, без которых скаут не стартует", () => {
  const deploy = read("scripts/vps-deploy.sh");

  const install = deploy.indexOf("npm ci --omit=dev");
  const start = deploy.indexOf("systemctl enable --now devuz-scout.service");

  assert.ok(install > 0, "выкатка не ставит зависимости сайта на хост");
  assert.ok(install < start, "зависимости ставятся после запуска скаута — он упадёт раньше");

  // Запуск обязан быть под условием: скаут без пакетов не падает один раз,
  // а перезапускается каждые тридцать секунд, засоряя journal и выглядя
  // работающим сервисом.
  assert.match(
    deploy.slice(install, start),
    /SCOUT_READY=0/,
    "неудачная установка не мешает запуску — скаут уйдёт в вечный перезапуск",
  );
});

/**
 * Прокси не достаётся выкатке.
 *
 * Он задан в том же .env, и человек, сходивший в скаут, обычно уже сделал
 * «set -a; . /opt/devuz/.env; set +a». Дальше git идёт к GitHub через
 * внешний прокси и получает 403 на первой же строке — при том что из
 * Action, где оболочка чистая, та же выкатка проходит. Диагноз при этом
 * звучит как «нет доступа к репозиторию», и искать идут токен.
 */
test("выкатка не ходит за кодом через прокси приложения", () => {
  const deploy = read("scripts/vps-deploy.sh");

  const cleared = deploy.indexOf("unset HTTPS_PROXY");
  assert.ok(cleared > 0, "выкатка не сбрасывает прокси — git пойдёт через него и получит 403");
  assert.ok(
    cleared < deploy.indexOf("git fetch"),
    "прокси сбрасывается уже после git fetch — то есть слишком поздно",
  );

  // Строчные варианты важнее прописных: curl внутри git смотрит на них
  // первыми, и сброс одних заглавных выглядел бы работающим.
  for (const name of ["https_proxy", "http_proxy"]) {
    assert.match(
      deploy,
      new RegExp(`unset[^\\n]*\\b${name}\\b`),
      `${name} не сброшен — git всё равно найдёт прокси`,
    );
  }
});

/**
 * Обратная сторона предыдущей проверки.
 *
 * «COPY . .» в Dockerfile идёт после того, как стадия deps положила в образ
 * полный node_modules. Всё, что лежит в node_modules на хосте, ложится
 * поверх — а на хосте он ставится с --omit=dev. Сборке нужен typescript, и
 * без исключения она падала бы на нём, хотя причина была бы за сто строк до
 * этого, в установке для скаута.
 */
test("хостовый node_modules не уезжает в образ", () => {
  assert.match(
    read(".dockerignore"),
    /^node_modules$/m,
    "node_modules не исключён из контекста сборки — образ соберётся без dev-зависимостей",
  );
});
