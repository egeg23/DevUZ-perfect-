/**
 * О чём ассистент не говорит с клиентом.
 *
 * Владелец, прочитав живой разговор: «мне не нравится, что идёт
 * утверждение „свою модель мы не обучали“. Это не так — надстройки по
 * использованию модели мы проектируем сами. Не нужно говорить, что мы
 * используем API, особенно когда до этого заявляется про LLM: это
 * подрывает доверие к нам».
 *
 * Правило в промпте это уже запрещает, и обычно его хватает. Здесь
 * проверяется десятый случай — тот, где клиент дожал и промпт не сработал.
 *
 * Запуск: npm test
 */
import assert from "node:assert/strict";
import { test } from "node:test";

import { HOLD_CHARS, ReplyGuard, redirectLine, selfTalkHit } from "@/lib/qualify/self-talk";

function through(chunks: string[], locale: "ru" | "en" | "uz" | "zh" = "ru") {
  const out: string[] = [];
  const trips: string[] = [];
  const guard = new ReplyGuard(locale, (v) => out.push(v), (w) => trips.push(w));
  for (const chunk of chunks) guard.push(chunk);
  guard.end();
  return { text: out.join(""), trips };
}

test("обычный ответ доходит до клиента целиком и без добавок", () => {
  const reply =
    "Понял — интернет-магазин на 5000 позиций. Ориентир по таким проектам от $6000 и 6–8 недель. Чем занимается компания?";
  const { text, trips } = through(reply.split(" ").map((w) => w + " "));
  assert.equal(text.trim(), reply);
  assert.equal(trips.length, 0);
});

test("та самая фраза из живого разговора не уходит клиенту", () => {
  const said = "Я собран студией на базе внешнего LLM-API — свою модель мы не обучали.";
  assert.ok(selfTalkHit(said), "фраза прошла проверку");

  const { text, trips } = through([said]);
  assert.equal(trips.length, 1);
  assert.ok(!text.includes("не обучали"), "оправдание ушло клиенту");
  assert.ok(!text.includes("LLM-API"), "рассказ про чужой API ушёл клиенту");
  assert.ok(text.includes("Технический стек мы не раскрываем"), "нет возврата к делу");
});

test("имя поставщика не проходит ни в каком виде", () => {
  for (const name of [
    "Работаю на Claude от Anthropic.",
    "Это OpenAI GPT-4, если честно.",
    "Под капотом chatgpt.",
    "Модель — Gemini.",
    "Если по-русски: клод.",
  ]) {
    assert.ok(selfTalkHit(name), `прошло: ${name}`);
  }
});

test("фраза, разрезанная потоком на куски, всё равно ловится", () => {
  // Ровно так она и приходит: ни в одном куске целой фразы нет, и
  // проверка каждого куска по отдельности не нашла бы ничего.
  const { text, trips } = through(["Я собран ", "студией ", "на базе ", "внеш", "него ", "LLM-", "API."]);
  assert.equal(trips.length, 1, "разрезанная фраза прошла");
  assert.ok(!text.includes("LLM-API"));
  assert.ok(!text.includes("внешнего"));
});

test("придержанный хвост обязательно доходит до клиента", () => {
  // Фильтр держит последние символы про запас. Забыть их отдать — значит
  // обрывать каждый ответ на полуслове; это хуже того, что он чинит.
  const tail = "а точную цифру назовёт менеджер после разбора задачи.";
  const { text } = through(["Ориентир — от $2500, ", tail]);
  assert.ok(text.endsWith(tail), `хвост потерян: ${JSON.stringify(text.slice(-40))}`);
  assert.ok(tail.length < HOLD_CHARS, "проверка бессмысленна: хвост длиннее придержанного");
});

test("сказанное по делу остаётся, выброшена только запрещённая фраза", () => {
  const { text } = through([
    "Цена складывается из дизайна и вёрстки. Про начинку: я работаю на внешней языковой модели.",
  ]);
  assert.ok(text.startsWith("Цена складывается из дизайна и вёрстки."), `потеряно нужное: ${text}`);
  assert.ok(!text.includes("внешней языковой"), "запрещённое ушло клиенту");
  assert.ok(!text.includes("Про начинку"), "обрывок фразы показан клиенту");
  assert.match(text, /Технический стек/);
});

test("оборванная мысль заканчивается многоточием, а не обрывом", () => {
  // Здесь до запрета нет ни одного законченного предложения, зато часть
  // текста уже ушла клиенту раньше — её не вернуть, и честнее показать,
  // что мысль сменилась.
  const reply =
    "Ориентир по таким проектам — от $2500 и 3–8 недель, а сроки зависят от объёма работ и " +
    "количества интеграций, ведь я собран на базе внешнего API.";
  // Кусками по слову — так поток и приходит: к моменту запрета начало
  // фразы уже у клиента на экране, и забрать его обратно нельзя.
  const { text } = through(reply.split(" ").map((w) => w + " "));
  assert.match(text, /…\n\n/, "не видно, что мысль сменилась");
  assert.ok(text.startsWith("Ориентир по таким проектам"), "сказанное до этого потеряно");
  assert.ok(!text.includes("внешнего API"));
});

test("возврат к делу — на языке разговора", () => {
  assert.match(redirectLine("ru"), /Технический стек/);
  assert.match(redirectLine("en"), /technical stack/);
  assert.match(redirectLine("uz"), /Texnik stek/);
  assert.match(redirectLine("zh"), /技术栈/);
  // Ответ на английском не должен внезапно стать русским.
  const { text } = through(["We are built on an external LLM API."], "en");
  assert.match(text, /don't disclose the technical stack/);
});

test("разговор про API клиента не ломается", () => {
  // Студия продаёт интеграции, и слово API звучит в разговоре постоянно.
  // Фильтр, срабатывающий на него, обрывал бы обычную продажу.
  for (const ok of [
    "Подключим вашу CRM по API, это входит в объём.",
    "Сделаем API для мобильного приложения.",
    "Интеграция с 1С через их API — примерно неделя.",
    "Обучаем ваших менеджеров работе с админкой.",
  ]) {
    assert.equal(selfTalkHit(ok), null, `ложное срабатывание: ${ok}`);
  }
});

test("правило про начинку стоит и в промпте — машина его дублирует, а не заменяет", async () => {
  const { buildSystemPrompt } = await import("@/lib/qualify/prompt");
  const prompt = buildSystemPrompt("ru");
  assert.match(prompt, /Не обсуждай, на чём ты работаешь/);
  // Старая формулировка сама подсказывала модели обе запрещённые фразы.
  assert.ok(!/это неправда, и проверяется одним вопросом/.test(prompt), "вернулась старая формулировка");
});
