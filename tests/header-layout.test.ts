import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";

const header = readFileSync(
  new URL("../components/layout/header.tsx", import.meta.url),
  "utf8",
);
const code = header.replace(/\{\/\*[\s\S]*?\*\/\}/g, "");

/**
 * Три настройки, которые держат шапку в одну строку, и каждая по
 * отдельности выглядит необязательной.
 *
 * Замерено на собранном приложении: строка шапки шире 1224 px не бывает —
 * контейнер упирается в 1320 при полях по 48. А восемь пунктов меню,
 * переключатель на четыре языка и кнопка требуют 1278 px по-русски и
 * 1315 по-узбекски. Поэтому «Проверить сайт» и «О студии» ломались
 * пополам на любом экране, включая 1920.
 *
 * Убрать любую из трёх — и сломается либо перенос, либо выезд за край.
 */
test("подписи меню не переносятся", () => {
  const nav = code.slice(code.indexOf("<nav"), code.indexOf("</nav>"));
  assert.match(nav, /whitespace-nowrap/, "подписи снова смогут ломаться пополам");
});

test("меню разворачивается там, где помещается", () => {
  // lg (1024) даёт всего 928 px содержимого — меню туда не влезает даже
  // сжатым. Ниже xl должен быть бургер.
  const nav = code.slice(code.indexOf("<nav"), code.indexOf("</nav>"));
  assert.match(nav, /xl:flex/, "меню снова показывается раньше, чем помещается");
  assert.doesNotMatch(nav, /\blg:flex/, "вернулся брейкпоинт lg — меню будет сжато и переносится");

  // Бургер обязан исчезать ровно там, где появляется меню: иначе на
  // какой-то ширине их видно оба или не видно ни одного.
  assert.match(code, /xl:hidden/, "бургер живёт не на том же брейкпоинте, что меню");
  assert.doesNotMatch(code, /\blg:hidden/, "бургер остался на lg — разъедется с меню");
});

test("слово «DevUz» уступает место меню", () => {
  // Знак остаётся, ссылка подписана для скринридера. Вернуть слово можно
  // только освободив около 90 px — то есть убрав пару пунктов меню или
  // укоротив подписи.
  assert.match(code, /wordmarkClassName="xl:hidden"/, "слово вернулось в строку, где нет места");
  assert.match(code, /aria-label="DevUz Studio"/, "ссылка на главную осталась без доступного имени");
});
