import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";

const route = readFileSync(
  new URL("../app/api/telegram/webhook/route.ts", import.meta.url),
  "utf8",
);

/** Комментарии выкидываем: в них про await и разговор с моделью написано намеренно. */
const code = route.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");

/**
 * Сторож за порядком «сначала ответ, потом работа».
 *
 * Telegram ждёт от вебхука ответа считаные секунды. Не дождавшись, он
 * считает доставку неудачной, присылает то же обновление снова, а после
 * нескольких промахов перестаёт слать обновления вовсе — на часы. Это
 * уже случалось: getWebhookInfo показывал «Connection timed out», команда
 * /login переставала доходить, и выглядело это как сломанный вход.
 *
 * Разбор сообщения клиента поднимает разговор с моделью, то есть десятки
 * секунд. Один возвращённый `await` перед route() — и таймаут снова
 * гарантирован на каждом живом клиенте.
 *
 * Замерено на собранном приложении: с работой до ответа Telegram ждёт
 * 5,08 с при пятисекундной внешней задержке, с after() — 0,004 с.
 * Поведение проверяется браузером и заглушкой Bot API, здесь — только то,
 * что порядок не переставили обратно.
 */
test("ответ Telegram не ждёт разбора сообщения", () => {
  assert.match(code, /after\(\(\)\s*=>\s*route\(update\)\)/, "route() больше не уезжает в after()");
  assert.doesNotMatch(
    code,
    /await\s+route\(update\)/,
    "route() снова выполняется до ответа — Telegram будет отваливаться по таймауту",
  );
});

test("быстрые проверки остаются до ответа", () => {
  // Секрет, разбор тела и отсев повторов обязаны отработать синхронно:
  // после ответа отказать уже нельзя, а 200 на чужой запрос означал бы,
  // что вебхук принимает что угодно.
  const body = code.slice(code.indexOf("export async function POST"), code.indexOf("async function route"));

  assert.match(body, /TELEGRAM_WEBHOOK_SECRET/, "проверка секрета уехала из синхронной части");
  assert.match(body, /status:\s*403/, "чужой запрос больше не отклоняется");
  assert.match(body, /alreadyHandled\(update\.update_id\)/, "отсев повторов уехал из синхронной части");

  // И порядок: отсев повторов должен стоять раньше, чем работа ставится в
  // очередь, иначе повтор всё равно её запустит.
  assert.ok(
    body.indexOf("alreadyHandled") < body.indexOf("after("),
    "повтор попадёт в работу: проверка стоит после постановки в очередь",
  );
});
