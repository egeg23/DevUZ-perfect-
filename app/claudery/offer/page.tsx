import type { Metadata } from "next";

import { rub } from "@/lib/claudery/scenario";

import { Footer, PRIVACY_PATH, TERMS_PATH, sellerData } from "../docs";

export const dynamic = "force-dynamic";
export const metadata: Metadata = { title: "Claudery — оферта на продажу подписок" };

/**
 * Публичная оферта Claudery. Владелец, 17.11.2026: «Клиенты в рублях —
 * оферта от ИП в РФ, реквизиты из хранилища, в репозиторий их не клади».
 * С 18.11.2026 — купля-продажа цифрового товара (подписки на нейросети), не
 * оказание услуг: так согласовано с Platega. Продавец и ИНН — из
 * `app.INVOICE_RU_*` при каждом показе; товары и цены — из настроек бота;
 * условия и гарантию владелец пишет в конструкторе.
 */
export default async function ClauderyOffer() {
  const seller = await sellerData();
  const { payee, taxId, setup } = seller;
  const h2 = { fontSize: 20 } as const;
  let n = 4;
  return (
    <main style={{ maxWidth: 760, margin: "0 auto", padding: "32px 16px" }}>
      <h1 style={{ fontSize: 26 }}>Публичная оферта: продажа подписок на нейросети «Claudery»</h1>
      <p>
        Продавец: {payee ?? "индивидуальный предприниматель (реквизиты уточняются)"}
        {taxId ? `, ИНН ${taxId}` : ""}.
      </p>
      <h2 style={h2}>1. Предмет</h2>
      <p>
        Продавец передаёт Покупателю цифровой товар: доступ к подписке на нейросеть из перечня ниже на указанный срок. Заказ оформляется в Telegram-боте Claudery
        и оплачивается на странице заказа на сайте.
      </p>
      <h2 style={h2}>2. Товары и цены</h2>
      <ul>
        {setup.products.map((p, i) => (
          <li key={i}>
            {p.title}: {rub(p.price)}
            {p.note ? `. ${p.note}` : ""}
          </li>
        ))}
      </ul>
      <p>
        Оплата через платёжный сервис Platega на странице заказа. Оплата означает согласие с этой офертой (акцепт). Покупателю, который уже покупал у Продавца,
        цена может быть снижена: итоговая цена показана на странице заказа до оплаты.
      </p>
      <h2 style={h2}>3. Передача товара</h2>
      <p>
        Доступ передаётся Покупателю в Telegram после того, как платёжный сервис подтвердит оплату, с 06:00 до 19:00 по московскому времени. Товар считается
        переданным, когда Покупатель получил данные доступа. Подключение и ответы на вопросы по купленной подписке входят в поддержку покупателя и отдельно не
        оплачиваются.
      </p>
      {setup.terms ? (
        <>
          <h2 style={h2}>{n++}. Условия и гарантия</h2>
          <p style={{ whiteSpace: "pre-line" }}>{setup.terms}</p>
        </>
      ) : null}
      <h2 style={h2}>{n++}. Возврат</h2>
      <p>Если доступ не был передан, Продавец возвращает оплату полностью по обращению Покупателя в поддержку (контакты ниже).</p>
      <h2 style={h2}>{n++}. Персональные данные</h2>
      <p>
        Продавец обрабатывает данные Покупателя по <a href={PRIVACY_PATH}>политике конфиденциальности</a>. Порядок пользования ботом и сайтом — в{" "}
        <a href={TERMS_PATH}>пользовательском соглашении</a>.
      </p>
      <Footer s={seller} />
    </main>
  );
}
