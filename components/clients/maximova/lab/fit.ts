const FALLBACK = 1.15;

/** Ширина самого длинного слова в кеглях, с запасом на округление. */
export function longestEm(text: string): number {
  let max = 0;
  for (const word of text.toUpperCase().split(/\s+/)) {
    let w = 0;
    for (const ch of word) w += WIDTH[ch] ?? FALLBACK;
    if (w > max) max = w;
  }
  return Math.round(max * 1.04 * 100) / 100;
}

/** style для заголовка: `<h1 className={s.display1} style={fit(text)}>`. */
export const fit = (text: string) => ({ "--em": longestEm(text) }) as CSSProperties;
