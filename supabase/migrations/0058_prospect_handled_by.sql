-- Кто отвечает клиенту сам, после «Отвечать самому».
--
-- Пока разговор ведёт модель, человеку пишут только по делу: клиент просит
-- позвать человека или не писать ему. После «Отвечать самому» модель
-- замолкает, и обычный ответ клиента не доходил ни до кого: он ложился в
-- переписку, и узнать о нём можно было, только открыв карточку лида.
--
-- Теперь каждое входящее после перехвата уходит тому, кто перехватил. Это
-- не обязательно тот, за кем касание (claimed_by): разговор может забрать
-- руководитель или владелец, и сообщения нужны ему, а не менеджеру.
alter table public.prospects
  add column if not exists handled_by uuid references public.staff(id) on delete set null;

comment on column public.prospects.handled_by is
  'Кто нажал «Отвечать самому». Ему уходит каждое новое сообщение клиента; пусто — разговор ведёт модель или его передали тому, за кем касание.';
