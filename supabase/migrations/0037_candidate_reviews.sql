-- Разборы кандидатов: что модель сказала о резюме.
--
-- Владелец: «хочу новую вкладку — анализ кандидатов. Туда загружается PDF, и
-- ты выдаёшь такой же отчёт, как сделал ранее… это для оценки пригодности
-- сотрудника для работы у нас».
--
-- Самого PDF здесь нет и не будет. Резюме — это чужие персональные данные:
-- телефон, почта, адрес, места работы. Хранить их у себя без нужды значит
-- взять на себя ответственность, которой можно не брать: для решения нужен
-- разбор, а не файл. Файл живёт ровно столько, сколько идёт разбор, и
-- нигде не сохраняется.
--
-- Контакты кандидата не сохраняются по той же причине: чтобы позвонить,
-- у нанимающего есть письмо с резюме, а панели телефон не нужен.
create table if not exists public.candidate_reviews (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  created_by uuid references public.staff(id) on delete set null,

  /* Имя из резюме — чтобы карточку можно было найти глазами. */
  name text not null,
  /* На какую вакансию смотрели. */
  role text not null,
  /* На что претендует сам кандидат, по его же словам. */
  wants text,

  /* yes | conditional | no */
  verdict text not null,
  /* Вердикт одной фразой. */
  headline text not null,
  /* Разбор целиком: сильные стороны, стопы, факты, вопросы, проба. */
  report jsonb not null,

  /* Сколько страниц было в файле — на случай «а это точно всё резюме?». */
  pages integer
);

create index if not exists candidate_reviews_recent on public.candidate_reviews (created_at desc);
