-- Откуда пришёл лид: канал, ник и страница — фактами, а не пересказом.
--
-- Владелец: «указывай юзернейм, если он есть. Откуда писал, во сколько,
-- где».
--
-- Время у лида было и раньше (created_at), а вот остального не было совсем.
-- Ник клиента до сих пор попадал в contact_handle только потому, что так
-- велено модели в системном промпте: «контакт клиента уже известен,
-- подставь ровно это значение». Просьба в промпте исполняется в девяти
-- случаях из десяти, и десятый — это лид, по которому менеджер не может
-- написать человеку, хотя бот всё это время знал его ник.
--
-- Поэтому три колонки заполняет не модель, а сам канал.
--
-- tg_username — то, что Telegram прислал в message.from.username. Без «@»
-- и без выдумок: нет ника — null, и это честнее пустой строки.
--
-- entry_path — страница сайта, с которой человек открыл чат. Это ответ на
-- «где»: разговор с карточки кейса и разговор с калькулятора — разные
-- разговоры, и начинать их надо по-разному.
--
-- entry_ref — откуда он вообще пришёл на сайт: поиск, инстаграм, чужая
-- ссылка. Первое касание, а не последнее: внутренние переходы по сайту
-- сюда не пишутся, иначе у всех лидов в источнике окажется devuz.studio.
alter table public.leads
  add column if not exists tg_username text,
  add column if not exists entry_path text,
  add column if not exists entry_ref text;

comment on column public.leads.tg_username is
  'Ник в Telegram от самого Telegram, без @. Не от модели.';
comment on column public.leads.entry_path is
  'Страница сайта, с которой начался разговор.';
comment on column public.leads.entry_ref is
  'Первый переход на сайт: хост источника или utm_source.';
