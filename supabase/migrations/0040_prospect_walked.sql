-- Обход сайта — рядом с письмом, которое по нему написано.
--
-- Менеджеры: «кнопка „отправить“ в касании не работает».
--
-- Так и было, и отказ приходил по делу — только по делу, которого менеджер
-- не совершал. Письмо пишется по промпту, куда входят строки обхода:
-- пройденные страницы, заголовок главной, число адресов в карте сайта. Там
-- же модели сказано сослаться на что-то из этого дословно — «страницу по
-- её адресу». Она и ссылается.
--
-- А перед отправкой письмо проверяется заново, и промпт для проверки
-- собирался без строк обхода: он их не хранил. Проверка «числа, которых
-- нет в анализе» видела в письме /maps/org/my_smile/6725449754 и честно
-- отбивала 6725449754 как выдуманное. Нажатие не делало ничего видимого:
-- отказ печатался вверху страницы, а якорь уводил к карточке.
--
-- Колонка закрывает разрыв: письмо и его проверка опираются на одни и те же
-- строки.
alter table public.prospects
  add column if not exists walked jsonb;

comment on column public.prospects.walked is
  'Итог обхода сайта при написании письма: страницы, заголовок, карта сайта, язык.';
