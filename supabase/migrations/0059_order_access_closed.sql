-- «Отозвать доступ к файлам» — это закрыть доступ, а не только погасить ссылки.
--
-- До сих пор отзыв поднимал entitlement_version, и выданные ссылки на
-- скачивание переставали работать. Но страница заказа покупателя при каждом
-- открытии выпускала новую ссылку уже с новой версией — то есть отозванный
-- покупатель продолжал качать, просто открыв свою страницу ещё раз.
--
-- Теперь отзыв ещё и ставит access_closed_at: страница заказа вместо кнопки
-- говорит «доступ закрыт», выдача файлов отказывает. «Вернуть доступ»
-- очищает отметку, а версию оставляет поднятой — утёкшие ссылки остаются
-- мёртвыми, а покупатель получает новую со своей страницы.
alter table public.orders
  add column if not exists access_closed_at timestamptz;

comment on column public.orders.access_closed_at is
  'Когда закрыли доступ к файлам кнопкой «отозвать доступ». Пусто — доступ открыт (если заказ оплачен).';
