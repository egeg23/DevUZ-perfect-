-- Структура статьи рядом с её текстом.
--
-- В 0021 под содержание отведены `body_ru` и `body_uz` — по одному
-- текстовому полю на язык. Страница разбора при этом показывает не сплошной
-- текст, а разобранную структуру: преамбулу абзацами, находки тройками
-- «что видит посетитель / чем оборачивается / что делаем», исход и цену.
-- Складывать это в text значит договориться о формате внутри строки и
-- разбирать его при каждом показе — то есть завести второй, никем не
-- проверяемый тип поверх первого.
--
-- Поэтому структура кладётся как jsonb, а `body_*` остаётся под простой
-- текст для тех мест, где статья нужна одним куском.
alter table public.razbors add column if not exists article_ru jsonb;
alter table public.razbors add column if not exists article_uz jsonb;

-- Потерянные обращения считаются при публикации и хранятся, а не
-- пересчитываются при каждом показе. Набор проверок растёт, и пересчёт
-- задним числом менял бы цифру в уже опубликованном тексте: читатель увидел
-- бы одно число, а вернувшись через месяц — другое, без объяснения.
alter table public.razbors add column if not exists lost_per_100 jsonb;
