-- Формы слова ниши, которой нет в каталоге.
--
-- Каталог `content/razbor/catalog.ts` описывает четырнадцать ниш готовыми
-- формами: родительный падеж для «сайт для …», узбекский корень запроса,
-- подпись, имя для макета. Это не список тех, кого мы согласны разбирать —
-- аудитор работает по любому сайту, — а материал самой страницы: без
-- падежа нет ни заголовка, ни адреса.
--
-- Стоило это ровно того, что смена молча выбрасывала каждый сайт, чья ниша
-- в каталог не попала. Включая застройщиков: классификатор их узнавал, а
-- каталога под ключ `nedvizhimost` не было вовсе.
--
-- Теперь формы спрашиваются у модели и ложатся сюда — в строку своего
-- разбора, а не в общий каталог. Второй сайт в той же нише берёт эти же
-- формы: две наши страницы под «сайт для автошколы» и «сайт для автошкол»
-- — это случай, когда Google не может выбрать и не показывает ни одну.
alter table public.razbors
  add column if not exists niche_words jsonb;

comment on column public.razbors.niche_words is
  'Формы слова ниши, если её нет в каталоге: {key, ruGen, ruLabel, uz, uzLabel, ruMock, uzMock, ruServices, uzServices}.';

-- Искать прежние формы по нише приходится на каждом разборе с нишей вне
-- каталога. Без индекса это перебор всей таблицы ради одной строки.
create index if not exists razbors_category_words_idx
  on public.razbors (category)
  where niche_words is not null;
