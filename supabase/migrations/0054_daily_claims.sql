-- Отметка «сегодняшнюю смену уже взяли».
--
-- 22 сентября смена разборов прошла дважды: она идёт двенадцать-пятнадцать
-- минут, а «сегодня уже была» узнаётся по её отчёту, который пишется в
-- самом конце. Свип ходит раз в пять минут — и следующий проход, не найдя
-- отчёта, запускал смену заново. Двойной счёт за модель и второй черновик,
-- который не записался, потому что первый уже занял тот же запрос.
--
-- Первичный ключ (job, day) делает взятие атомарным: из двух проходов
-- строку вставит один, второй получит конфликт и уйдёт.
create table if not exists public.daily_claims (
  job text not null,
  day date not null,
  claimed_at timestamptz not null default now(),
  primary key (job, day)
);

alter table public.daily_claims enable row level security;
