-- Какие сообщения бота приходят сотруднику.
--
-- Владелец, 28.09: «чтобы он [Александр] и я могли выбирать, что приходит
-- менеджерам. По умолчанию приходит всё. Но мы можем через галочки выбрать,
-- что идёт, а что нет».
--
-- Хранится список выключенного: пустой массив — приходит всё. Так новый
-- сотрудник и новый вид сообщений получают «всё» без правки каждой строки.
-- Виды и их смысл — lib/admin/notify-prefs.ts.
alter table public.staff
  add column if not exists notify_off text[] not null default '{}'::text[];

comment on column public.staff.notify_off is
  'Выключенные виды сообщений бота (lib/admin/notify-prefs.ts). Пусто — приходит всё.';
