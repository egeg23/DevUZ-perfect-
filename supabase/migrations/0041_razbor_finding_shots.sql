-- Снимки на каждую находку разбора.
--
-- До этого у разбора было четыре картинки на всю статью: первый экран сайта
-- «как есть» и наш макет «как сделали бы мы», каждый в двух размерах. Они
-- показывают, что сайт выглядит плохо, но не показывают, где именно то, о
-- чём говорит конкретная находка. А разбор держится ровно на этом: «телефон
-- на сайте нельзя нажать с телефона» — утверждение, тот же текст со снимком
-- шапки, где номер обведён, — доказательство. Читатель приходит из поиска к
-- незнакомой студии, и верить ей на слово у него причин нет.
--
-- Хранится картой «код находки → картинка»: {"tiny_text": {"path": "...",
-- "width": 1440, "height": 420}}. Код — тот же, что у находки в article_*,
-- так страница и связывает текст с картинкой.
--
-- Размеры лежат рядом с путём, а не вычисляются при показе: снимок
-- обведённого места — вырез произвольной высоты, и без честных размеров
-- страница дёргается при загрузке. Эту метрику Google меряет отдельно.
alter table public.razbors
  add column if not exists shot_findings jsonb;

comment on column public.razbors.shot_findings is
  'Снимки мест, о которых находки: код находки → {path, width, height}. Путь — в публичном бакете razbor.';

-- Бакет со снимками — публичный, и это не упущение.
--
-- Снимок «как есть» уже анонимен: имя и логотип затираются сплошными
-- плашками при съёмке, до записи файла. При этом картинки разбора — половина
-- его ценности: Google Картинки приводят на раздел отдельный трафик, а
-- картинка за подписанной ссылкой в поиск не попадает вовсе.
--
-- Личных данных здесь нет по построению: снимается публичная главная чужого
-- сайта, которую и так видит любой прохожий.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('razbor', 'razbor', true, 10485760, array['image/png', 'image/webp', 'image/jpeg'])
on conflict (id) do update
  set public = true,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;
