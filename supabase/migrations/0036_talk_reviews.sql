-- Надзиратель: разбор каждой переписки вторым проходом.
--
-- Владелец: «можно чтобы чаты в скауте мониторились арбитром или
-- надзирателем, на основании ответов клиентов строились разные подходы к
-- общению… типа самообучающаяся модель».
--
-- Самообучения в буквальном смысле здесь нет и не будет: веса модели мы не
-- трогаем. Есть другое, и оно честнее — копилка разборов. После каждого
-- закончившегося разговора вторая модель читает его целиком и отвечает на
-- четыре вопроса: что в нашем письме зацепило, какое возражение прозвучало,
-- где разговор сломался и какой отсюда урок. Уроки копятся здесь.
--
-- Почему только копятся. На день, когда таблица заводится, настоящих ответов
-- от клиентов ровно два. Вывод, сделанный из двух разговоров, — не статистика,
-- а выдумка с уверенным лицом, и подмешивать такое в промпт следующего письма
-- значит учить систему на шуме. Поэтому первый слой только показывает разборы
-- человеку; подмешивание включается отдельно и позже, когда наберётся объём.
--
-- outcome считается по базе, а не со слов модели: чем кончился разговор, мы
-- знаем точно, и спрашивать об этом ту же модель, которая его вела, незачем.
create table if not exists public.talk_reviews (
  id uuid primary key default gen_random_uuid(),
  prospect_id uuid not null references public.prospects(id) on delete cascade,
  lead_id uuid references public.leads(id) on delete set null,
  created_at timestamptz not null default now(),

  /* На каком языке шёл разговор — ru, uz или en. */
  lang text not null default 'ru',
  /* Сколько реплик клиента было. Ноль означает, что разбирать нечего. */
  turns integer not null default 0,
  /* Чем кончилось: refused, asked_human, qualified, stalled, talking. */
  outcome text not null,

  /* Что в нашем письме зацепило — словами надзирателя. */
  hook text,
  /* Какое возражение прозвучало. */
  objection text,
  /* Где разговор сломался. */
  failed text,
  /* Один урок на будущее, одной фразой. Пусто — значит учиться нечему. */
  lesson text,
  /*
   * Насколько надзиратель уверен: high или low.
   *
   * Отдельным полем, потому что разговор из одной реплики разобрать нельзя,
   * а модель, которую попросили сделать вывод, вывод сделает всегда. Низкая
   * уверенность — это разрешение не выдумывать.
   */
  confidence text not null default 'low',
  /* Ответ модели целиком: на случай, если понадобится пересчитать. */
  raw jsonb
);

-- Один разбор на переписку. Разговор продолжился — разбор переписывается, а
-- не заводится вторым: иначе в копилке окажется десять мнений об одном и том
-- же диалоге, и любой счёт по ним будет врать.
create unique index if not exists talk_reviews_one_per_prospect
  on public.talk_reviews (prospect_id);

create index if not exists talk_reviews_recent on public.talk_reviews (created_at desc);
