-- Метка последнего напоминания по заявке.
--
-- Свип ходит каждые пять минут. Без этой колонки заявка, застрявшая без
-- счёта, напоминала бы о себе двести восемьдесят восемь раз в сутки — и
-- через день чат отдела продаж выключили бы совсем, вместе с брифами
-- настоящих лидов.
--
-- Здесь лежит имя стадии, о которой уже сказали. Каждая стадия
-- («ждёт счёта», «счёт просрочен 14 дней», «оплачено, а релиза нет»)
-- проговаривается один раз; следующая стадия — это новое событие, и о нём
-- говорят снова.

alter table public.orders
  add column if not exists last_nudged_stage text,
  add column if not exists last_nudged_at timestamptz;

comment on column public.orders.last_nudged_stage is
  'Стадия, о которой свип уже напомнил. Каждая стадия проговаривается один раз.';

-- Свип выбирает незакрытые заявки и смотрит на даты. Частичный индекс:
-- отменённые и переданные его не интересуют никогда.
create index if not exists orders_sweep_idx
  on public.orders (status, created_at)
  where status in ('new', 'invoiced', 'paid');
