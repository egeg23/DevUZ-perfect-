-- Просьба о передаче лида — с кнопками прямо в Telegram.
--
-- Руководителю и владельцу просьба приходила текстом «подтвердите на
-- странице лида в панели» — без кнопок и даже без ссылки на лид. Решать её
-- приходилось, найдя лид в панели руками. Теперь под сообщением «Подтвердить»
-- и «Отклонить», а после решения кнопки у всех, кому пришла просьба,
-- меняются на «Подтвердил …» — иначе второй нажал бы по уже решённой.
--
-- Для этого просьба помнит, куда её отправили: пары (чат, сообщение).
alter table public.lead_transfers
  add column if not exists notices jsonb not null default '[]'::jsonb;

comment on column public.lead_transfers.notices is
  'Сообщения с кнопками решения: [{chatId, messageId}]. По ним после решения кнопки меняются на итог у всех, кому пришла просьба.';
