-- Меню панели: новое (группами) или как раньше (одной строкой).
--
-- Владелец, 13.10.2026: «Открой всем менеджерам новую панель… но также
-- сделай возможность оставить как сейчас тумблером». По умолчанию —
-- новое меню; тумблер «Новое меню» в шапке переключает его себе.
--
-- Колонка в staff, а не кука браузера — как язык панели: выбор один на
-- человека, а не на ноутбук.
alter table public.staff
  add column if not exists nav_classic boolean not null default false;

comment on column public.staff.nav_classic is
  'true — меню панели одной строкой, как до 12.10.2026; false — группами. Меняет сам сотрудник тумблером в шапке.';
