-- Куда и под каким номером ушла карточка лида.
--
-- Карточка нового лида уходит не в один чат, а всей команде — каждому в
-- личку. Кнопка «Взять в работу» при этом меняла надпись только там, где её
-- нажали: у остальных карточка оставалась с живыми кнопками, и о том, что
-- лид уже занят, человек узнавал, только нажав. А иногда — уже начав писать
-- клиенту.
--
-- Чтобы переписать все копии, надо знать, где они лежат. Telegram этого не
-- помнит за нас: правка сообщения требует чат и номер, и взять их можно
-- только из ответа на отправку.
--
-- Отдельной таблицей, а не полем у лида: по одному лиду карточка уходит не
-- раз — на повторное обращение клиента бот шлёт её снова, — и дописывать в
-- общий массив из двух мест значило бы терять копии на гонке.
create table if not exists public.lead_notices (
  lead_id uuid not null references public.leads(id) on delete cascade,
  chat_id text not null,
  message_id bigint not null,
  created_at timestamptz not null default now(),
  primary key (lead_id, chat_id, message_id)
);

comment on table public.lead_notices is
  'Копии карточки лида в Telegram: чат и номер сообщения. Нужны, чтобы после взятия лида переписать кнопки у всех, а не только у нажавшего.';

-- Читает и пишет только сервер: номер сообщения в чужом личном чате — не
-- то, что стоит отдавать наружу.
alter table public.lead_notices enable row level security;
