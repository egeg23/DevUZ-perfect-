-- Здоровье свипа и счётчик попыток доставки.
--
-- До этой миграции свип напоминаний ломался молча. Не доехала переменная
-- окружения, упал прокси, сменился секрет — напоминания просто перестают
-- приходить, и узнают об этом по остывшему лиду через неделю. Тишина
-- неотличима от «напоминать было нечего», и это худшее свойство, какое
-- может быть у механизма, который существует ради того, чтобы о лиде не
-- забыли.
--
-- Вторая половина — счётчик попыток. Сейчас пометка «отправлено» ставится
-- только после успеха, и это правильно: иначе первый же сбой Telegram
-- съедал бы напоминание навсегда. Но обратная сторона в том, что
-- недоставляемое напоминание — например, менеджер заблокировал бота —
-- пересылается каждые пять минут вечно.

-- ---------------------------------------------------- stats_snapshots
create table if not exists public.stats_snapshots (
  key text primary key,
  payload jsonb not null default '{}'::jsonb,
  computed_at timestamptz not null default now()
);

comment on table public.stats_snapshots is
  'Посчитанные значения, которые дешевле хранить, чем пересчитывать. Ключ sweep_health пишет свип напоминаний.';

alter table public.stats_snapshots enable row level security;

-- ---------------------------------------------------- lead_reminders
alter table public.lead_reminders
  add column if not exists attempts integer not null default 0,
  add column if not exists last_attempt_at timestamptz;

comment on column public.lead_reminders.attempts is
  'Сколько раз свип пытался доставить. Упёршись в предел, он перестаёт пробовать, а панель показывает напоминание как недоставленное — вместо того чтобы молча слать его вечно.';
