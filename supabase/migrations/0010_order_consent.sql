-- Согласие с офертой, записанное вместе с заявкой.
--
-- Без этих двух колонок «покупатель принял оферту» недоказуемо. Галочка в
-- форме доказывает только то, что галочка была в форме: текст на сайте
-- меняется, заявка лежит с прошлого года, и какой именно редакции
-- покупатель говорил «да», установить нечем. Оферта — это договор, который
-- заключается без подписи, и версия здесь заменяет подпись.
--
-- Колонки nullable: заявки, поданные до этой миграции, согласия не несут, и
-- проставлять им версию задним числом значило бы записать в базу неправду.
-- Пустое значение честно говорит «неизвестно».

alter table public.orders
  add column if not exists offer_version text,
  add column if not exists offer_accepted_at timestamptz;

comment on column public.orders.offer_version is
  'Редакция оферты и лицензии, с которой согласился покупатель. NULL — заявка старше введения согласия.';
comment on column public.orders.offer_accepted_at is
  'Когда покупатель нажал согласие. Отдельно от created_at: заявку может создать и менеджер руками.';
