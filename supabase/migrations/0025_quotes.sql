-- Смета для менеджера.
--
-- projects.quote — выбор менеджера: категория калькулятора, допы и
-- обещанный срок. Сама вилка не хранится: она считается из этого выбора и
-- прайса в коде, иначе правка прайса оставила бы старые цифры в карточках.
--
-- leads.brief — бриф с витрины как есть, структурой. До этого он жил
-- только пересказом в summary, и смету по нему можно было собрать лишь
-- разбором текста.
alter table public.projects add column if not exists quote jsonb;
alter table public.leads add column if not exists brief jsonb;
