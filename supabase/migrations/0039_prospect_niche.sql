-- Ниша адресата — рядом с его письмом.
--
-- Владелец: «MAVERA идёт в пример логистики, странно. Это же застройщик».
--
-- Ниша определялась при написании письма — углублённым разбором сайта — и
-- тут же терялась: в строке проспекта её не было. Из-за этого проверка
-- письма перед отправкой пересчитывала наш проект «в его нише», не зная
-- ниши вовсе, и молча не находила ничего: правило «назови наш проект из
-- его ниши» существовало, но не срабатывало никогда.
--
-- Колонка закрывает разрыв. Заодно менеджер видит в карточке, кем мы
-- считаем адресата, — и может поправить нас раньше, чем письмо уйдёт.
alter table public.prospects
  add column if not exists niche text;

comment on column public.prospects.niche is
  'Ниша адресата по классификатору — та, по которой подбирался наш пример.';
