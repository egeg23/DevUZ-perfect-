-- Доказательство доставки: сообщение действительно лежит в переписке.
--
-- Владелец: «после того как отправилось — делай проверку, что с нашего
-- аккаунта реально ушло сообщение».
--
-- Ответ Telegram на отправку означает только, что сервер запрос принял. Это
-- не то же самое, что «письмо у адресата в переписке»: сообщение может быть
-- снято антиспамом сразу после приёма, а у заблокировавшего нас оно исчезает
-- молча. Разница видна ровно одним способом — перечитать переписку и найти
-- в ней своё сообщение по id.
--
-- Отсюда три колонки.
--
-- sent_message_id — что вернул Telegram при отправке. По нему и ищем: не «в
-- переписке что-то есть», а «в переписке есть именно это».
--
-- delivered_at — когда перечитали и нашли. Пусто при статусе 'sent' значит
-- «отправили, но подтвердить не смогли», и это другая новость, чем «ушло».
--
-- delivery_note — почему не подтвердилось, словами менеджера. Пусто —
-- значит подтвердилось.
alter table public.prospects
  add column if not exists sent_message_id bigint,
  add column if not exists delivered_at timestamptz,
  add column if not exists delivery_note text;

-- Уже отправленным ничего не проставляем задним числом.
--
-- Соблазн написать delivered_at = sent_at велик и ровно поэтому его здесь
-- нет: это выдало бы непроверенное за проверенное, а вся колонка заводится
-- как раз чтобы отличать одно от другого. Старые строки останутся без
-- отметки — так и есть на самом деле.
