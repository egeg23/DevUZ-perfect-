-- Нерабочее время: равная доля вместо получаса на человека.
--
-- Владелец: «вне рабочих часов, с 18:00 до 08:00 по Ташкенту, правило
-- получаса не действует: тут работает система равного распределения, и
-- взять лида можно, но не больше, чем будет при равном распределении между
-- всеми участниками».
--
-- Ночью предлагать лид по очереди некому: полчаса у каждого спящего — это
-- три с половиной часа, за которые клиент напишет в другую студию. Поэтому
-- ночной лид открыт сразу всем в очереди, а от того, чтобы его забрал один
-- неспящий «ушлый», держит потолок: не больше равной доли за месяц.
--
-- Флаг у лида, а не проверка часов при нажатии: лид, пришедший в 23:00 и
-- не взятый до утра, остаётся ночным и в 9:00 — очередь по нему не
-- начиналась, и начинать её задним числом значило бы снова держать его
-- полчаса у каждого.
alter table public.leads
  add column if not exists fair_share boolean not null default false;

comment on column public.leads.fair_share is
  'Лид пришёл или открылся в нерабочее время: взять его может любой в очереди, но не больше равной доли за месяц.';
