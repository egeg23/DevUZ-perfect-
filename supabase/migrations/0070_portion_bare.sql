-- Карточка порции или потока ушла в Telegram без текста.
--
-- 1 октября на ключе модели кончились деньги: утренняя порция и поток
-- ушли менеджерам карточками «Текст ещё готовится», а писать их заново
-- было некому — подготовка письма второй попытки не делала. Теперь отказ
-- модели (деньги, ключ, частота, недоступность) возвращает письмо в
-- очередь подготовки, а эта отметка говорит свипу: карточка уже у
-- человека, текст дошли отдельным сообщением, как только он будет готов.
-- Дошли — отметка снимается.
alter table public.touch_portions
  add column if not exists bare_at timestamptz;

comment on column public.touch_portions.bare_at is
  'Карточка ушла в Telegram без текста. Свип дошлёт текст, когда модель его напишет, и снимет отметку.';
