/**
 * Сумма прописью — чтобы цифру нельзя было «поправить» после подписания.
 *
 * Склонение «тысяча / тысячи / тысяч» вынесено отдельной функцией не ради
 * красоты: правило имеет исключение на 11–14, и записанное одним тернарным
 * выражением оно читается неверно даже автором. В договоре это тот случай,
 * когда «двадцать одна тысяч долларов» стоит дороже, чем выглядит.
 */
function plural(n: number, one: string, few: string, many: string): string {
  const mod100 = n % 100;
  if (mod100 >= 11 && mod100 <= 14) return many;
  const mod10 = n % 10;
  if (mod10 === 1) return one;
  if (mod10 >= 2 && mod10 <= 4) return few;
  return many;
}

const ONES = ["", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"];
const TEENS = ["десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать", "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать"];
const TENS = ["", "", "двадцать", "тридцать", "сорок", "пятьдесят", "шестьдесят", "семьдесят", "восемьдесят", "девяносто"];
const HUNDREDS = ["", "сто", "двести", "триста", "четыреста", "пятьсот", "шестьсот", "семьсот", "восемьсот", "девятьсот"];

/** Трёхзначная группа прописью. `feminine` — для тысяч: «одна», «две». */
function trio(value: number, feminine = false): string {
  if (value === 0) return "";
  const parts: string[] = [];
  let rest = value;
  if (rest >= 100) { parts.push(HUNDREDS[Math.floor(rest / 100)]); rest %= 100; }
  if (rest >= 20) { parts.push(TENS[Math.floor(rest / 10)]); rest %= 10; }
  else if (rest >= 10) { parts.push(TEENS[rest - 10]); rest = 0; }
  if (rest > 0) {
    parts.push(feminine && rest === 1 ? "одна" : feminine && rest === 2 ? "две" : ONES[rest]);
  }
  return parts.join(" ");
}

export function amountInWords(amount: number): string {
  const whole = Math.floor(Math.abs(amount));
  if (whole === 0) return "ноль";
  // Миллионы в договоре студии не встречаются, но молча обрезать их нельзя:
  // цифра и пропись разойдутся, и спорить будут о прописи.
  if (whole >= 1_000_000) {
    const mil = Math.floor(whole / 1_000_000);
    const rest = whole % 1_000_000;
    const head = `${trio(mil)} ${plural(mil, "миллион", "миллиона", "миллионов")}`;
    return rest > 0 ? `${head} ${amountInWords(rest)}` : head;
  }
  const th = Math.floor(whole / 1000);
  const rest = whole % 1000;
  const chunks: string[] = [];
  if (th > 0) chunks.push(`${trio(th, true)} ${plural(th, "тысяча", "тысячи", "тысяч")}`);
  if (rest > 0) chunks.push(trio(rest));
  return chunks.join(" ");
}

