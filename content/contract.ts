/**
 * Договор на разработку от ИП в сторону заказчика.
 *
 * ── Чего этот документ не заменяет ──────────────────────────────────────
 *
 * Проверки юристом. Текст составлен по обычной практике договоров подряда
 * на разработку, но право Узбекистана, регистрация арбитражной оговорки и
 * формулировки по НДС — то, что должен один раз посмотреть человек с
 * лицензией. Пока этого не произошло, документ помечен как черновик и
 * владелец видит об этом строку на странице договора.
 *
 * ── Что здесь защищает и от чего ────────────────────────────────────────
 *
 * Владелец сформулировал риск так: разработка стоила $10 000, а решение
 * суда в Узбекистане можно купить дешевле. Значит, выгодно взыскать
 * стоимость работ плюс неустойку. Против этого работают четыре вещи, и
 * только одна из них про текст:
 *
 * 1. Арбитражная оговорка (§10). Спор уходит из суда общей юрисдикции в
 *    арбитраж. Это главное условие всего договора: оно меняет не аргументы,
 *    а того, кто их слушает. Состав арбитров дороже и сложнее, чем районный
 *    судья, и сам факт оговорки убирает расчёт на «дешёвое решение».
 * 2. Потолок ответственности (§9): фактически полученное по договору.
 *    Даже проигранный спор не может стоить больше, чем пришло.
 * 3. Исключение упущенной выгоды (§9). Именно ею раздувают иск с $10 000
 *    до суммы, которой никто никогда не видел.
 * 4. Потолок неустойки (§9). Без него неустойка растёт линейно и за год
 *    превышает сумму договора.
 *
 * Остальное — приёмка, встречные обязательства, права на код — не про суд,
 * а про то, чтобы до суда не дошло.
 *
 * ── Чего здесь намеренно нет ────────────────────────────────────────────
 *
 * Запутанных формулировок. Владелец просил написать так, чтобы защиту
 * разглядел только очень грамотный юрист. Так делать нельзя, и не из
 * осторожности: неясное условие толкуется против того, кто составил
 * договор, а условие, которого сторона объективно не могла понять,
 * снимается первым. Туман защищает ровно до первого спора, то есть до того
 * момента, ради которого он писался. Поэтому каждое условие сформулировано
 * однозначно — читается тяжело, но толкуется одним способом.
 */

export type ContractStage = {
  /** «Дизайн», «Вёрстка и админка», «Запуск». */
  title: string;
  /** Доля от суммы договора, проценты. Сумма долей обязана давать 100. */
  percent: number;
  /** Срок в рабочих днях от начала этапа. */
  workdays: number;
};

export type ContractInput = {
  number: string;
  /** ISO-дата подписания. */
  date: string;
  client: {
    name: string;
    /** Реквизиты заказчика одной строкой: адрес, ИНН/ПИНФЛ, банк. */
    details: string;
  };
  /** Предмет: что именно делаем. Одно предложение, без воды. */
  subject: string;
  amountUsd: number;
  stages: readonly ContractStage[];
  /**
   * Позиции согласованной сметы.
   *
   * Печатаются в самом договоре, а не только прикладываются файлом.
   * Ссылаться на вложение, которого читатель не видит, значит получить спор
   * о его содержании — а смета это то единственное, о чём спорят чаще
   * сроков.
   */
  estimate?: readonly EstimateLine[];
  /** Согласованный срок словами: «60 рабочих дней с даты аванса». */
  deadline?: string;
};

