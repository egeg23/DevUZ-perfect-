export const BOX_NAME = "DevUz Box";

/** Система внутри коробки. Тоже рабочее имя, в текстах через {os}. */
export const BOX_OS = "DevUz OS";

/** Адрес промо-страницы: /{язык}/box. */
export const BOX_PATH = "box";

/** Месяц и год запуска продаж по плану. */
export const BOX_LAUNCH = { month: 10, year: 2027 } as const;

/** Папка картинок в public/. Собирает scripts/box/assets.py. */
export const BOX_IMG = "/box";

export type BoxModelKey = "lite" | "pro" | "premium" | "jarvis";

/**
 * Кадры разреза: горизонтальные слои одного кадра 1920×1086 из презентации.
 * `stage` — ширина и высота стопки в пикселях кадра, `rows` — верх и низ
 * каждого слоя; компонент раскладывает слои по этим числам, а файлы
 * `<model>-l<N>.webp` (980 px) и `-s` (520 px) режет скрипт.
 *
 * Число слоёв — настоящее: столько деталей в кадре, столько и подписей.
 */
export const BOX_CUTS: Record<"lite" | "pro" | "jarvis", { stage: [number, number]; rows: [number, number][] }> = {
  pro: { stage: [980, 1040], rows: [[20, 195], [195, 340], [340, 490], [490, 598], [598, 740], [740, 850], [850, 1060]] },
  lite: { stage: [840, 980], rows: [[40, 225], [225, 340], [340, 530], [530, 640], [640, 815], [815, 1020]] },
  jarvis: { stage: [980, 1050], rows: [[20, 100], [100, 270], [270, 350], [350, 500], [500, 670], [670, 840], [840, 1070]] },
};

export function boxLayerCount(model: keyof typeof BOX_CUTS): number {
  return BOX_CUTS[model].rows.length;
}

/** Собранные коробки: файл и пропорции кадра. */
export const BOX_SHOTS: Record<"lite" | "pro" | "jarvis", { w: number; h: number }> = {
  pro: { w: 1320, h: 880 },
  lite: { w: 1320, h: 880 },
  jarvis: { w: 1080, h: 1040 },
};

/**
 * Экраны системы на промо-странице: концепт интерфейса, файлы
 * `public/box/os-<key>.webp` (кадр 1344×752) и `-s` (800 px); подписи в словаре
 * (`box.os.screens`) идут тем же порядком.
 */
export const BOX_OS_SCREENS = ["desktop", "studio", "inbox", "code"] as const;

/** Подставить имена коробки и системы в строку словаря. */
export function named(text: string): string {
  return text.replaceAll("{name}", BOX_NAME).replaceAll("{os}", BOX_OS);
}
