/** Страна по адресу страницы. */
export function marketOf(slug: string): Market | null {
  return MARKETS.find((market) => market.slug === slug) ?? null;
}

/** Площадки страны по видам, в порядке RESOURCE_KINDS; пустые виды — без заголовка. */
export function resourcesByKind(market: Market): { kind: ResourceKind; items: MarketResource[] }[] {
  return RESOURCE_KINDS.map((kind) => ({ kind, items: market.resources.filter((item) => item.kind === kind) })).filter(
    (group) => group.items.length > 0,
  );
}
