/** Трюк по умолчанию для модели — если у ниши своего нет. */
export const MODEL_TRICK: Record<ProtoModel, string> = {
  booking: "clock",
};

export function trickFor(niche: ProtoNiche): string {
  return niche.trick ?? MODEL_TRICK[niche.model];
}
