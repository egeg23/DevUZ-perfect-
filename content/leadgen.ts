/** Цена лида по тарифу: от и до, в рублях, округлено до десятков. */
export function perLead(t: LeadgenTariff): readonly [number, number] | null {
  if (t.price === null || t.leads === null) return null;
  const round = (n: number) => Math.round(n / 10) * 10;
  return [round(t.price / t.leads[1]), round(t.price / t.leads[0])];
}

export function rub(n: number): string {
  return `${n.toLocaleString("ru-RU").replace(/ /g, " ")} ₽`;
}

