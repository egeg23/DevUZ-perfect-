/**
 * Сколько обращений сайт теряет на найденных местах.
 *
 * Это самая опасная часть разбора, поэтому правила здесь жёстче, чем везде.
 *
 * Считаем ПОТЕРИ, а не прирост. «Переделка поднимет заявки на 40 %» —
 * обещание, которого никто не может сдержать: заявки зависят от рекламы,
 * сезона, цен и очереди в сервисе. «На этих пяти пунктах из ста человек,
 * готовых обратиться, до вас не доходят примерно двадцать» — утверждение о
 * текущем состоянии сайта, и оно проверяемо: уберите пункт и посмотрите.
 *
 * Считаем на сто посетителей, а не в месяц. Трафика чужого сайта мы не
 * знаем и знать не можем; подставить туда выдуманное «обычно 500 визитов» —
 * ровно та ложь, за которую мы в разборах и ругаем. Сто — единица измерения,
 * а не оценка посещаемости. Когда человек приходит в аудитор со СВОИМ
 * сайтом, он может назвать свою посещаемость сам, и тогда `scaleTo` считает
 * в обращениях в месяц — но это уже его число, а не наше.
 *
 * Доли — допущения студии, и они названы допущениями прямо в тексте
 * страницы. Студия, которая показывает, из чего считала, вызывает больше
 * доверия, чем студия с красивой цифрой без вывода. Менять их можно, но
 * только всем вместе и с объяснением: подогнать одну долю под нужный
 * результат конкретного разбора — значит начать торговать цифрами.
 */
import type { Finding } from "@/lib/audit/checks";

/** Доля теряемых обращений: [нижняя, верхняя]. */
export type Band = readonly [number, number];

/**
 * Сколько людей, уже готовых обратиться, теряется на каждой находке.
 *
 * Границы разведены широко намеренно. Узкий диапазон выглядит точным
 * замером, которым он не является; широкий честно показывает, что это
 * оценка. Верхняя граница — когда находка бьёт по главному пути к заявке,
 * нижняя — когда есть обходные пути.
 */
const LOSS: Record<string, Band> = {
  // Сайт не работает. Теряется практически всё.
  unreachable: [0.9, 1],
  http_error: [0.9, 1],

  // Путь к обращению перекрыт целиком.
  no_phone: [0.25, 0.45],
  no_viewport: [0.3, 0.5],

  // Перекрыт частично: способ связи есть, но неудобный или не тот.
  phone_not_clickable: [0.05, 0.12],
  no_messenger: [0.1, 0.2],

  // Человек не получает ответа на главный вопрос и уходит сравнивать.
  no_prices: [0.15, 0.3],

  // Доверие.
  no_https: [0.1, 0.25],
  cert_expiring: [0.05, 0.2],
  mixed_content: [0.03, 0.1],
  slow: [0.05, 0.15],

  // Видимость: человек не доходит до сайта вовсе.
  no_title: [0.05, 0.15],
  one_language: [0.05, 0.15],
  no_og: [0.03, 0.08],
  img_no_alt: [0.02, 0.06],
  no_schema: [0.02, 0.05],
  no_description: [0.02, 0.05],
  no_h1: [0.02, 0.05],
};

/** Находка, для которой доли нет, в расчёт не идёт — молча и намеренно. */
export function lossFor(code: string): Band | null {
  return LOSS[code] ?? null;
}

export type Forecast = {
  /** Скольких из ста теряем: нижняя и верхняя граница, целые. */
  lostPer100: readonly [number, number];
  /** Коды находок, попавшие в расчёт. */
  counted: readonly string[];
  /** Находки без доли — их в расчёте нет. */
  skipped: readonly string[];
};

/**
 * Складывает потери так, как они складываются в жизни.
 *
 * Не суммой. Человек, ушедший из-за того, что не нашёл телефона, не уйдёт
 * второй раз из-за отсутствия цены — он уже ушёл. Сумма пяти находок по
 * 25 % дала бы 125 %, то есть больше, чем людей вообще было.
 *
 * Поэтому считаем через тех, кто дошёл: каждая находка оставляет свою долю
 * дошедших, доли перемножаются, потеря — это остаток до единицы.
 */
export function forecast(findings: readonly Pick<Finding, "code">[]): Forecast {
  const counted: string[] = [];
  const skipped: string[] = [];
  let survivesLow = 1;
  let survivesHigh = 1;

  for (const finding of findings) {
    const band = lossFor(finding.code);
    if (!band) {
      skipped.push(finding.code);
      continue;
    }
    // Одна и та же находка дважды потерь не удваивает.
    if (counted.includes(finding.code)) continue;
    counted.push(finding.code);
    survivesLow *= 1 - band[0];
    survivesHigh *= 1 - band[1];
  }

  if (counted.length === 0) return { lostPer100: [0, 0], counted, skipped };

  return {
    lostPer100: [Math.round((1 - survivesLow) * 100), Math.round((1 - survivesHigh) * 100)],
    counted,
    skipped,
  };
}

/**
 * Пересчёт на посещаемость, которую назвал сам владелец сайта.
 *
 * Только для аудитора, где человек проверяет свой сайт и знает своё число.
 * В разборе чужого сайта этой функции делать нечего.
 */
export function scaleTo(result: Forecast, visitorsPerMonth: number): readonly [number, number] {
  if (!Number.isFinite(visitorsPerMonth) || visitorsPerMonth <= 0) return [0, 0];
  const k = visitorsPerMonth / 100;
  return [Math.round(result.lostPer100[0] * k), Math.round(result.lostPer100[1] * k)];
}
