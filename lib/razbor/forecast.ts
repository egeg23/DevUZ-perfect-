/**
 * Сколько обращений сайт теряет на найденных местах.
 *
 * Это самая опасная часть разбора, поэтому правила здесь жёстче, чем везде.
 *
 * Считаем ПОТЕРИ, а не прирост. «Переделка поднимет заявки на 40 %» —
 * обещание, которого никто не может сдержать: заявки зависят от рекламы,
 * сезона, цен и очереди в сервисе. «На этих пяти пунктах из ста человек,
 * готовых обратиться, до вас не доходят примерно двадцать» — утверждение о
 * текущем состоянии сайта, и оно проверяемо: уберите пункт и посмотрите.
 *
 * Считаем на сто готовых обратиться, а не в месяц. Трафика чужого сайта мы
 * не знаем и знать не можем; подставить туда выдуманное «обычно 500
 * визитов» — ровно та ложь, за которую мы в разборах и ругаем. Сто — единица
 * измерения, а не оценка посещаемости.
 *
 * Когда человек приходит в аудитор со СВОИМ сайтом, он называет не трафик, а
 * обращения в месяц, и `lostBesides` считает, сколько теряется сверх них.
 * Именно обращения, а не посетителей: доля посчитана от готовых обратиться,
 * и умножение её на всю посещаемость завышает результат. Обращения владелец
 * знает точно и без аналитики.
 *
 * Доли — допущения студии, и они названы допущениями прямо в тексте
 * страницы. Студия, которая показывает, из чего считала, вызывает больше
 * доверия, чем студия с красивой цифрой без вывода. Менять их можно, но
 * только всем вместе и с объяснением: подогнать одну долю под нужный
 * результат конкретного разбора — значит начать торговать цифрами.
 */
import type { Finding } from "@/lib/audit/checks";

/** Доля теряемых обращений: [нижняя, верхняя]. */
export type Band = readonly [number, number];

/**
 * Сколько людей, уже готовых обратиться, теряется на каждой находке.
 *
 * Границы разведены широко намеренно. Узкий диапазон выглядит точным
 * замером, которым он не является; широкий честно показывает, что это
 * оценка. Верхняя граница — когда находка бьёт по главному пути к заявке,
 * нижняя — когда есть обходные пути.
 */
const LOSS: Record<string, Band> = {
  // Сайт не работает. Теряется практически всё.
  unreachable: [0.9, 1],
  http_error: [0.9, 1],

  // Путь к обращению перекрыт целиком.
  no_phone: [0.25, 0.45],
  no_viewport: [0.3, 0.5],

  // Перекрыт частично: способ связи есть, но неудобный или не тот.
  phone_not_clickable: [0.05, 0.12],
  no_messenger: [0.1, 0.2],

  // Человек не получает ответа на главный вопрос и уходит сравнивать.
  no_prices: [0.15, 0.3],

  // Доверие.
  no_https: [0.1, 0.25],
  cert_expiring: [0.05, 0.2],
  mixed_content: [0.03, 0.1],
  slow: [0.05, 0.15],

  // Видимость: человек не доходит до сайта вовсе.
  no_title: [0.05, 0.15],
  one_language: [0.05, 0.15],
  no_og: [0.03, 0.08],
  img_no_alt: [0.02, 0.06],
  no_schema: [0.02, 0.05],
  no_description: [0.02, 0.05],
  no_h1: [0.02, 0.05],

  // Вёрстка и следы раннего интернета. Битые файлы и заглушки бьют по
  // доверию сразу; устаревшая вёрстка — по первому впечатлению, но
  // человек ещё может дочитать.
  under_construction: [0.5, 0.8],
  broken_links: [0.15, 0.35],
  broken_images: [0.1, 0.25],
  placeholder_text: [0.1, 0.25],
  frames: [0.15, 0.3],
  flash: [0.1, 0.25],
  ancient_layout: [0.15, 0.3],
  no_responsive_css: [0.15, 0.3],
  dated_layout: [0.05, 0.15],
  autoplay_sound: [0.05, 0.15],
  popup_onload: [0.03, 0.1],
  zoom_locked: [0.02, 0.06],
  stale_copyright: [0.03, 0.08],
  marquee: [0.02, 0.06],
  visitor_counter: [0.01, 0.04],
  ie_only: [0.02, 0.05],
  ancient_scripts: [0.02, 0.06],
  no_favicon: [0.01, 0.03],

  // Глазами дизайнера: не «некрасиво», а «неудобно читать и нажимать».
  horizontal_scroll: [0.15, 0.3],
  tiny_text: [0.05, 0.12],
  wall_of_text: [0.04, 0.1],
  font_zoo: [0.02, 0.05],
};

/** Находка, для которой доли нет, в расчёт не идёт — молча и намеренно. */
export function lossFor(code: string): Band | null {
  return LOSS[code] ?? null;
}

export type Forecast = {
  /** Скольких из ста теряем: нижняя и верхняя граница, целые. */
  lostPer100: readonly [number, number];
  /** Коды находок, попавшие в расчёт. */
  counted: readonly string[];
  /** Находки без доли — их в расчёте нет. */
  skipped: readonly string[];
};

/**
 * Складывает потери так, как они складываются в жизни.
 *
 * Не суммой. Человек, ушедший из-за того, что не нашёл телефона, не уйдёт
 * второй раз из-за отсутствия цены — он уже ушёл. Сумма пяти находок по
 * 25 % дала бы 125 %, то есть больше, чем людей вообще было.
 *
 * Поэтому считаем через тех, кто дошёл: каждая находка оставляет свою долю
 * дошедших, доли перемножаются, потеря — это остаток до единицы.
 */
export function forecast(findings: readonly Pick<Finding, "code">[]): Forecast {
  const counted: string[] = [];
  const skipped: string[] = [];
  let survivesLow = 1;
  let survivesHigh = 1;

  for (const finding of findings) {
    const band = lossFor(finding.code);
    if (!band) {
      skipped.push(finding.code);
      continue;
    }
    // Одна и та же находка дважды потерь не удваивает.
    if (counted.includes(finding.code)) continue;
    counted.push(finding.code);
    survivesLow *= 1 - band[0];
    survivesHigh *= 1 - band[1];
  }

  if (counted.length === 0) return { lostPer100: [0, 0], counted, skipped };

  return {
    lostPer100: [Math.round((1 - survivesLow) * 100), Math.round((1 - survivesHigh) * 100)],
    counted,
    skipped,
  };
}

/**
 * Сколько обращений теряется сверх тех, что вы получаете.
 *
 * Первая версия этой функции умножала посещаемость на долю потерь — и была
 * неправа. Доля посчитана от тех, кто ГОТОВ обратиться, а посещаемость
 * считает всех подряд, включая случайных. Умножение одного на другое даёт
 * число заметно больше настоящего, и оспорить его смог бы любой владелец с
 * доступом к своей статистике.
 *
 * Поэтому спрашиваем не трафик, а обращения — число, которое владелец знает
 * точно и без аналитики. Дальше чистая арифметика: если из ста готовых
 * доходят (100 − p), то полученные N обращений — это и есть те дошедшие,
 * а потерянные к ним относятся как p к (100 − p).
 *
 * Никаких новых допущений здесь не появляется: всё уже заложено в долях.
 */
export function lostBesides(
  result: Forecast,
  enquiriesPerMonth: number,
): readonly [number, number] {
  if (!Number.isFinite(enquiriesPerMonth) || enquiriesPerMonth <= 0) return [0, 0];

  const share = (lost: number) => (enquiriesPerMonth * lost) / (100 - lost);

  // Сайт, теряющий все сто, обращений не даёт вовсе — делить не на что, и
  // деление честно возвращает бесконечность. Отдельной проверки на сотню
  // здесь стояла и была мёртвой: до этой строки не доходило ни одно
  // значение, которое `isFinite` не отсеял бы сам. Мутация это и показала.
  const low = share(result.lostPer100[0]);
  const high = share(result.lostPer100[1]);
  return [
    Number.isFinite(low) ? Math.round(low) : 0,
    Number.isFinite(high) ? Math.round(high) : 0,
  ];
}
