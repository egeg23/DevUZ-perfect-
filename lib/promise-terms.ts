/**
 * Условия гарантии — одно место для сервера и браузера.
 *
 * Отсчёт идёт на клиенте, а решение придержать ответ принимает сервер.
 * Разъехавшиеся числа означали бы, что человек видит «осталось 0», а скидка
 * не приходит, — то есть публичное обещание нарушено на глазах у клиента.
 * Модуль намеренно без зависимостей, чтобы его можно было импортировать
 * и в серверный код, и в клиентский компонент.
 */

/** Сколько секунд обещано клиенту на первый ответ. */
export const PROMISE_SECONDS = 20;

/** Размер скидки при несработавшей гарантии, в процентах. */
export const PROMISE_DISCOUNT = 30;

/**
 * За что выдана скидка 30%.
 *
 * `promise` — не уложились в двадцать секунд ответа. `minute` — человек
 * написал ассистенту в первую минуту на сайте, пока шёл таймер. Скидка одна
 * и та же и не складывается: причина нужна менеджеру (что сказать клиенту)
 * и владельцу (во что обходится каждая из двух механик).
 */
export type DiscountReason = "promise" | "minute";
