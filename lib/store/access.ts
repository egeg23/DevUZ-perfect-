import { createHash, randomBytes } from "node:crypto";

/**
 * Ссылка на страницу заказа.
 *
 * Покупателю нужен доступ ровно к одной покупке, и заводить под это логин с
 * паролем значит придумать человеку работу там, где её можно не придумывать:
 * пароль к одному заказу никто не запомнит, а «восстановить пароль» без
 * подтверждённой почты всё равно упрётся в живого менеджера.
 *
 * Поэтому доступ — неугадываемая ссылка. Требования к ней ровно два, и оба
 * выполняются здесь:
 *
 * 1. Перебор бесполезен. 32 случайных байта — это 256 бит; ограничение по
 *    скорости на маршруте нужно от шума, а не от перебора, потому что
 *    перебирать такое пространство нечем.
 * 2. Дамп базы не открывает чужие заказы. В базе лежит sha256, восстановить
 *    из него токен нельзя. Соль не нужна и была бы вредна: у токена нет
 *    словаря, а соль сломала бы поиск по индексу — пришлось бы читать все
 *    строки и хешировать каждую.
 */

/** Токен для ссылки. base64url, 43 знака, ничего не требует экранировать. */
export function newAccessToken(): string {
  return randomBytes(32).toString("base64url");
}

/** То, что уходит в базу. hex, потому что колонка text и её читают глазами. */
export function hashAccessToken(token: string): string {
  return createHash("sha256").update(token, "utf8").digest("hex");
}

/**
 * Похоже ли это вообще на токен.
 *
 * Дешёвая отсечка перед походом в базу: мусорные пути вроде /order/favicon.ico
 * приходят постоянно, и каждый такой запрос не обязан стоить нам запроса к
 * Supabase.
 */
export function looksLikeAccessToken(value: string): boolean {
  return /^[A-Za-z0-9_-]{43}$/.test(value);
}

/**
 * Код для диплинка Telegram.
 *
 * Короче токена страницы (16 байт против 32) намеренно: payload у `/start`
 * ограничен 64 знаками, а с префиксом `order_` в них надо уложиться вместе
 * с ним. Шестнадцати случайных байт для одноразового кода более чем
 * достаточно — подбирать его нечем и незачем, он гаснет при первом же
 * использовании.
 */
export function newBindCode(): string {
  return randomBytes(16).toString("base64url");
}

export function looksLikeBindCode(value: string): boolean {
  return /^[A-Za-z0-9_-]{22}$/.test(value);
}
