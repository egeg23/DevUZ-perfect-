import { cases } from "@/content/cases";
import { proof } from "@/content/company";
import { nicheWords } from "@/lib/razbor/classify";

/**
 * Чем подпереть первое письмо, кроме находок.
 *
 * Владелец: «надо ещё жути нагнать — делали тут конкуренту вашему, вырос в
 * икс раз по заказам… результат по любой нише в среднем х2-х4 к
 * лидогенерации после нашего аудита и работы».
 *
 * Жуть в холодном письме работает ровно один раз и только если она
 * проверяема. «Ваши конкуренты уже это сделали» без имени — пустая угроза,
 * её пролистывают. «Мы делали Mavera, вот ссылка» — это либо правда, которую
 * адресат проверит за десять секунд, либо ложь, которую он поймает за те же
 * десять. Третьего не дано, поэтому здесь нет ни одной строки, которую
 * нельзя открыть.
 *
 * Отсюда устройство. Проект подбирается из настоящего списка кейсов по нише
 * адресата; не нашлось совпадения — никакого проекта в письме не будет, и
 * подставить «похожий» нельзя. Масштаб студии и средний рост берутся из
 * `content/company.ts`, откуда их читает и сайт: расхождение между письмом и
 * страницей ловит первый же, кто перейдёт по ссылке.
 */

export type Reference = {
  /** Название проекта — так, как оно стоит в кейсах. */
  name: string;
  /** Наша страница разбора: она никуда не денется и рассказывает историю. */
  url: string;
  /** Ниша, по которой совпало, — ею объясняем, почему показываем именно это. */
  niche: string;
};

export type Proof = {
  /** Настоящий проект из ниши адресата либо ничего. */
  reference: Reference | null;
  staff: number;
  projects: number;
  lift: readonly [number, number];
};

const SITE = "https://devuz.studio";

/** Слова, по которым ниша адресата сходится с нишей кейса. */
function words(value: string): string[] {
  return value
    .toLowerCase()
    .split(/[^a-zа-яё0-9]+/i)
    .filter((w) => w.length >= 4);
}

/**
 * Проект из той же ниши.
 *
 * Совпадение ищется по словам, а не по точному равенству: ниша адресата
 * приходит из классификатора («недвижимость»), а в кейсе может стоять
 * «продажа квартир» или «жилой комплекс». Порог в одно слово длиной от
 * четырёх букв — компромисс: «сайт» и «услуги» отсеиваются длиной, а
 * «квартир» и «доставка» ловятся.
 *
 * Не нашлось — возвращаем null, и в письме проекта не будет вовсе.
 * Подставить «похожий» нельзя: «делали в вашей нише» про чужую нишу — это
 * та самая ложь, которую адресат ловит за десять секунд.
 */
export function referenceFor(niche: string | null, hints: readonly string[] = []): Reference | null {
  // Слаг ниши разворачивается в её же слова: «nedvizhimost» само по себе не
  // сойдётся с «недвижимость» из кейса ни одной буквой.
  const needles = new Set([
    ...words(niche ?? ""),
    ...nicheWords(niche).flatMap(words),
    ...hints.flatMap(words),
  ]);
  if (!needles.size) return null;

  for (const item of cases) {
    // Свой сайт в качестве примера не показываем: «мы сделали сайт себе» на
    // вопрос «а вы кому-то делали» — это ответ «нет».
    if (item.slug === "devuz") continue;

    const hit = item.niches.find((n) => words(n).some((w) => needles.has(w)));
    if (hit) return { name: item.name, url: `${SITE}/cases/${item.slug}`, niche: hit };
  }
  return null;
}

export function proofFor(niche: string | null, hints: readonly string[] = []): Proof {
  return {
    reference: referenceFor(niche, hints),
    staff: proof.staff,
    projects: proof.projects,
    lift: proof.lift,
  };
}

/**
 * Строки для промпта.
 *
 * Отдельно от сборки промпта, потому что числа отсюда потом проверяются
 * машиной: письмо, в котором названо «550 проектов», обязано было получить
 * это число здесь, а не придумать.
 */
export function proofLines(p: Proof): string {
  const scale = `Студия: ${p.staff} разработчиков в штате, ${p.projects}+ завершённых проектов по разным нишам. Средний рост лидогенерации после аудита и работ — в ${p.lift[0]}–${p.lift[1]} раза; это среднее по нашим проектам, а не обещание этому адресату, и так и говори.`;

  const ref = p.reference
    ? ` В его нише у нас есть «${p.reference.name}» — сошлись на него по имени и дай ссылку ${p.reference.url}. Один такой пример сильнее любых прилагательных: адресат проверит его за десять секунд.`
    : " Готового проекта в его нише у нас в списке нет — значит, ни одного названия и ни одной ссылки на чужой проект в письме быть не должно.";

  const how = ` Рост считаем не на словах: до работ и после снимаем статистику и показываем её рядом. Предложи это как способ проверить нас, а не как обещание.`;

  return scale + ref + how;
}
