import type { Finding, Severity } from "@/lib/audit/checks";

/**
 * Отдельный балл: насколько сайт вообще может быть найден в Google.
 *
 * Общий балл аудита мешает в одну кучу две разные беды. «Нет кнопки в
 * телеграм» и «страница закрыта от индексации» оба роняют его, но первое
 * теряет клиента, который уже пришёл, а второе означает, что он не придёт
 * никогда. Владельцу, который спрашивает «почему меня нет в поиске», нужен
 * ответ именно на второй вопрос, и общий балл его не даёт.
 *
 * Отсюда второй счёт по тем же находкам, но взвешенным иначе: сюда входит
 * только то, что стоит между сайтом и поисковой выдачей.
 *
 * ## Откуда веса
 *
 * Не из Google. Своей формулы он не публикует, и любой, кто утверждает
 * обратное, её выдумал. Здесь другое: находки расставлены по тому,
 * насколько прямо каждая мешает попасть в выдачу, и расстояние между
 * ступенями отражает эту прямоту, а не какой-то коэффициент ранжирования.
 *
 * Запрет индексации — не «минус сколько-то», а конец разговора: страницы в
 * поиске нет, и остальные двадцать замечаний к ней не относятся. Поэтому
 * такие находки не вычитаются, а ставят потолок.
 */

export type SeoGrade = "good" | "fixable" | "poor" | "blocked";

/** Находка без «что делаем»: наружу уходит проблема, а не её решение. */
export type SeoProblem = { code: string; severity: Severity; title: string; impact: string };

export type SeoReport = {
  /** 0–100. Осмысленно только при `measured`. */
  score: number;
  grade: SeoGrade;
  /**
   * Что показываем снаружи: одна-две находки, самые тяжёлые.
   *
   * Владелец: «не выдавай чёткие ответы, просто укажи 1-2 проблемы и
   * дальше — в разборе с нашим менеджером». Проблему и её цену человек
   * должен увидеть сам, иначе не поверит; порядок работ — это уже разговор.
   *
   * Поэтому тип урезан: `fix` в нём отсутствует. Правило, записанное в
   * комментарии, держится ровно до первого, кто напишет `f.fix` в вёрстке;
   * правило, записанное в типе, не даст это скомпилировать.
   */
  shown: SeoProblem[];
  /** Сколько находок осталось за разбором. */
  hidden: number;
  /** Сколько всего нашлось по этой части. */
  total: number;
  /** Смотрели ли мы вообще. Сайт не открылся — балла нет, а не ноль. */
  measured: boolean;
};

/**
 * Находки, которые стоят между сайтом и выдачей, и цена каждой.
 *
 * Чего здесь намеренно нет: телефон, мессенджеры, цены, шрифты, стена
 * текста. Они решают, обратится ли человек, который уже открыл сайт, — и
 * считаются общим баллом. Смешав их сюда, мы получили бы число, про которое
 * нельзя сказать, что оно означает.
 */
const WEIGHT: Record<string, number> = {
  // Google индексирует мобильную версию. Сайт, не приспособленный к
  // телефону, он и оценивает как непригодный к показу.
  no_viewport: 18,

  // Страницу собирает браузер — роботу достаётся пустая заготовка.
  client_rendered: 30,

  // Заголовок страницы — та самая синяя строка в выдаче. Без него Google
  // подставляет что придётся, и по названию компании сайт находят хуже.
  no_title: 14,
  no_h1: 8,
  no_description: 5,

  // Замочек: без него сайт стоит ниже похожих, а браузер пишет «Не защищено».
  no_https: 12,
  mixed_content: 4,
  cert_expiring: 3,

  // Как робот обходит сайт.
  no_sitemap: 8,
  no_canonical: 6,
  no_robots: 2,

  // Скорость Google измеряет и учитывает — об этом он говорит прямо.
  slow: 8,

  // Узбекистан: ищут и по-русски, и по-узбекски. Без связки версий Google
  // считает их конкурентами друг друга.
  one_language: 6,

  // Что добавляет строке в выдаче вес и вид.
  no_schema: 4,
  img_no_alt: 3,

  // Ссылки в никуда обходятся дважды: посетитель уходит, а робот тратит на
  // них обход.
  broken_links: 5,
  broken_images: 2,

  // Мелочь по сравнению с остальным, но это часть того же «удобно ли
  // читать с телефона», которое Google измеряет.
  zoom_locked: 2,
};

/**
 * Находки, после которых считать нечего.
 *
 * Страницы в поиске нет вовсе: либо ей прямо запрещено там быть, либо она
 * не открывается. Складывать к этому минусы за отсутствующий заголовок —
 * всё равно что перечислять царапины на машине без двигателя.
 */
const BLOCKING = new Set(["noindex", "robots_blocked", "http_error", "unreachable"]);

/** Потолок для сайта, которому запрещено быть в поиске. */
const BLOCKED_CEILING = 10;

/**
 * Относится ли находка к видимости в поиске.
 *
 * Нужно снаружи: на публичной проверке такие находки уходят в отдельный
 * блок и показываются без «что делаем». Оставить их заодно и в общем
 * списке, где «что делаем» стоит рядом, значило бы закрыть дверь и тут же
 * открыть окно.
 */
export function isSeoCode(code: string): boolean {
  return BLOCKING.has(code) || code in WEIGHT;
}

/**
 * Оценка словами — для панели, где язык всегда русский.
 *
 * На сайте четыре языка, и там те же четыре строки берутся из словаря
 * (`seoGoodGrade` и соседние). Разводить их по двум местам приходится
 * потому, что панель словарь не читает: у неё нет локали.
 */
export const GRADE_TEXT: Record<SeoGrade, string> = {
  good: "Для поиска всё в порядке",
  fixable: "Есть что поправить",
  poor: "В поиске вас находят плохо",
  blocked: "Сайта в поиске нет",
};

function grade(score: number, blocked: boolean): SeoGrade {
  if (blocked) return "blocked";
  if (score >= 80) return "good";
  if (score >= 50) return "fixable";
  return "poor";
}

/**
 * Сколько показать снаружи.
 *
 * Две — потому что одна читается как придирка, а список из десяти читается
 * как отчёт, который уже не нужно ни с кем обсуждать.
 */
const SHOW = 2;

/**
 * Принимает не отчёт целиком, а только находки: тот же счёт нужен и в
 * панели касаний, где отчёта уже нет — есть сохранённая карточка проспекта.
 */
export function seoReport(input: { findings: readonly Finding[] }): SeoReport {
  const relevant = input.findings.filter((f) => BLOCKING.has(f.code) || f.code in WEIGHT);

  const blocked = relevant.some((f) => BLOCKING.has(f.code));

  // Сортировка по цене находки, а не по тяжести из общего аудита: здесь
  // важно другое. «Нет карты сайта» в общем списке — мелочь, а для того,
  // кого не находят, это одна из главных причин.
  const ordered = [...relevant].sort(
    (a, b) => cost(b) - cost(a) || a.code.localeCompare(b.code),
  );

  const penalty = relevant.reduce((sum, f) => sum + (WEIGHT[f.code] ?? 0), 0);
  const raw = Math.max(0, 100 - penalty);
  const score = blocked ? Math.min(raw, BLOCKED_CEILING) : raw;

  return {
    score,
    grade: grade(score, blocked),
    shown: ordered.slice(0, SHOW).map(({ code, severity, title, impact }) => ({ code, severity, title, impact })),
    hidden: Math.max(0, ordered.length - SHOW),
    total: ordered.length,
    // Сайт, который не открылся, мы не смотрели: у `analyze` в этом случае
    // и общий балл ноль, и говорить о видимости в поиске нечего.
    measured: !relevant.some((f) => f.code === "unreachable" || f.code === "http_error"),
  };
}

function cost(finding: Finding): number {
  return BLOCKING.has(finding.code) ? 1000 : (WEIGHT[finding.code] ?? 0);
}

/**
 * Строка про остальное — та, ради которой всё это и затевалось.
 *
 * Не «купите разбор»: разбор уже сделан и стоит нам ноль. Продаётся
 * разговор, в котором из списка находок получается порядок работ, а из
 * порядка — смета. Поэтому формулировка зовёт к человеку, а не к кнопке.
 */
export function restLine(hidden: number): string | null {
  if (hidden <= 0) return null;
  const tens = hidden % 100;
  const ones = hidden % 10;
  const word =
    tens >= 11 && tens <= 14 ? "замечаний" : ones === 1 ? "замечание" : ones >= 2 && ones <= 4 ? "замечания" : "замечаний";
  return `Ещё ${hidden} ${word} по этой части разберём с менеджером — покажем на вашем сайте, что именно и в каком порядке чинить.`;
}
