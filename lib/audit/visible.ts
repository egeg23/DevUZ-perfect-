/**
 * Что мы вообще видим на этой странице.
 *
 * Появилось после разбора akbar-rich.uz. Аудит написал владельцу: «на сайте
 * не видно телефона» — а номер стоял у него в шапке крупными цифрами, и
 * кнопка «Связаться с нами» рядом. Письмо начиналось с утверждения, которое
 * адресат опровергал за одну секунду, просто посмотрев на свой сайт.
 *
 * Причина не в регулярке. Сервер отдаёт двадцать килобайт разметки, в
 * которой **девять слов видимого текста**: шапку, телефон, заголовок, цены
 * и меню собирает браузер уже у посетителя. Наш аудитор читает то, что
 * пришло по проводу, и честно не находит там ничего — после чего выдаёт это
 * за свойство сайта.
 *
 * Разница между «на сайте нет телефона» и «мы не смогли его увидеть»
 * принципиальна. Первое — претензия, и она бывает ложной. Второе — факт о
 * нашем разборе, и его нельзя оспорить.
 *
 * Причём второе для владельца ценнее. Поисковый робот на первом проходе
 * видит ровно то же, что и мы, — и индексирует девять слов вместо страницы.
 * То есть там, где аудит раньше врал, теперь стоит его самая сильная
 * находка, и она про деньги: сайт не ищется.
 */

/** Следы фреймворка, который собирает страницу в браузере. */
const FRAMEWORKS: [RegExp, string][] = [
  [/__NEXT_DATA__|\/_next\/static\//i, "Next.js"],
  [/__NUXT__|\/_nuxt\//i, "Nuxt"],
  [/ng-version=|\bng-app\b/i, "Angular"],
  [/data-reactroot|react-dom|\breact\.production\b/i, "React"],
  [/\bvue\.runtime\b|\bdata-v-[0-9a-f]{8}\b/i, "Vue"],
  [/\bsvelte-[0-9a-z]{6}\b/i, "Svelte"],
];

export type Seen = {
  /** Слов видимого текста в том, что отдал сервер. */
  words: number;
  /** Размер разметки в байтах — для сравнения со словами. */
  bytes: number;
  /** Какая доля байтов лежит внутри script. */
  scriptShare: number;
  /** Страницу собирает браузер: по проводу пришла почти пустая оболочка. */
  clientRendered: boolean;
  /** Чем собирает, если узнали. */
  framework: string | null;
};

/**
 * Текст, который виден посетителю: без скриптов, стилей и тегов.
 *
 * Отдельно от того же приёма в checks.ts не выносится — там он нужен для
 * поиска слов, здесь для счёта, и оба места должны считать одинаково.
 */
export function visibleText(html: string): string {
  return html
    .replace(/<script[\s\S]*?<\/script>/gi, " ")
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<!--[\s\S]*?-->/g, " ")
    .replace(/<[^>]+>/g, " ");
}

/**
 * Сколько слов пришло по проводу — и собирается ли страница в браузере.
 *
 * Порог в 120 слов взят не с потолка: это примерно один экран текста.
 * Страница, на которой меньше, либо действительно пуста, либо собирается
 * скриптом, — и в обоих случаях поисковик на первом проходе видит пустоту.
 *
 * Одного порога мало: короткая честная страница-визитка и пустая оболочка
 * SPA по количеству слов неразличимы. Отличает их второе условие — двадцать
 * килобайт разметки при девяти словах бывают только у второй. Поэтому
 * нужен либо след фреймворка, либо перевес скриптов над содержимым.
 */
export function whatWeSee(html: string): Seen {
  const words = visibleText(html).split(/\s+/).filter(Boolean).length;
  const bytes = Buffer.byteLength(html, "utf8");

  const scriptBytes = (html.match(/<script[\s\S]*?<\/script>/gi) ?? []).reduce(
    (sum, block) => sum + Buffer.byteLength(block, "utf8"),
    0,
  );
  const scriptShare = bytes ? scriptBytes / bytes : 0;

  const framework = FRAMEWORKS.find(([re]) => re.test(html))?.[1] ?? null;

  const clientRendered = words < 120 && bytes > 2000 && (framework !== null || scriptShare > 0.5);

  return { words, bytes, scriptShare, clientRendered, framework };
}
