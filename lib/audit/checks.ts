/**
 * Разбор страницы в находки.
 *
 * Главное правило здесь не техническое. Находка формулируется на языке
 * владельца бизнеса, а не разработчика: не «отсутствует meta viewport», а
 * «на телефоне сайт открывается в масштабе большого экрана — посетителю
 * приходится растягивать пальцами». Первое ему нечего делать, второе он
 * узнаёт и хочет исправить.
 *
 * У каждой находки три части, и все три обязательны: что не так, чем это
 * оборачивается для клиентов и денег, и что с этим делаем. Третья часть
 * появилась по просьбе владельца студии: без неё разбор читается как список
 * претензий, с ней — как предложение. Одни и те же строки видит посетитель
 * публичной страницы и читает менеджер в «Касаниях», поэтому тон здесь
 * один: дружелюбно, по делу, без обещаний, которые нечем подтвердить.
 *
 * Функция чистая: на входе HTML и замеры, на выходе список. Никаких запросов,
 * поэтому её целиком закрывают тесты.
 */
import {
  EMPTY_CONTACTS,
  extractContacts,
  mergeContacts,
  type Contacts,
} from "@/lib/audit/contacts";
import { designChecks, type DesignFacts } from "@/lib/audit/design";
import type { PageProbe } from "@/lib/audit/fetch";
import { visibleText, whatWeSee, type Seen } from "@/lib/audit/visible";
import { classify } from "@/lib/razbor/classify";

export type Severity = "critical" | "major" | "minor";

export type Finding = {
  code: string;
  severity: Severity;
  /** Что не так — одной строкой, словами владельца сайта. */
  title: string;
  /** Чем это оборачивается для него в клиентах и деньгах. */
  impact: string;
  /** Что с этим делаем и сколько это обычно занимает. */
  fix: string;
};

export type AuditReport = {
  url: string;
  score: number;
  findings: Finding[];
  facts: {
    https: boolean;
    ttfbMs: number;
    platform: string | null;
    isShop: boolean;
    certDaysLeft: number | null;
    /**
     * Ниша по приметам в разметке, или null.
     *
     * Нужна ровно для одного: показать человеку разборы его ниши сразу
     * после находок. Ошибиться лучше в сторону null — подставленные наугад
     * разборы автосервисов владельцу стоматологии роняют доверие ко всему
     * отчёту.
     */
    niche: string | null;
    /**
     * Вёрстка: эпоха, правила под телефон, таблицы как каркас.
     * Необязательное: отчёты, сохранённые до появления проверки, его не несут.
     */
    design?: DesignFacts;
    /** Куда писать: телефоны, почта, мессенджеры — с сайта компании. */
    contacts?: Contacts;
    /**
     * Что мы вообще увидели в том, что отдал сервер.
     *
     * Необязательное: разборы, снятые до появления проверки, его не несут.
     */
    seen?: Seen;
  };
};

const has = (html: string, re: RegExp) => re.test(html);

/** «9 слов», «22 слова», «1 слово» — находка с числом должна читаться вслух. */
function wordsWord(n: number): string {
  const ten = n % 100;
  if (ten >= 11 && ten <= 14) return "слов";
  const one = n % 10;
  if (one === 1) return "слово";
  if (one >= 2 && one <= 4) return "слова";
  return "слов";
}

/** Определяет движок по следам в разметке — нужно, чтобы говорить предметно. */
export function detectPlatform(html: string, headers: Record<string, string>): string | null {
  const h = html.toLowerCase();
  if (h.includes("wp-content") || h.includes("wp-includes")) return "WordPress";
  if (h.includes("tilda") || h.includes("tildacdn")) return "Tilda";
  if (h.includes("bitrix")) return "1С-Битрикс";
  if (h.includes("wix.com") || h.includes("_wixCssImports".toLowerCase())) return "Wix";
  if (h.includes("shopify")) return "Shopify";
  if (h.includes("insales")) return "InSales";
  const powered = (headers["x-powered-by"] ?? "").toLowerCase();
  if (powered.includes("next")) return "Next.js";
  return null;
}

/**
 * Запрещает ли robots.txt обход всего сайта.
 *
 * Смотрим только группу `User-agent: *`: правило, написанное отдельно для
 * какого-нибудь SemrushBot, к индексации в Google отношения не имеет, а
 * находка «сайт закрыт от поиска» из-за такой строки была бы ложной
 * тревогой — и самой обидной, потому что владелец пойдёт её проверять.
 */
export function robotsBlocksAll(robots: string): boolean {
  let inStar = false;
  let blocked = false;
  for (const raw of robots.split(/\r?\n/)) {
    const line = raw.replace(/#.*$/, "").trim();
    const agent = line.match(/^user-agent\s*:\s*(.+)$/i);
    if (agent) {
      inStar = agent[1].trim() === "*";
      continue;
    }
    if (!inStar) continue;
    const disallow = line.match(/^disallow\s*:\s*(.*)$/i);
    if (disallow && disallow[1].trim() === "/") blocked = true;
    // Отдельное «можно всё» после запрета снимает его: так пишут, когда
    // закрывают сайт на время и забывают убрать строку целиком.
    const allow = line.match(/^allow\s*:\s*(.*)$/i);
    if (allow && allow[1].trim() === "/") blocked = false;
  }
  return blocked;
}

/** Признаки того, что это магазин, а не визитка. */
export function looksLikeShop(html: string): boolean {
  const h = html.toLowerCase();
  return (
    has(h, /корзин|savat|cart|basket/) &&
    has(h, /в корзину|добавить|buy|купить|savatga/)
  );
}

function textBetween(html: string, tag: string): string | null {
  const m = html.match(new RegExp(`<${tag}[^>]*>([\\s\\S]*?)</${tag}>`, "i"));
  return m ? m[1].replace(/<[^>]+>/g, "").trim() : null;
}

function metaContent(html: string, name: string): string | null {
  const m = html.match(
    new RegExp(`<meta[^>]+(?:name|property)=["']${name}["'][^>]*>`, "i"),
  );
  if (!m) return null;
  const c = m[0].match(/content=["']([^"']*)["']/i);
  return c ? c[1].trim() : null;
}

/**
 * Отчёт по сайту, который не открылся вовсе.
 *
 * Это находка, а не пропуск: перед нами бизнес, у которого сайт не работает,
 * и для его клиента это выглядит ровно так же. Строится здесь, а не в двух
 * вызывающих местах, чтобы публичная страница и пакетный аудит говорили
 * одними словами. `why` — уже человеческая причина («домен не найден»),
 * а не код ошибки.
 */
export function unreachable(url: string, why: string): AuditReport {
  // Ошибка сертификата — не «не отвечает»: сайт жив, но браузер ставит
  // перед ним предупреждение на весь экран. Владелец, прочитав «не
  // отвечает», откроет сайт у себя, нажмёт «всё равно перейти» — и решит,
  // что мы ошиблись.
  const cert = /сертификат/i.test(why);
  return {
    url,
    score: 0,
    findings: [
      {
        code: "unreachable",
        severity: "critical",
        title: cert ? "Вместо сайта — предупреждение браузера" : "Сайт не отвечает",
        impact: cert
          ? `Сайт открывается только через предупреждение безопасности: ${why}. Посетитель не станет разбираться, что это техническая мелочь, — решит, что сайт взломан, и уйдёт к тем, у кого открылось.`
          : `Мы не смогли открыть страницу: ${why}. Для клиента это выглядит ровно так же — он вводит адрес, не попадает никуда и идёт к тому, у кого открылось. Если сайта пока нет, это не проблема, а точка роста.`,
        fix: "Если сайт есть и просто упал — разбираемся с хостингом или доменом и поднимаем его, обычно за час-два. Если сайта ещё нет — соберём: для сайта-визитки это неделя-две.",
      },
    ],
    facts: {
      https: false,
      ttfbMs: 0,
      platform: null,
      isShop: false,
      certDaysLeft: null,
      niche: null,
      design: { era: "unknown", mediaQueries: 0, flexOrGrid: false, tablesLayout: false, cssRead: false },
      contacts: EMPTY_CONTACTS,
    },
  };
}

export function analyze(probe: PageProbe, now: Date = new Date()): AuditReport {
  const html = probe.html;
  const findings: Finding[] = [];
  const add = (f: Finding) => findings.push(f);

  /**
   * Контакты считаются здесь, а не в конце, потому что на них теперь
   * опираются находки. Раньше проверка «есть ли телефон» искала его сама, в
   * видимом тексте, и не видела номера в разметке для поисковика: аудит
   * написал владельцу akbar-rich.uz «на сайте не видно телефона», когда тот
   * стоял у него в шапке. Источник истины должен быть один, и это разбор
   * контактов — он знает про все места, где номер бывает.
   */
  const contacts = mergeContacts(
    extractContacts(html),
    probe.assets?.contactsHtml ? extractContacts(probe.assets.contactsHtml) : EMPTY_CONTACTS,
    probe.assets?.contactsUrl ?? null,
  );

  const seen = whatWeSee(html);

  /**
   * Страница ошибки — не сайт.
   *
   * На apex.uz сервер отдавал 503, и аудит разбирал страницу «сервис
   * недоступен» как главную: тринадцать претензий, из них двенадцать — к
   * заглушке хостинга. Владельцу уходило письмо про отсутствующий телефон и
   * ненаписанный заголовок, когда единственная его беда была в том, что сайт
   * лежит.
   */
  const pageLoaded = probe.status < 400;

  /**
   * Что до нас доехало. Если страницу собирает браузер, содержимого в
   * ответе сервера нет, и ни одну находку про содержимое утверждать нельзя:
   * «на сайте нет цен» превращается в ложь, которую адресат опровергает за
   * секунду, просто открыв свой сайт.
   */
  const sawContent = pageLoaded && !seen.clientRendered;

  if (probe.status >= 400) {
    add({
      code: "http_error",
      severity: "critical",
      title: `Сайт отвечает ошибкой ${probe.status}`,
      impact:
        "Каждый, кто приходит по ссылке из поиска, из карт или с визитки, видит вместо сайта страницу ошибки и уходит — чаще всего к тому, чей сайт открылся. Если так продолжается несколько дней, Google начинает убирать страницы из выдачи, и возвращаются они не сразу.",
      fix: "Смотрим, что именно упало — хостинг, база или неудачное обновление, — и поднимаем сайт. Обычно это час-два; если сайт падает регулярно, предлагаем переезд на нормальный хостинг.",
    });
  }

  if (!probe.https) {
    add({
      code: "no_https",
      severity: "critical",
      title: "Сайт открывается без защищённого соединения",
      impact:
        "Браузер пишет рядом с адресом «Не защищено», и часть посетителей закрывает вкладку, не читая. Формы с личными данными и оплату на таком сайте принимать нельзя, а в поиске он стоит ниже похожих сайтов с замочком.",
      fix: "Выпускаем бесплатный сертификат, включаем автопродление и переводим все страницы на защищённый адрес так, чтобы старые ссылки продолжали работать. Пара часов работы.",
    });
  } else if (probe.certDaysLeft !== null && probe.certDaysLeft < 14) {
    add({
      code: "cert_expiring",
      severity: probe.certDaysLeft < 0 ? "critical" : "major",
      title:
        probe.certDaysLeft < 0
          ? "Сертификат безопасности истёк"
          : `Сертификат безопасности истекает через ${probe.certDaysLeft} дн.`,
      impact:
        "Истёкший сертификат — это красное предупреждение на весь экран вместо сайта. Посетитель не станет разбираться, что это техническая мелочь: он решит, что сайт взломан, и уйдёт. Особенно обидно, если в этот момент идёт реклама.",
      fix: "Продлеваем сертификат и настраиваем автоматическое продление, чтобы это больше не повторялось. Около часа.",
    });
  }

  if (probe.tlsIssue === "chain") {
    add({
      code: "cert_chain",
      severity: "major",
      title: "Сертификат установлен не полностью",
      impact:
        "Браузер на компьютере сайт открывает, а часть телефонов, приложений и ботов — нет: они видят ошибку безопасности. Превью ссылки в мессенджере тоже может не собраться.",
      fix: "Доустанавливаем промежуточный сертификат на сервере. Полчаса работы, сайт при этом не останавливается.",
    });
  }

  if (pageLoaded && !has(html, /<meta[^>]+name=["']viewport["']/i)) {
    add({
      code: "no_viewport",
      severity: "critical",
      title: "Сайт не приспособлен к телефонам",
      impact:
        "На телефоне страница открывается в масштабе большого экрана: текст мелкий, кнопки крошечные, чтобы что-то прочитать, приходится растягивать пальцами. Большинство людей сегодня заходит с телефона — именно так сайт видит большая часть ваших клиентов, и многие уходят, не дочитав.",
      fix: "Делаем мобильную версию: перестраиваем страницы так, чтобы на телефоне всё читалось и нажималось без масштабирования. Для небольшого сайта это несколько дней.",
    });
  }

  if (probe.ttfbMs > 1500) {
    add({
      code: "slow",
      severity: probe.ttfbMs > 3000 ? "major" : "minor",
      title: `Сайт начинает открываться только через ${(probe.ttfbMs / 1000).toFixed(1)} сек`,
      impact:
        "Всё это время посетитель смотрит на белый экран — текст и картинки ещё даже не начали загружаться. После трёх секунд ожидания уходит примерно каждый второй, а Google учитывает скорость, когда решает, кого показать выше.",
      fix: "Находим, где теряется время — чаще всего это слабый хостинг, тяжёлые плагины или база без кэша, — и убираем причину. Обычно день-два, и сайт начинает отвечать в несколько раз быстрее.",
    });
  }

  const title = textBetween(html, "title");
  if (pageLoaded && !title) {
    add({
      code: "no_title",
      severity: "major",
      title: "У страницы нет заголовка для поисковиков",
      impact:
        "Заголовок — та синяя строка, которой сайт представлен в Google и во вкладке браузера. Без него поисковик подставляет что придётся, и даже по названию компании вас находят хуже, чем могли бы.",
      fix: "Пишем заголовки для главной и ключевых страниц — с названием компании, тем, что вы делаете, и городом. Несколько часов.",
    });
  }

  if (pageLoaded && !metaContent(html, "description")) {
    add({
      code: "no_description",
      severity: "minor",
      title: "Нет описания для поисковиков",
      impact:
        "Под ссылкой в Google показывается случайный кусок текста со страницы вместо короткого объяснения, чем вы занимаетесь. Люди читают эти две строки, прежде чем нажать, и чаще выбирают того, у кого написано понятно.",
      fix: "Пишем описания для главной и основных страниц — по два предложения, по-человечески, без канцелярита. Час-два.",
    });
  }

  if (pageLoaded && !metaContent(html, "og:image")) {
    add({
      code: "no_og",
      severity: "major",
      title: "Ссылка на сайт выглядит пусто при пересылке",
      impact:
        "Когда клиент отправляет вашу ссылку в Telegram или WhatsApp, вместо карточки с картинкой и названием уходит голый адрес. По такой ссылке переходят заметно реже — а пересылают её как раз те, кто вас рекомендует.",
      fix: "Добавляем картинку и подпись для мессенджеров и соцсетей, чтобы ссылка разворачивалась в аккуратную карточку. Пара часов вместе с подготовкой картинки.",
    });
  }

  if (sawContent && !textBetween(html, "h1")) {
    add({
      code: "no_h1",
      severity: "minor",
      title: "На странице нет главного заголовка",
      impact:
        "Посетитель за секунду должен понять, куда он попал, а поисковик — о чём страница. Главный заголовок делает это за обоих; без него оба гадают.",
      fix: "Выносим на первый экран одну строку: что вы делаете и для кого. Час, чаще меньше.",
    });
  }

  /* ── Как с вами связаться ─────────────────────────────────────────────
   *
   * Дальше идут находки не про разметку, а про путь клиента. Их не было, и
   * оттого аудит молчал почти на каждом живом сайте: HTTPS, viewport и
   * title сегодня есть у всех, а вот дозвониться и узнать цену можно
   * далеко не везде. Именно на этом бизнес теряет деньги, и именно это
   * владелец сайта узнаёт про себя с первого взгляда. */

  const text = visibleText(html);
  const hasTelLink = has(html, /href=["']tel:/i);

  if (sawContent && !hasTelLink && !contacts.phones.length) {
    add({
      code: "no_phone",
      severity: "critical",
      title: "На сайте не видно телефона",
      impact:
        "Человек, который уже решил обратиться, ищет номер — и не находит. Дальше он не пишет письмо и не заполняет форму, а возвращается в поиск и звонит следующему. Для услуг, которые заказывают голосом, это самая дорогая из возможных потерь.",
      fix: "Ставим номер в шапку на каждой странице и делаем его нажимаемым, чтобы с телефона звонок начинался одним касанием. Час.",
    });
  } else if (sawContent && !hasTelLink) {
    add({
      code: "phone_not_clickable",
      severity: "major",
      title: "Телефон на сайте нельзя нажать с телефона",
      impact:
        "Номер написан текстом, поэтому с мобильного его приходится выделять и копировать вручную — а половина посетителей приходит именно с мобильного. Каждый такой лишний шаг забирает часть звонков.",
      fix: "Превращаем номер в ссылку для звонка: нажатие сразу открывает набор. Полчаса.",
    });
  }

  if (sawContent && !contacts.telegram.length && !contacts.whatsapp.length) {
    add({
      code: "no_messenger",
      severity: "major",
      title: "С сайта нельзя написать в Telegram или WhatsApp",
      impact:
        "В Узбекистане переписка давно обогнала звонок: человеку проще написать, чем набирать номер и слушать гудки — особенно вечером и в выходные. Без кнопки в мессенджер эти обращения просто не случаются, и в статистике их не видно.",
      fix: "Добавляем кнопку в Telegram и WhatsApp — в шапку и плавающую на мобильном, с заранее подставленным первым сообщением. Несколько часов.",
    });
  }

  /* ── Сколько это стоит ───────────────────────────────────────────────── */

  // Только на непорезанной странице: на обрезанном HTML отсутствие цены
  // означает лишь то, что мы до неё не дочитали.
  const hasPrice =
    has(text, /\d[\d\s\u00a0.,]*\s*(сум|so['\u2018\u02bb]?m|сўм|UZS|у\.\s?е\.)/i) ||
    has(text, /\$\s?\d/) ||
    has(text, /\d[\d\s\u00a0.,]*\s*(долл|USD)/i);
  if (sawContent && !probe.truncated && !hasPrice) {
    add({
      code: "no_prices",
      severity: "major",
      title: "Нигде не сказано, сколько это стоит",
      impact:
        "«Сколько стоит» — первый вопрос почти каждого посетителя, и сайт на него не отвечает. Часть людей напишет и спросит, но большинство закроет вкладку и пойдёт туда, где цена названа: молчание о цене читается как «дорого» или «будут торговаться».",
      fix: "Ставим вилку «от и до» по основным услугам и объясняем, от чего зависит итог. Это не обязывает продавать по нижней границе, зато отсеивает тех, кому всё равно не по карману. День-два вместе с текстами.",
    });
  }

  /* ── Что видит поисковик ─────────────────────────────────────────────── */

  /**
   * Самая дорогая находка и самая проверяемая.
   *
   * Сервер отдаёт заготовку, текст дорисовывает браузер. Посетитель разницы
   * не замечает — поисковый робот на первом проходе получает ровно то, что
   * получили мы. Отрисовку он делает отдельным, более поздним заходом, и до
   * неё страница живёт в индексе почти пустой.
   *
   * Это и есть «низкая индексация», про которую спрашивает владелец: не
   * загадочная немилость Google, а число слов, которые ему отдали.
   */
  if (seen.clientRendered) {
    add({
      code: "client_rendered",
      severity: "critical",
      title: `Поисковик видит на главной ${seen.words} ${wordsWord(seen.words)} вместо страницы`,
      impact:
        "Сервер отдаёт почти пустую заготовку, а текст, телефон и меню дорисовывает браузер уже у посетителя. Человек этого не замечает, а поисковый робот на первом проходе получает ровно то же, что и мы. Отрисовку он делает отдельным, более поздним заходом — и до неё страница стоит в индексе почти пустой: по словам, которые на ней написаны, её не находят. Проверить просто: откройте сайт и нажмите «просмотр кода страницы» — там будет то же, что видит Google.",
      fix: seen.framework
        ? `Включаем сборку страниц на сервере — ${seen.framework}, на котором сайт уже работает, это умеет, и переделывать его не придётся. Несколько дней вместе с проверкой, что в коде страницы появился весь текст.`
        : "Переносим сборку страницы на сервер, чтобы в ответе сразу приходил готовый текст. Обычно это настройка того же движка, на котором сайт уже работает, а не переделка: несколько дней.",
    });
  }

  /* ── Индексация: почему сайт не ищется ───────────────────────────────── */

  const robotsMeta = metaContent(html, "robots") ?? "";
  const xRobots = probe.headers["x-robots-tag"] ?? "";
  if (/noindex/i.test(robotsMeta) || /noindex/i.test(xRobots)) {
    add({
      code: "noindex",
      severity: "critical",
      title: "Страница закрыта от поисковиков прямым запретом",
      impact:
        "В коде страницы стоит указание не показывать её в поиске. Такое обычно ставят на время разработки и забывают снять — а пока оно стоит, сайта в Google нет вовсе, сколько бы за него ни платили и сколько бы текстов ни написали.",
      fix: "Снимаем запрет и отправляем страницы на переобход в Search Console. Полчаса; в выдаче сайт появляется в течение нескольких дней.",
    });
  }

  const robots = probe.assets?.robots;
  if (robots === null) {
    add({
      code: "no_robots",
      severity: "minor",
      title: "У сайта нет robots.txt",
      impact:
        "Это первый файл, который поисковик спрашивает у сайта. Без него ничего не ломается, но и указать, где лежит карта сайта и какие служебные разделы обходить не надо, негде — робот ходит вслепую и тратит обход на страницы вроде корзины и поиска.",
      fix: "Пишем robots.txt со ссылкой на карту сайта и закрываем служебные адреса. Полчаса.",
    });
  } else if (robots && robotsBlocksAll(robots)) {
    add({
      code: "robots_blocked",
      severity: "critical",
      title: "robots.txt запрещает поисковикам весь сайт",
      impact:
        "В файле стоит строка, запрещающая обход всех страниц. Так закрывают сайт на время переделки — и забывают открыть обратно. Пока она там, новые страницы в индекс не попадают, а старые постепенно выпадают: сайт исчезает из поиска сам собой.",
      fix: "Убираем запрет, оставляем закрытыми только служебные разделы, и отправляем сайт на переобход. Час.",
    });
  }

  if (probe.assets?.sitemap === false) {
    add({
      code: "no_sitemap",
      severity: "major",
      title: "У сайта нет карты для поисковика",
      impact:
        "Карта сайта — список всех страниц, который поисковик читает вместо того, чтобы искать их по ссылкам. Без неё до страниц, на которые нет прямых ссылок с главной, робот добирается месяцами или не добирается совсем. Чем больше на сайте разделов, тем дороже обходится её отсутствие.",
      fix: "Настраиваем карту, которая обновляется сама при добавлении страниц, прописываем её в robots.txt и отдаём в Search Console. Несколько часов.",
    });
  }

  if (pageLoaded && !has(html, /<link\b[^>]+rel=["']canonical["']/i)) {
    add({
      code: "no_canonical",
      severity: "minor",
      title: "Не указано, какой адрес страницы главный",
      impact:
        "Одна и та же страница обычно доступна по нескольким адресам — со слэшем и без, с www и без, с метками рекламных кампаний. Без указания основного поисковик считает их разными страницами с одинаковым текстом и делит между ними вес: вместо одной сильной страницы получается несколько слабых.",
      fix: "Проставляем канонический адрес на всех страницах. Несколько часов.",
    });
  }


  const images = html.match(/<img\b[^>]*>/gi) ?? [];
  const withoutAlt = images.filter((tag) => !/\balt=["'][^"']+["']/i.test(tag));
  // Пять картинок — порог, ниже которого это ещё не система, а случайность.
  if (sawContent && images.length >= 5 && withoutAlt.length > images.length / 2) {
    add({
      code: "img_no_alt",
      severity: "minor",
      title: `У ${withoutAlt.length} картинок из ${images.length} нет подписи для поиска`,
      impact:
        "Google не смотрит картинки глазами: он читает подпись в разметке. Без неё ваши работы и товары не попадают в поиск по картинкам — а это отдельный поток людей, которые ищут «как это выглядит», а не «где это купить». Заодно подпись читают вслух программы для незрячих.",
      fix: "Подписываем картинки по делу — что на них, а не «фото1». Для сайта на несколько десятков изображений это день.",
    });
  }

  if (pageLoaded && !has(html, /application\/ld\+json/i) && !has(html, /itemtype=["'][^"']*schema\.org/i)) {
    add({
      code: "no_schema",
      severity: "minor",
      title: "В выдаче сайт показан голой ссылкой",
      impact:
        "Соседи по выдаче показывают звёзды отзывов, адрес, часы работы и цену прямо в результатах поиска — это данные, размеченные особым образом. У вас такой разметки нет, поэтому строка выглядит беднее соседних, и нажимают на неё реже даже с той же позиции.",
      fix: "Размечаем организацию, адрес, часы и услуги так, как читает Google. Полдня, и в выдаче появляются дополнительные строки.",
    });
  }

  if (pageLoaded && !has(html, /hreflang=/i)) {
    add({
      code: "one_language",
      severity: "minor",
      title: "Поисковик не знает про вторую языковую версию",
      impact:
        "В Узбекистане ищут и по-русски, и по-узбекски, и это разные люди с разными запросами. Даже когда обе версии на сайте есть, без связки между ними Google считает их отдельными страницами-конкурентами и показывает то одну, то другую — вместо того чтобы каждому показать его язык.",
      fix: "Связываем языковые версии между собой так, как этого ждёт Google. Несколько часов, если обе версии уже есть.",
    });
  }

  // Только загружаемые файлы: src у картинок и скриптов, href у стилей.
  // Обычная ссылка <a href="http://t.me/…"> смешанным контентом не является
  // — браузер её не грузит, он по ней переходит. Первая версия проверки
  // ловила и её, и разбор салона красоты чуть не получил претензию на
  // ровном месте из-за ссылки на Telegram.
  const insecureAsset =
    has(html, /\bsrc=["']http:\/\//i) ||
    has(html, /\bsrcset=["'][^"']*http:\/\//i) ||
    has(html, /<link\b[^>]+href=["']http:\/\//i) ||
    has(html, /url\(\s*["']?http:\/\//i);
  if (probe.https && insecureAsset) {
    add({
      code: "mixed_content",
      severity: "major",
      title: "Часть файлов грузится по незащищённому соединению",
      impact:
        "Страница открывается по защищённому адресу, но тянет картинки или скрипты по обычному. Браузер такие файлы блокирует или ругается в адресной строке — в результате на чужом компьютере сайт может выглядеть поломанным, а замочек пропадает вместе с доверием.",
      fix: "Переводим все внутренние адреса на защищённое соединение и убираем внешние, которые его не поддерживают. Несколько часов.",
    });
  }

  // Вёрстка и следы раннего интернета — после всего остального: их
  // находки идут в общий список и в общий балл на тех же правах.
  const design = designChecks(probe, now);
  for (const f of design.findings) add(f);

  /**
   * Балл считается по находкам — но только если страницу удалось прочитать.
   *
   * Упавший сайт даёт ровно одну находку, «отвечает ошибкой», и по общей
   * формуле получал бы 75 из 100: на экране это выглядит как «почти всё в
   * порядке» напротив сайта, который не открывается вовсе. Ноль здесь не
   * наказание, а отсутствие оценки: мы его не видели. Столько же ставит
   * `unreachable` сайту, который не отозвался.
   */
  const score = pageLoaded
    ? Math.max(
        0,
        100 -
          findings.reduce(
            (sum, f) =>
              sum + (f.severity === "critical" ? 25 : f.severity === "major" ? 12 : 5),
            0,
          ),
      )
    : 0;

  return {
    url: probe.finalUrl,
    score,
    findings,
    facts: {
      https: probe.https,
      ttfbMs: probe.ttfbMs,
      platform: detectPlatform(html, probe.headers),
      isShop: looksLikeShop(html),
      certDaysLeft: probe.certDaysLeft,
      // Ниша определяется по тем же словам, что уже прочитаны: отдельного
      // запроса не делаем, отчёт остаётся мгновенным.
      niche: classify({ url: probe.finalUrl, html, title: textBetween(html, "title") })?.niche ?? null,
      design: design.facts,
      // Контакты — с главной и со страницы контактов, если она нашлась.
      contacts,
      seen,
    },
  };
}
