/**
 * Дешёвый отсев до обращения к модели.
 *
 * Живой чат на тысячу человек даёт несколько тысяч сообщений в сутки.
 * Отправлять каждое в модель — это и деньги, и задержка, и, что хуже,
 * очередь: пока разбираются приветствия и стикеры, настоящий запрос ждёт.
 * Здесь остаётся малая доля, и уже она идёт дальше.
 *
 * Главное различение файла — спрос против предложения. В любом чате про
 * разработку девять из десяти сообщений о сайтах пишут те, кто их делает,
 * а не те, кому нужен. «Делаю сайты под ключ» и «нужен сайт под ключ»
 * отличаются одним словом и означают противоположное: первое — конкурент,
 * второе — клиент. Фильтр, который этого не видит, приносит оператору
 * ленту чужой рекламы, и оператор перестаёт её открывать через неделю.
 */

/**
 * Границы слова, знающие кириллицу.
 *
 * \b и \w в JavaScript определены через [A-Za-z0-9_], то есть кириллица
 * для них — не буквы. Первая версия этого файла была написана на \b, и не
 * срабатывало ни одно правило: «нужен» не совпадал с \bнужен\b, потому что
 * перед «н» стоит пробел, а «н» для движка сам по себе не словесный
 * символ. Хуже того, тест «предложение не проходит» при этом был зелёным —
 * не проходило вообще ничего.
 *
 * Поэтому границы заданы через свойства Unicode, а суффиксы — через \p{L},
 * а не \w.
 */
const LEFT = "(?<![\\p{L}\\p{N}])";
const RIGHT = "(?![\\p{L}\\p{N}])";

function word(body: string): RegExp {
  return new RegExp(`${LEFT}(?:${body})${RIGHT}`, "iu");
}

/** То же, но без правой границы: для оборотов, продолжающихся дальше. */
function phrase(body: string): RegExp {
  return new RegExp(`${LEFT}(?:${body})`, "iu");
}

export type PrefilterVerdict = {
  /** Стоит ли тратить на сообщение вызов модели. */
  pass: boolean;
  /** Почему решили так — попадает в журнал скаута. */
  reason: "too_short" | "too_long" | "no_topic" | "no_demand" | "supply" | "spam" | "candidate" | "noisy_chat";
  /** Совпавшие темы: сайт, магазин, приложение, автоматизация. */
  topics: string[];
};

/**
 * Тематика. Узбекский и русский вперемешку намеренно: в ташкентских чатах
 * пишут на обоих и переключаются внутри одного сообщения.
 */
const TOPIC_PATTERNS: Record<string, RegExp> = {
  магазин: word(
    "интернет-?магазин\\p{L}*|онлайн-?магазин\\p{L}*|маркетплейс\\p{L}*|e-?commerce|do'?kon\\p{L}*",
  ),
  /**
   * `apps?` и `applications?` — целиком, а не `app\\p{L}*`: левая граница не
   * спасает от «apply», «approve», «appointment», а в англоязычном чате
   * это каждое третье сообщение.
   */
  приложение: word(
    "приложени\\p{L}*|мобилк\\p{L}*|android|ios|flutter|ilova\\p{L}*|apps?|applications?|mobile\\s+app\\p{L}*",
  ),
  /**
   * Латинское `bot` найдено сценарным прогоном: «Telegram bot kerak» —
   * самая частая узбекская формулировка — отсеивалось как «не по теме»,
   * потому что тема была задана только кириллицей. Ташкентский чат пишет
   * на двух алфавитах вперемешку, и правило обязано читать оба.
   */
  автоматизация: word(
    "автоматизаци\\p{L}*|crm|erp|интеграци\\p{L}*|чат-?бот\\p{L}*|телеграм-?бот\\p{L}*|бот\\p{L}*|avtomatlashtir\\p{L}*|chat-?bot\\p{L}*|telegram-?bot\\p{L}*|bot\\p{L}*",
  ),
  /**
   * Учётные и складские системы.
   *
   * Пробел найден холостым прогоном: «нужна система учёта для склада,
   * 4 филиала, бюджет есть, сроки горят» — запрос с объёмом, бюджетом и
   * сроком — отсеивался как сообщение не по теме. Это профильная для студии
   * работа, и такие лиды не просто терялись: отсев происходит ДО модели, то
   * есть они не появлялись даже низким баллом. Их не было нигде.
   *
   * Формулировки узкие намеренно. «Склад» и «учёт» по отдельности слишком
   * общие («складские цены», «учёт рабочего времени»), а лишняя ширина
   * отсева стоит внимания оператора — ленту, в которой шум, перестают
   * открывать через неделю.
   */
  учёт: word(
    "систем\\p{L}*\\s+уч[ёе]т\\p{L}*|складск\\p{L}*\\s+уч[ёе]т\\p{L}*|уч[ёе]т\\p{L}*\\s+(?:остатк|товар|склад)\\p{L}*|управлени\\p{L}*\\s+складом|wms|ombor\\p{L}*|hisobot\\p{L}*",
  ),
  сайт: word(
    "сайт\\p{L}*|веб-?сайт\\p{L}*|лендинг\\p{L}*|landing|веб-?студи\\p{L}*|websayt\\p{L}*|sayt\\p{L}*|web\\s*-?\\s*sites?|websites?|landing\\s+page\\p{L}*",
  ),
};

/**
 * «Прайс» — признак исполнителя, но не всегда.
 *
 * «Прайс в личке» пишет продавец; «скиньте прайс, нужен корпоративный
 * сайт» — покупатель. Второе найдено сценарным прогоном: слово стояло в
 * общем списке предложения, перебивало «нужен», и клиент, который сам
 * просит цены, уходил в отсев как конкурент. Поэтому слово вынесено из
 * общего списка и не считается, когда его просят прислать.
 */
const PRICE_LIST = word("прайс\\p{L}*");
const ASKS_FOR_PRICE_LIST = phrase(
  "(?:скиньте|скинь|пришлите|пришли|сбросьте|сбрось|дайте|отправьте|покажите|есть)\\s+(?:ваш\\s+|свой\\s+|пожалуйста\\s+)?прайс",
);

/**
 * Спрос. Человек ищет исполнителя.
 *
 * «Посоветуйте» здесь тоже спрос: в чатах чаще спрашивают совета, чем прямо
 * заказывают, и такой человек — тот же клиент, только на шаг раньше.
 */
const DEMAND = [
  // «Надо» найдено сценарным прогоном: «надо сделать магазин» — одно из
  // самых частых русских слов в этом контексте — отсеивалось как «без
  // спроса». Правило требует ещё и тему, так что «не надо» про погоду
  // сюда не попадёт.
  word("нужен|нужна|нужно|нужны|нужен-?то|надо|нада"),
  // Основа вместо формы: «подскажите», «подскажете», «посоветуете»,
  // «порекомендуете». Раньше стояло только повелительное наклонение, и
  // вежливое «порекомендуете кого-нибудь?» не считалось спросом.
  word("ищ[уеё]|ищем|(?:подскаж|посовет|порекоменд)\\p{L}*"),
  phrase("кто\\s+(?:может|делает|возьмётся|возьмется|сделает|поможет)"),
  word("хочу|хотим|планиру\\p{L}*|требуется|требуются|заказать|разработать"),
  // Необязательное слово внутри оборота: люди говорят «сколько вообще
  // стоит», «во сколько примерно обойдётся». Без этого допуска половина
  // вопросов о цене — а это прямой спрос — уходила в отсев.
  phrase(
    "сколько\\s+(?:\\p{L}+\\s+)?стоит|во\\s+сколько\\s+(?:\\p{L}+\\s+)?обойд|цена\\s+вопроса",
  ),
  word("бюджет|бюджета"),
  // Просьба прислать прайс — это покупатель. Слово «прайс» само по себе
  // остаётся признаком исполнителя (см. PRICE_LIST ниже), но в этом
  // обороте оно перестаёт им быть.
  ASKS_FOR_PRICE_LIST,
  /**
   * Узбекский — в обоих алфавитах.
   *
   * Латиница здесь была с самого начала, кириллица — нет, и «Сайт керак
   * эди, ким қилади?» отсеивалось как «без спроса». Кириллический
   * узбекский в ташкентских чатах не реже латиницы. Буквы қ/ҳ/ў/ғ
   * набирают и как к/х/у/г — поэтому обе формы.
   */
  word("kerak|zarur|izlayapman|qidir\\p{L}*|керак|кере|зарур"),
  phrase(
    "qancha\\s+turadi|kim\\s+qiladi|kim\\s+qila\\s+oladi|kim\\s+yasaydi|maslahat\\s+bering|narxi\\s+qancha|narxini\\s+ayt\\p{L}*",
  ),
  phrase(
    "ким\\s+[қк]илади|ким\\s+ясайди|[қк]анча\\s+туради|нархи\\s+[қк]анча|маслаҳат\\s+беринг|маслахат\\s+беринг",
  ),
  // Английский встречается реже, но встречается — и целиком проходил мимо.
  word("need|needs|needed|recommend\\p{L}*"),
  phrase("looking\\s+for|who\\s+can|how\\s+much"),
];

/**
 * Предложение. Человек продаёт — это конкурент, а не лид.
 *
 * Проверяется раньше спроса и перебивает его: «делаю сайты, нужен заказ» —
 * это по-прежнему исполнитель, хотя слово «нужен» в сообщении есть.
 */
const SUPPLY = [
  phrase(
    "(?:дела[юе]м?|разрабатыва\\p{L}+|созда[юёе]\\p{L}*|пишем|пишу|вёрстк\\p{L}+|верстк\\p{L}+|верста\\p{L}+)" +
      "\\s+(?:вам\\s+)?(?:сайт|лендинг|магазин|приложени|бот)",
  ),
  word("предлага[юе]м?|портфолио|расцен\\p{L}+|резюме|freelance|фриланс"),
  // «Любой сложности» пишут только исполнители: «сайты любой сложности».
  // Покупатель так не говорит. Ловит рекламу, у которой нет глагола
  // «делаем», — «Разработка сайтов любой сложности. Нужен сайт? Пишите!»
  // иначе уходила в модель как спрос.
  phrase("любой\\s+сложности"),
  phrase("оказыва\\p{L}+\\s+услуг|наш[аи]\\s+(?:команда|студия|компания)"),
  phrase("мы\\s+—?\\s*(?:студия|команда|агентство)"),
  phrase("опыт\\s+работы|мо[ий]\\s+работы|ищу\\s+(?:работу|заказ|проект)"),
  word("услуги"),
  phrase("от\\s+\\d+\\s*\\$?\\s*(?:за|/)\\s*(?:сайт|проект|час)"),
  phrase("xizmat\\s+ko'?rsatamiz|bizning\\s+jamoa|(?:yasab|qilib)\\s+beramiz|(?:ясаб|[қк]илиб)\\s+берамиз"),
  phrase("we\\s+(?:build|develop|make|create)|our\\s+(?:team|studio|agency)"),
  word("portfolio"),
];

/**
 * Субподряд: человек отдаёт работу, а не берёт.
 *
 * Самый ценный тип лида и при этом единственный, который прежний отсев
 * терял системно. «Наша команда перегружена, ищем подрядчиков на сайты»
 * попадает под SUPPLY правилом «наша команда» и отсеивается как конкурент —
 * до модели, то есть не появляется даже низким баллом. Между тем это
 * заказчик: у него уже есть работа, есть деньги и выстроенное доверие
 * конечного клиента, а нужна ему ровно наша мощность.
 *
 * Различение проходит по направлению денег, а не по роли говорящего.
 * «Делаю сайты, портфолио в личке» — продавец. «Работы больше, чем тяну,
 * кто возьмёт часть» — покупатель. Оба говорят о себе как об исполнителе,
 * и по роли их не отличить.
 *
 * Обороты узкие намеренно: это исключение из SUPPLY, а слишком широкое
 * исключение вернёт в ленту ровно ту чужую рекламу, ради отсева которой
 * SUPPLY и написан.
 *
 * Проверено на живых формулировках: «работы много» и «не справляемся»
 * здесь стояли и были убраны. Они описывают загрузку, а не намерение отдать
 * работу, и под них проходило «делаем сайты под ключ, работы много,
 * портфолио в личке» — та самая реклама. Засчитывается только явный акт
 * передачи: ищем подрядчиков, кто возьмёт часть, субподряд, аутсорс.
 *
 * Засчитывается и за спрос тоже. Иначе «работы много, кто возьмёт часть
 * проектов на себя?» уходит в no_demand: в DEMAND есть «возьмётся», но не
 * голое «возьмёт».
 */
const HANDOFF = [
  phrase("ищ[уеё]м?\\s+(?:подрядчик|исполнител|субподряд|фрилансер|разработчик)"),
  phrase("нужн\\p{L}*\\s+(?:подрядчик|исполнител|субподряд)"),
  phrase("кто\\s+возьм[её]т\\s+(?:часть|на\\s+себя)"),
  phrase("возьм[её]т\\s+(?:часть|на\\s+себя)\\s+(?:часть\\s+)?(?:проект|работ)"),
  phrase("переда(?:ть|м|дим)\\s+(?:часть\\s+)?(?:проект|работ)"),
  word("субподряд\\p{L}*|аутсорс\\p{L}*"),
];

function looksLikeSupply(text: string): boolean {
  if (SUPPLY.some((pattern) => pattern.test(text))) return true;
  return PRICE_LIST.test(text) && !ASKS_FOR_PRICE_LIST.test(text);
}

const SPAM = [
  word("инвестиц\\p{L}*|заработок|крипт\\p{L}*|казино|ставк\\p{L}+|подписывайтесь"),
  phrase("переходи\\s+по\\s+ссылке|доход\\s+\\d+\\s*%"),
  /(?:https?:\/\/\S+\s*){3,}/i,
  /(?:t\.me\/\S+\s*){3,}/i,
];

/**
 * Границы длины.
 *
 * Нижняя — не про смысл, а про физику: в восьми знаках не помещаются
 * тема и спрос разом, так что короче проверять нечего. Раньше стояло 25,
 * и «нужен сайт» (десять знаков) отсеивалось как «слишком коротко» — при
 * том что это самый прямой спрос из возможных. Мусор вроде «ок» и
 * «спасибо» режет не длина, а отсутствие темы.
 *
 * Верхняя раньше была 1500 и защищала якобы от прайс-листов и вакансий —
 * но их и так режут правила предложения и темы. А человек с развёрнутым
 * описанием задачи («четыре филиала, вот процессы, вот бюджет») — это
 * лучший лид, и он длиннее полутора тысяч знаков. Расходов длинное
 * сообщение не прибавляет: разбор всё равно обрезает текст до 1200
 * символов. Так что предел — только от пересланных статей.
 */
const MIN_LENGTH = 8;
const MAX_LENGTH = 4000;

export function prefilter(text: string): PrefilterVerdict {
  const clean = text.trim();

  if (clean.length < MIN_LENGTH) return { pass: false, reason: "too_short", topics: [] };
  if (clean.length > MAX_LENGTH) return { pass: false, reason: "too_long", topics: [] };

  if (SPAM.some((pattern) => pattern.test(clean))) {
    return { pass: false, reason: "spam", topics: [] };
  }

  const topics = Object.entries(TOPIC_PATTERNS)
    .filter(([, pattern]) => pattern.test(clean))
    .map(([topic]) => topic);

  if (!topics.length) return { pass: false, reason: "no_topic", topics: [] };

  // Субподряд перебивает предложение: тот, кто отдаёт работу, — заказчик,
  // даже когда говорит о себе как об исполнителе. Проверяется первым, иначе
  // «наша команда перегружена, ищем подрядчиков» умирает на SUPPLY.
  const handoff = HANDOFF.some((pattern) => pattern.test(clean));

  // Предложение перебивает спрос: исполнитель, которому «нужен заказ», всё
  // равно исполнитель.
  if (!handoff && looksLikeSupply(clean)) {
    return { pass: false, reason: "supply", topics };
  }

  // Причина своя, а не «тема не найдена».
  //
  // Раньше здесь возвращалось no_topic — при том, что тема как раз нашлась,
  // не нашёлся спрос. Это поле уходит в журнал скаута и есть единственное,
  // по чему потом разбираются, почему лиды не доходят. Врущая причина уводит
  // разбор в противоположную сторону: человек начинает расширять темы, а
  // расширять надо было спрос.
  if (!handoff && !DEMAND.some((pattern) => pattern.test(clean))) {
    return { pass: false, reason: "no_demand", topics };
  }

  return { pass: true, reason: "candidate", topics };
}
