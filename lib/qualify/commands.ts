/**
 * Распознавание команд бота.
 *
 * Вынесено из обработчика вебхука ради одной проверки, которую там было не
 * сделать: файл маршрута не экспортирует ничего, кроме самого обработчика.
 *
 * История этого файла — реальная поломка. Команда входа сравнивалась с
 * «/login» как есть, а остальные команды приводились к нижнему регистру.
 * Клавиатура телефона сама делает первую букву заглавной, человек
 * отправляет «/Login», совпадения нет, бот молчит — и сотрудник видит не
 * «команда не распознана», а «вход в панель сломался». Ошибка невидима
 * ни в типах, ни при чтении кода: обе строки выглядят правильно, разница
 * в одном вызове, которого нет.
 */

/**
 * Команда входа в панель — в любом написании, которое может прислать
 * Telegram: с заглавной буквы от клавиатуры телефона и с дописанным именем
 * бота («/login@devuz_bot»), как Telegram делает в группах.
 */
export function loginCommand(text: string | undefined | null): boolean {
  return (text ?? "").trim().toLowerCase().startsWith("/login");
}
