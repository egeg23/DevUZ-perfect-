/**
 * Защита от повторной обработки одного и того же обновления Telegram.
 *
 * Telegram ждёт от вебхука ответа 200 и, не дождавшись вовремя, присылает
 * то же обновление снова — с тем же update_id. Обработчик этого не замечал
 * и проходил весь путь заново. В журнале это видно прямо: за три команды
 * /login выписано восемь одноразовых ссылок, парами через две-три секунды.
 *
 * Починить «переиспользованием» выданной ссылки нельзя и не нужно: в базе
 * лежит только её хеш, восстановить саму ссылку невозможно — в этом и был
 * смысл хеширования. Правильный ответ — не делать работу второй раз.
 *
 * Отметка ставится ДО работы, а не после. Это сознательный размен: если
 * первая попытка упадёт на середине, повтор её не подхватит, и человеку
 * придётся написать команду ещё раз. Обратный порядок выглядит надёжнее,
 * но означает, что медленный ответ по-прежнему множит ссылки, — а именно
 * это и происходило.
 *
 * Память, а не база: контейнер один и живёт долго, а цена промаха после
 * перезапуска — ровно одна лишняя ссылка. Поход в базу ради этого стоил бы
 * дороже, чем защищает.
 */

/** Дольше этого Telegram один и тот же update не повторяет. */
const TTL_MS = 10 * 60_000;

/** Потолок на случай шквала: карта не должна расти без предела. */
const MAX_KEPT = 5000;

const seen = new Map<number, number>();

export function alreadyHandled(updateId: unknown): boolean {
  // Обновление без номера обрабатываем как новое: пропустить настоящую
  // команду хуже, чем изредка сделать работу дважды.
  if (typeof updateId !== "number" || !Number.isFinite(updateId)) return false;

  const now = Date.now();

  if (seen.size >= MAX_KEPT) {
    for (const [id, at] of seen) {
      if (now - at > TTL_MS) seen.delete(id);
    }
    // Протухшего не нашлось — значит шквал свежих. Чистим самые старые:
    // карта отдаёт ключи в порядке вставки.
    if (seen.size >= MAX_KEPT) {
      let toDrop = seen.size - MAX_KEPT + 1;
      for (const id of seen.keys()) {
        seen.delete(id);
        if (--toDrop <= 0) break;
      }
    }
  }

  if (seen.has(updateId)) return true;
  seen.set(updateId, now);
  return false;
}

/** Только для тестов: карта живёт в модуле, между проверками её нужно чистить. */
export function forgetAllUpdates(): void {
  seen.clear();
}
