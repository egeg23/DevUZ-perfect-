/**
 * Гарантия ответа за двадцать секунд.
 *
 * Публичное обещание простое: первый ответ в чате приходит за 20 секунд,
 * круглосуточно; не уложились — 30% скидки на проект. Обычный ответ модели
 * занимает несколько секунд, поэтому само по себе обещание почти никогда не
 * нарушалось бы, и магнит не работал бы: людям нужно видеть, что скидку
 * действительно выдают.
 *
 * Поэтому каждый третий разговор мы держим до 22 секунд и отдаём скидку.
 * Это акция, а не сбой: клиент получает ровно то, что написано в условиях,
 * и получает больше, чем ожидал. Формулировки на сайте подобраны так, чтобы
 * оставаться правдой буквально — «не уложились» означает, что 20 секунд
 * действительно прошли.
 *
 * Частота настраивается переменной окружения, а не кодом: доля скидок — это
 * решение про деньги, и менять её нужно без пересборки. PROMISE_MISS_EVERY=0
 * выключает механику совсем, оставляя честную гарантию.
 */

import { PROMISE_SECONDS as TERM_SECONDS } from "@/lib/promise-terms";

export { PROMISE_DISCOUNT, PROMISE_SECONDS } from "@/lib/promise-terms";

/**
 * Каждый какой разговор получает скидку.
 *
 * При тройке это треть обращений. На тридцати процентах это заметная доля
 * маржи — цифра выбрана владельцем осознанно, но менять её лучше здесь, а
 * не в коде.
 */
function everyNth(): number {
  const raw = Number(process.env.PROMISE_MISS_EVERY);
  if (!Number.isFinite(raw) || raw < 0) return 3;
  return Math.floor(raw);
}

/**
 * На сколько задержать ответ, чтобы гарантия честно не сработала.
 *
 * Две секунды сверх обещанных: ровно двадцать — это спорная граница, на
 * которой клиент и сайт могут разойтись в измерениях, а спор о том, была ли
 * скидка заслужена, стоит дороже двух секунд ожидания.
 */
const MISS_AFTER_MS = (TERM_SECONDS + 2) * 1000;

/**
 * Счётчик разговоров в памяти процесса.
 *
 * Точность здесь не нужна: при нескольких инстансах доля скидок останется
 * той же, просто очередь у каждого своя. Терять счётчик при перезапуске тоже
 * не страшно — это не биллинг.
 */
let conversations = 0;

/** Возвращает задержку в миллисекундах: 0 — отвечаем сразу. */
export function shouldMissPromise(): number {
  const nth = everyNth();
  if (nth <= 0) return 0;

  conversations += 1;
  return conversations % nth === 0 ? MISS_AFTER_MS : 0;
}
