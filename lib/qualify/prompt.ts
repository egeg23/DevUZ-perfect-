/**
 * Справка о студии, собранная из тех же файлов, что и сайт.
 *
 * Смысл именно в сборке, а не в отдельном тексте: когда в content/cases.ts
 * добавится проект, ассистент узнает о нём в тот же деплой. Разъехавшаяся
 * копия портфолио в промпте — это ассистент, который врёт про экспертность.
 */
function studioFacts(): string {
  const serviceLines = services
    .map(
      (s) =>
        `- ${s.title.ru} (${s.slug}): ${s.tagline.ru}. Ориентир: от $${s.priceFromUsd}, ${s.weeksFrom}–${s.weeksTo} недель. Стек: ${s.tech.join(", ")}.`,
    )
    .join("\n");

  const caseLines = cases
    .map(
      (c) =>
        `- ${c.name} (${c.year}, Tier ${c.tier}): ${c.summary.ru} Ниши: ${c.niches.join(", ")}. Стек: ${c.tech.join(", ")}.`,
    )
    .join("\n");

  return `### Услуги\n${serviceLines}\n\n### Библиотека проектов\n${caseLines}`;
}

