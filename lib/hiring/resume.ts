/**
 * Разбор резюме: чистая часть.
 *
 * Владелец: «хочу новую вкладку — анализ кандидатов. Туда загружается PDF, и
 * ты выдаёшь такой же отчёт, как сделал ранее… это для оценки пригодности
 * сотрудника для работы у нас».
 *
 * Отчёт устроен так же, как тот, что писался руками: вердикт одной строкой,
 * разбор по задачам, сильные стороны, стопы, факты из резюме, вопросы на
 * собеседование и способ проверить делом. Разница одна — его пишет модель, и
 * поэтому здесь есть правила, которых у человека в голове не было нужды
 * проговаривать.
 *
 * ## Чего в оценке не будет
 *
 * Возраста, пола, семейного положения, национальности, внешности. Не из
 * вежливости: эти признаки ничего не говорят о том, справится ли человек с
 * работой, зато отлично умеют выглядеть объяснением — и решение, принятое по
 * ним, выглядит обоснованным, будучи предрассудком. В Узбекистане отказ по
 * таким основаниям вдобавок противоречит трудовому кодексу.
 *
 * Модель, читая резюме, видит и дату рождения, и имя, и пол — и без прямого
 * запрета неизбежно сошлётся на них хотя бы в интонации. Поэтому запрет
 * стоит в системном промпте первой строкой и проверяется машиной после.
 */

export type Verdict = "yes" | "conditional" | "no";

export const VERDICT_TEXT: Record<Verdict, string> = {
  yes: "брать",
  conditional: "брать с условием",
  no: "не брать",
};

export type ResumeReport = {
  /** Имя из резюме — чтобы карточку можно было найти. */
  name: string;
  /** На что человек претендует, по его же словам. */
  wants: string;
  verdict: Verdict;
  /** Вердикт одной фразой — то, что читают первым и часто единственным. */
  headline: string;
  /** Почему так: два-три предложения. */
  why: string;
  /**
   * Списки приходят от модели строками «Заголовок — пояснение», а хранятся
   * парами: разбирает их `cleanReport`. Причина в том, что массив объектов в
   * схеме инструмента живой прогон сломал — подробности там же.
   */
  strengths: { title: string; text: string }[];
  stops: { title: string; text: string }[];
  /** Факты из резюме, на которые опирается разбор. */
  facts: { label: string; value: string }[];
  /** Вопросы на собеседование — по одному на каждый стоп. */
  questions: { ask: string; why: string }[];
  /** Как проверить делом, а не разговором. */
  trial: string[];
};

