/**
 * Признаки, которых в разборе быть не должно.
 *
 * Просьба в системном промпте выполняется в девяти разборах из десяти, и
 * десятый — как раз тот, где вывод построен на возрасте. Поэтому после
 * модели идёт машина.
 *
 * Ищем слова, а не числа. Первая версия ловила «\d{2} лет» — и первый же
 * живой прогон отбила на фразе «четырнадцать лет оператором»: стаж в
 * резюме измеряется ровно теми же словами, что и возраст, и по числу их
 * не различить. Различить можно по контексту, а он у возраста всегда
 * словесный: «возраст», «года рождения», «41-летняя», «ей 41 год». Стаж
 * так не пишут.
 */
const FORBIDDEN = [
  /возраст/iu,
  /\d{2}\s*-\s*летн/iu,
  /(?:год|года)\s+рождени/iu,
  /(?:^|\P{L})родил[аси]\w*/iu,
  /(?:^|\P{L})(?:ей|ему|кандидат\w*)\s+\d{2}\s*(?:год|года|лет)(?!\p{L})/iu,
  /(?:^|\P{L})(?:женщин|мужчин|замужем|женат|холост|разведен|декрет)/iu,
  /(?:^|\P{L})(?:национальност|вероисповедан|гражданств)/iu,
];

export type ReportProblem = { code: string; text: string };

/**
 * Чего в разборе не хватает, чтобы его стоило показывать.
 *
 * Живой прогон дважды вернул разбор с верным вердиктом и пустыми списками:
 * вступление написано, а сильные стороны, стопы, вопросы и проба — нет.
 * Показать такое нанимающему значит выдать за разбор его оглавление.
 *
 * `required` в схеме инструмента этого не ловит: он описывает форму, а не
 * содержание, и пустой массив ему не противоречит.
 */
export function reportProblems(report: ResumeReport): ReportProblem[] {
  const out: ReportProblem[] = [];
  if (!report.strengths.length) out.push({ code: "no_strengths", text: "не названо ни одной сильной стороны" });
  if (!report.stops.length) out.push({ code: "no_stops", text: "не названо ни одного стопа" });
  if (!report.facts.length) out.push({ code: "no_facts", text: "не выписано ни одного факта из резюме" });
  if (!report.questions.length) out.push({ code: "no_questions", text: "нет вопросов на собеседование" });
  if (!report.trial.length) out.push({ code: "no_trial", text: "не сказано, как проверить делом" });
  return out;
}

/** Что нашлось запретного — словами, чтобы это можно было показать. */
export function forbiddenGrounds(report: ResumeReport): string[] {
  const text = [
    report.headline,
    report.why,
    ...report.strengths.flatMap((s) => [s.title, s.text]),
    ...report.stops.flatMap((s) => [s.title, s.text]),
    ...report.questions.flatMap((q) => [q.ask, q.why]),
  ].join(" ");

  const found: string[] = [];
  for (const re of FORBIDDEN) {
    const hit = text.match(re);
    if (hit) found.push(hit[0].trim());
  }
  return [...new Set(found)];
}

/**
 * Разбор строк вида «Заголовок — пояснение».
 *
 * Списки приходят строками, а не объектами. Первая версия схемы просила у
 * модели массив объектов `{title, text}` — и живой прогон показал, во что это
 * превращается: ответ пришёл пятнадцатью блоками вместо одного, а поле
 * `strengths` — строкой с `<parameter name="title">` внутри. Восемь тысяч
 * токенов ушли в эту кашу целиком.
 *
 * Плоский список строк такого не делает, а пара «заголовок — пояснение»
 * восстанавливается здесь и стоит одну строку кода.
 */
/** Докуда ищем разделитель заголовка. Дальше тире — часть предложения. */
const HEAD_MAX = 60;

function asLines(v: unknown, max: number): string[] {
  /**
   * Список может прийти чем угодно, и это не теория.
   *
   * Живые прогоны показали три формы подряд. Массив объектов `{title, text}`
   * развалил ответ на пятнадцать блоков, а поле пришло строкой с
   * `<parameter name="title">` внутри. Массив строк пришёл одной строкой, где
   * пункты склеены тем же тире, которым внутри пункта отделён заголовок, — и
   * разделить их было уже нечем. Массив строк приходит и как задумано.
   *
   * Поэтому здесь принимается всё три формы, а пункты разделяются переводом
   * строки: он не совпадает ни с чем внутри пункта, в отличие от тире.
   */
  const lines: string[] = [];
  const push = (raw: string) => {
    for (const part of raw.split(/\r?\n+/)) {
      const line = part.replace(/^\s*[-*•]\s*/, "").trim();
      if (line) lines.push(line);
    }
  };

  if (typeof v === "string") push(v);
  else if (Array.isArray(v)) {
    for (const item of v) {
      if (typeof item === "string") push(item);
      else if (item && typeof item === "object") {
        // Объект — склеиваем его значения в ту же форму «заголовок — текст».
        const vals = Object.values(item as Record<string, unknown>).filter((x) => typeof x === "string");
        if (vals.length) push(vals.join(" — "));
      }
    }
  }
  return lines.slice(0, max);
}

function splitPairs(v: unknown, a: string, b: string, max: number, sep: RegExp): Record<string, string>[] {
  return asLines(v, max).map((line) => {
    const at = line.search(sep);
    /**
     * Делим только там, где тире действительно разделяет заголовок.
     *
     * Заголовок короток и цельн: «Опыт входящей линии — четырнадцать лет у
     * оператора». Тире посреди предложения выглядит так же, но перед ним
     * стоит запятая или строка уже длинна. Живой прогон это и показал:
     * «Целится на руководителя отдела, вакансия — рядовой менеджер»
     * разрезалось по этому тире, и в заголовок ушла половина мысли.
     *
     * Отсюда два условия: разделитель в начале строки и без запятой перед
     * ним. Не сошлось — строка остаётся целой, и это не потеря: карточка
     * просто без подзаголовка.
     */
    const head0 = at < 0 ? "" : line.slice(0, at);
    const split = at >= 0 && at <= HEAD_MAX && !head0.includes(",");
    const head = split ? line.slice(0, at) : line;
    const tail = split ? line.slice(at).replace(sep, "") : "";
    return { [a]: head.trim().slice(0, 200), [b]: tail.trim().slice(0, 900) };
  });
}

/**
 * Привести ответ модели к тому, что можно показать и сохранить.
 *
 * Вход — `unknown`, и это не лень типизации, а правда: модель возвращает
 * списки то массивом строк, то одной строкой, то массивом объектов, и
 * обещать здесь `Partial<ResumeReport>` значило бы соврать про форму. Всё,
 * что известно наверняка, проверяется ниже руками.
 */
export function cleanReport(input: unknown): ResumeReport | null {
  if (!input || typeof input !== "object") return null;
  const raw = input as Record<string, unknown>;

  const text = (v: unknown, max = 900): string => (typeof v === "string" ? v.trim().slice(0, max) : "");

  const verdict: Verdict =
    raw.verdict === "yes" || raw.verdict === "no" || raw.verdict === "conditional" ? raw.verdict : "conditional";

  const headline = text(raw.headline, 300);
  if (!headline) return null;

  const DASH = /\s+[—–-]\s+/;
  return {
    name: text(raw.name, 200) || "Без имени",
    wants: text(raw.wants, 300),
    verdict,
    headline,
    why: text(raw.why, 1200),
    strengths: splitPairs(raw.strengths, "title", "text", 6, DASH) as ResumeReport["strengths"],
    stops: splitPairs(raw.stops, "title", "text", 6, DASH) as ResumeReport["stops"],
    facts: splitPairs(raw.facts, "label", "value", 10, /:\s+/) as ResumeReport["facts"],
    questions: splitPairs(raw.questions, "ask", "why", 6, DASH) as ResumeReport["questions"],
    trial: asLines(raw.trial, 5),
  };
}
