import type { Locale } from "@/lib/i18n";

/**
 * На каком языке с нами говорят.
 *
 * Владелец: «общение первичкой надо всё-таки делать на двух языках — у нас
 * рынок Узбекистана, и нам отвечают на узбекском».
 *
 * Поводом была не догадка, а переписка. За день пришло двенадцать входящих:
 * два настоящих ответа по-русски, девять — меню чужого бота, и одно слово
 * «Kerskmas» с сайта alfraganus.uz. Это «kerakmas» с опечаткой — «не нужно».
 * Разобрали мы его как «продолжай разговор», и модель написала ответ; спас
 * случай — ответ не прошёл проверку по другой причине. Написать второй раз
 * человеку, который отказал, — ровно то, за что Telegram ограничивает
 * аккаунт, а этим же аккаунтом скаут читает чаты.
 *
 * Поэтому язык здесь определяется не ради вежливости, а чтобы услышать
 * отказ.
 *
 * ## Почему не библиотека
 *
 * Готовые определители языка на двух словах ошибаются, а у нас именно такие
 * сообщения и решают: «Kerakmas», «Ha», «Yo'q». Зато у узбекского есть то,
 * чего нет у русского: четыре буквы в кириллице (қ ў ғ ҳ) и апостроф в
 * латинице (oʻ, g‘). По ним двух слов хватает.
 */

/** Буквы, которых в русском нет вовсе. Одна такая — и вопрос закрыт. */
const UZ_CYRILLIC_ONLY = /[қўғҳ]/i;

/**
 * Частые узбекские слова — латиницей.
 *
 * Список короткий намеренно: сюда попало только то, что встречается в
 * деловой переписке и не совпадает с английским. «Bor» и «ha» не взяты —
 * слишком коротки и ловят случайные совпадения.
 */
const UZ_LATIN_WORDS =
  /(?:^|[^a-z])(?:kerak|emas|yo['ʻ‘`]?q|rahmat|salom|assalom|qancha|narx|yaxshi|qanday|qachon|nima|bo['ʻ‘`]?l\w*|uchun|bilan|qil\w+|sayt\w*|siz|iltimos|marhamat|xayr|gaplash\w*|kel\w+|ber\w+|ayt\w+|tushun\w+|xizmat\w*|mijoz\w*|so['ʻ‘`]?m)(?:$|[^a-z])/i;

/**
 * Частые узбекские слова — кириллицей, для тех, кто пишет по-старому.
 *
 * Ни одного слова, которое есть и в русском. Первая версия списка включала
 * «сайт» — и всякое русское письмо со словом «сайт», а у нас других почти не
 * бывает, определялось бы как узбекское.
 */
const UZ_CYRILLIC_WORDS =
  /(?:^|[^а-яё])(?:керак|эмас|йў|рахмат|салом|қанча|яхши|қандай|качон|нима|учун|билан|илтимос)(?:$|[^а-яё])/i;

/** Английские слова, по которым отличаем латиницу английскую от узбекской. */
const EN_WORDS =
  /(?:^|[^a-z])(?:the|and|you|your|we|our|for|with|please|thanks|thank|hello|hi|price|cost|website|site|need|want|can|could|would|about|from|have)(?:$|[^a-z])/i;

const CYRILLIC = /[а-яёқўғҳ]/gi;
const LATIN = /[a-z]/gi;

/**
 * Язык сообщения.
 *
 * Возвращает только то, на чём студия действительно говорит первой линией.
 * Китайский сюда не попадает намеренно: на сайте он есть, а в холодных
 * касаниях по Узбекистану — нет, и добавлять ветку без единого живого
 * примера значило бы угадывать.
 */
export function detectLang(text: string): Extract<Locale, "ru" | "uz" | "en"> {
  const body = String(text ?? "").slice(0, 2000);
  if (!body.trim()) return "ru";

  // Узбекская буква в кириллице — однозначный ответ, спорить не о чем.
  if (UZ_CYRILLIC_ONLY.test(body)) return "uz";

  const cyr = (body.match(CYRILLIC) ?? []).length;
  const lat = (body.match(LATIN) ?? []).length;

  // Кириллица: узбекская, если встретилось узбекское слово, иначе русская.
  // Проверки на «русские буквы» здесь нет намеренно: «э» и «ъ» в узбекской
  // кириллице есть и работают вовсю — «эмас», «эди», «маъно», — и первая
  // версия из-за них читала «Керак эмас» как русский.
  if (cyr > lat) return UZ_CYRILLIC_WORDS.test(body) ? "uz" : "ru";

  if (lat === 0) return "ru";

  // Латиница. Апостроф в oʻ/g‘ — узбекская примета, в английском его так не
  // ставят.
  if (/[a-z][ʻ‘'`][a-z]/i.test(body) && !EN_WORDS.test(body)) return "uz";

  const uz = UZ_LATIN_WORDS.test(body);
  const en = EN_WORDS.test(body);
  if (uz && !en) return "uz";
  if (en && !uz) return "en";

  /**
   * Ни одной приметы — считаем узбекским.
   *
   * Сторона ошибки выбрана намеренно. Мы пишем компаниям Узбекистана; текст
   * латиницей от них — это узбекский куда чаще, чем английский. И цена
   * ошибки разная: ответить по-узбекски тому, кто писал по-английски,
   * неловко, а ответить по-английски узбеку — как не услышать.
   *
   * Именно этот случай и был живым: «Kerskmas» — опечатка, ни одной приметы,
   * и без такого умолчания сообщение ушло бы в английский.
   */
  return "uz";
}

/**
 * Язык разговора по всей ленте.
 *
 * Считаем по тому, что писал клиент, и по последнему весомее: человек мог
 * начать по-русски и перейти на узбекский, увидев, что мы понимаем. Наши
 * собственные реплики не в счёт — иначе разговор навсегда останется на том
 * языке, на котором мы его начали.
 */
export function talkLang(
  thread: readonly { direction: "in" | "out"; body: string }[],
): Extract<Locale, "ru" | "uz" | "en"> {
  const theirs = thread.filter((m) => m.direction === "in" && m.body.trim());
  if (!theirs.length) return "ru";

  const last = detectLang(theirs[theirs.length - 1].body);
  if (theirs.length === 1) return last;

  // Последнее сообщение весит столько же, сколько все прежние вместе: так
  // переход на другой язык подхватывается сразу, а одна случайная реплика
  // не переворачивает разговор.
  const tally = new Map<string, number>([[last, theirs.length - 1]]);
  for (const m of theirs.slice(0, -1)) {
    const lang = detectLang(m.body);
    tally.set(lang, (tally.get(lang) ?? 0) + 1);
  }

  let best = last;
  let bestScore = -1;
  for (const [lang, score] of tally) {
    if (score > bestScore) {
      best = lang as Extract<Locale, "ru" | "uz" | "en">;
      bestScore = score;
    }
  }
  return best;
}
