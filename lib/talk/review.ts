/**
 * Надзиратель над перепиской: чистая часть.
 *
 * Владелец: «можно чтобы чаты в скауте мониторились арбитром или
 * надзирателем, на основании ответов клиентов строились разные подходы к
 * общению… в идеале самообучающаяся модель».
 *
 * Здесь только то, что считается без базы и без сети: как назвать исход, что
 * спросить у модели и как проверить её ответ. Сам вызов — в review-run.ts,
 * запросы — в review-store.ts. Разделение то же, что у остальной переписки, и
 * по той же причине: разбор, который нельзя прогнать тестом, проверяется
 * только в бою.
 *
 * ## Чего здесь нет
 *
 * Оценки в баллах. Соблазн поставить разговору «7 из 10» велик, и число
 * выглядит убедительно — но сравнивать такие числа между разговорами нельзя,
 * а складывать тем более: модель ставит их по ощущению, а не по шкале.
 * Вместо балла — четыре вопроса, на каждый из которых есть ответ в самом
 * тексте переписки, и признание «не уверен», когда ответа нет.
 */

export type TalkOutcome = "refused" | "asked_human" | "qualified" | "stalled" | "talking";

export const OUTCOME_TEXT: Record<TalkOutcome, string> = {
  refused: "отказался",
  asked_human: "позвал человека",
  qualified: "первичка закрыта",
  stalled: "разговор заглох",
  talking: "ещё идёт",
};

/**
 * Чем кончился разговор — по базе, а не со слов модели.
 *
 * Спрашивать об этом ту же модель, которая разговор вела, незачем: исход мы
 * знаем точно. У модели спрашиваем только то, чего в базе нет, — почему.
 */
export function outcomeOf(input: {
  aiHandling: boolean;
  handoverReason: string | null;
  turns: number;
}): TalkOutcome {
  if (input.aiHandling) return "talking";

  const why = (input.handoverReason ?? "").toLowerCase();
  if (why.includes("не писать")) return "refused";
  if (why.includes("просит человека")) return "asked_human";
  if (why.includes("первичка закрыта")) return "qualified";
  return "stalled";
}

