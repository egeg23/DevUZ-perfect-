/** Что показываем модели. Лента как есть, без пересказа. */
export function reviewPrompt(input: {
  host: string;
  niche: string | null;
  lang: string;
  outcome: TalkOutcome;
  thread: readonly { direction: "in" | "out"; body: string }[];
}): string {
  const talk = input.thread
    .map((m) => `${m.direction === "out" ? "МЫ" : "КЛИЕНТ"}: ${m.body.trim()}`)
    .join("\n\n");

  return [
    `Сайт: ${input.host}`,
    input.niche ? `Ниша: ${input.niche}` : "",
    `Язык переписки: ${input.lang}`,
    `Чем кончилось: ${OUTCOME_TEXT[input.outcome]}.`,
    "",
    "Переписка целиком:",
    "",
    talk,
    "",
    "Разбери её.",
  ]
    .filter(Boolean)
    .join("\n");
}

/**
 * Проверка разбора перед тем, как класть его в копилку.
 *
 * Модель, которую попросили сделать вывод, сделает его всегда — даже из
 * одной реплики. Поэтому уверенность проверяется не по её слову, а по длине
 * разговора: меньше двух реплик клиента — урок стирается, чем бы модель его
 * ни обосновала.
 */
export function cleanReview(raw: Partial<Review> | null, turns: number, host = ""): Review {
  const text = (v: unknown): string => (typeof v === "string" ? v.trim().slice(0, 600) : "");

  const enough = turns >= ENOUGH_TURNS;
  const lesson = enough && !aboutThisClient(text(raw?.lesson), host) ? text(raw?.lesson) : "";
  // Уверенность падает вместе с уроком: разбор без урока — это наблюдение, а
  // не вывод, и помечать его высокой уверенностью значит врать счётчику.
  const confidence = lesson && raw?.confidence === "high" ? "high" : "low";

  return {
    hook: text(raw?.hook),
    objection: text(raw?.objection),
    failed: text(raw?.failed),
    lesson,
    confidence,
  };
}

/**
 * Урок про этого клиента — не урок, а задача.
 *
 * Первый же живой разбор это и выдал: по gh.uz надзиратель написал
 * «отправляй разбор на info@gh.uz, адресуй отделу маркетинга». Выполнимо,
 * верно и совершенно бесполезно — следующему адресату это не говорит ничего,
 * а в копилке будет выглядеть как вывод.
 *
 * Правило в промпте про «подставь другую компанию» модель выполняет не
 * всегда, поэтому здесь машинная проверка: домен адресата, почта и @адрес в
 * тексте урока означают, что он написан про одного человека. Такой урок
 * стирается; наблюдения при этом остаются — они и должны быть про этот
 * разговор.
 */
function aboutThisClient(lesson: string, host: string): boolean {
  if (!lesson) return false;

  const body = lesson.toLowerCase();
  if (/\S+@\S+\.\w+/.test(body)) return true;
  if (/(?:^|[^a-z0-9])@[a-z0-9_]{3,}/i.test(body)) return true;

  const domain = host.toLowerCase().replace(/^www\./, "");
  if (domain && body.includes(domain)) return true;
  // И голое имя домена без зоны: «gh.uz» превращается в «gh», а «намуна» в
  // уроке про namuna.uz — это всё ещё про namuna.
  const name = domain.split(".")[0];
  if (name.length >= 4 && body.includes(name)) return true;

  return false;
}
