import { inventedNumbers, bannedPhrase } from "@/lib/admin/outreach";
import type { ChatMessage } from "@/lib/qualify/types";

/**
 * Переписка по холодному касанию: чистая часть.
 *
 * Владелец: «пусть ИИ подхватывает первичку, если она найдена через поиск,
 * и ведёт переписку по лиду. Но лид фиксируется за тем, кто нажал кнопку с
 * отправкой сообщения».
 *
 * Отсюда разделение, которое держится на всём пути: переписку ведёт модель,
 * а лид принадлежит человеку. Модель пишет с того же рабочего аккаунта, с
 * которого ушло первое сообщение, — для адресата это один собеседник, и
 * второй голос в том же диалоге выглядел бы как передача из рук в руки без
 * объяснения. `assigned_staff_id` при этом не меняется нигде: ни один путь
 * в коде не переназначает лид касания.
 *
 * Здесь только то, что считается без базы и без сети.
 */

/** Максимум реплик модели в одном разговоре. */
export const MAX_AI_REPLIES = 12;

/** Длина ответа: Telegram режет длинное, а на телефоне и это много. */
export const MAX_REPLY_CHARS = 1200;

/**
 * Адрес в общем виде.
 *
 * Входящее приходит от `@Ivan`, а в проспекте лежит `ivan` или
 * `https://t.me/Ivan` — и если сравнивать как есть, ответ клиента не найдёт
 * своего разговора и модель промолчит.
 */
export function normalizeHandle(raw: string | null | undefined): string {
  if (!raw) return "";
  const trimmed = String(raw).trim();
  // Схема необязательна: в контактах сайта ссылка чаще написана как
  // «t.me/ivan», без http. С обязательным http такой адрес оставался целым,
  // и ответ клиента не находил своего разговора.
  const path = trimmed.replace(/^(?:https?:\/\/)?(?:www\.)?t(?:elegram)?\.me\//i, "");
  return path.replace(/^@/, "").split(/[/?#]/)[0].toLowerCase();
}

export type TalkRow = {
  direction: "in" | "out";
  body: string;
};

/** Лента переписки в том виде, в каком её читает модель. */
export function asTranscript(rows: readonly TalkRow[]): ChatMessage[] {
  return rows.map((row) => ({
    role: row.direction === "in" ? ("user" as const) : ("assistant" as const),
    content: row.body,
  }));
}

/**
 * Что делать со входящим.
 *
 * Три исхода, и только один из них — «отвечай». Просьбу не писать модель не
 * обсуждает: любое следующее сообщение человеку, который попросил
 * отстать, — это уже то, из-за чего аккаунты и блокируют. Просьбу позвать
 * человека модель тоже не перехватывает: «сейчас позову менеджера» и
 * продолжение расспросов — самый быстрый способ потерять доверие.
 */
export type InboundVerdict = "stop" | "human" | "talk";

const STOP_WORDS = [
  /не\s+пиш/i,
  /не\s+писать/i,
  /отстань/i,
  /отвали/i,
  /спам/i,
  /жалоб/i,
  /заблокир/i,
  /отпиш/i,
  /unsubscribe/i,
  /stop\s+writing/i,
];

const HUMAN_WORDS = [
  /позвон/i,
  /перезвон/i,
  /созвон/i,
  /свяж[ие]те/i,
  /дайте\s+номер/i,
  /номер\s+телефона/i,
  /с\s+менеджером/i,
  /с\s+человеком/i,
  /живо[йг]о?\s+человек/i,
  /встрет/i,
];

export function readInbound(text: string): InboundVerdict {
  const body = text.trim();
  if (STOP_WORDS.some((re) => re.test(body))) return "stop";
  if (HUMAN_WORDS.some((re) => re.test(body))) return "human";
  return "talk";
}

