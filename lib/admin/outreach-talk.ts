import { inventedNumbers, bannedPhrase } from "@/lib/admin/outreach";
import type { ChatMessage } from "@/lib/qualify/types";

/**
 * Переписка по холодному касанию: чистая часть.
 *
 * Владелец: «пусть ИИ подхватывает первичку, если она найдена через поиск,
 * и ведёт переписку по лиду. Но лид фиксируется за тем, кто нажал кнопку с
 * отправкой сообщения».
 *
 * Отсюда разделение, которое держится на всём пути: переписку ведёт модель,
 * а лид принадлежит человеку. Модель пишет с того же рабочего аккаунта, с
 * которого ушло первое сообщение, — для адресата это один собеседник, и
 * второй голос в том же диалоге выглядел бы как передача из рук в руки без
 * объяснения. `assigned_staff_id` при этом не меняется нигде: ни один путь
 * в коде не переназначает лид касания.
 *
 * Здесь только то, что считается без базы и без сети.
 */

/** Максимум реплик модели в одном разговоре. */
export const MAX_AI_REPLIES = 12;

/** Длина ответа: Telegram режет длинное, а на телефоне и это много. */
export const MAX_REPLY_CHARS = 1200;

/**
 * Адрес в общем виде.
 *
 * Входящее приходит от `@Ivan`, а в проспекте лежит `ivan` или
 * `https://t.me/Ivan` — и если сравнивать как есть, ответ клиента не найдёт
 * своего разговора и модель промолчит.
 */
export function normalizeHandle(raw: string | null | undefined): string {
  if (!raw) return "";
  const trimmed = String(raw).trim();
  // Схема необязательна: в контактах сайта ссылка чаще написана как
  // «t.me/ivan», без http. С обязательным http такой адрес оставался целым,
  // и ответ клиента не находил своего разговора.
  const path = trimmed.replace(/^(?:https?:\/\/)?(?:www\.)?t(?:elegram)?\.me\//i, "");
  return path.replace(/^@/, "").split(/[/?#]/)[0].toLowerCase();
}

export type TalkRow = {
  direction: "in" | "out";
  body: string;
};

/** Лента переписки в том виде, в каком её читает модель. */
export function asTranscript(rows: readonly TalkRow[]): ChatMessage[] {
  return rows.map((row) => ({
    role: row.direction === "in" ? ("user" as const) : ("assistant" as const),
    content: row.body,
  }));
}

/**
 * Что делать со входящим.
 *
 * Три исхода, и только один из них — «отвечай». Просьбу не писать модель не
 * обсуждает: любое следующее сообщение человеку, который попросил
 * отстать, — это уже то, из-за чего аккаунты и блокируют. Просьбу позвать
 * человека модель тоже не перехватывает: «сейчас позову менеджера» и
 * продолжение расспросов — самый быстрый способ потерять доверие.
 */
export type InboundVerdict = "stop" | "human" | "send" | "unclear" | "talk";

const STOP_WORDS = [
  /не\s+пиш/i,
  /не\s+писать/i,
  /не\s+интересует/i,
  /не\s+интересно/i,
  /не\s*на[дт]о/i,
  /не\s+нужн/i,
  /отстань/i,
  /отвали/i,
  /спам/i,
  /жалоб/i,
  /заблокир/i,
  /отпиш/i,
  /unsubscribe/i,
  /stop\s+writing/i,
  /not\s+interested/i,
  /**
   * Узбекский отказ.
   *
   * Всё это писали бы нам вместо «не нужно»: kerak emas / kerakmas —
   * «не нужно», qiziqmaymiz — «не интересует», yozmang — «не пишите».
   * Апостроф в yo‘q пишут четырьмя разными знаками, поэтому он в скобках, а
   * не буквой.
   */
  /kerak\s*emas/i,
  /kerakmas/i,
  /qiziq(?:mayman|maymiz|miz\s*emas)/i,
  /yozman?g/i,
  /bezovta\s*qilmang/i,
  /(?:^|[^a-z])yo['ʻ‘`]?q\s*rahmat/i,
  /(?:^|[^а-яё])керак\s*эмас/i,
  /(?:^|[^а-яё])кераксиз/i,
];

const HUMAN_WORDS = [
  /позвон/i,
  /перезвон/i,
  /созвон/i,
  /свяж[ие]те/i,
  /дайте\s+номер/i,
  /номер\s+телефона/i,
  /с\s+менеджером/i,
  /с\s+человеком/i,
  /живо[йг]о?\s+человек/i,
  /встрет/i,
  // Узбекский: «позвоните», «поговорим», «с менеджером», «встретимся».
  /qo['ʻ‘`]?ng['ʻ‘`]?iroq/i,
  /telefon\s*qil/i,
  /gaplash(?:amiz|sak|aylik)/i,
  /menejer\s*bilan/i,
  /uchrash/i,
  /(?:^|[^а-яё])қўнғироқ/i,
];

/**
 * Просьба что-то прислать — разбор, смету, предложение, на почту.
 *
 * Разбор заглохших переписок: человек написал, куда прислать разбор, модель
 * ответила «хорошо, подготовлю и пришлю» — и не прислал никто. Модель сама
 * ничего не отправит, а обещание, которое не сдержали, хуже молчания.
 * Поэтому такая просьба сразу уходит менеджеру, как просьба позвонить.
 */
const SEND_WORDS = [
  /пришл(?:и|ите)/i,
  /скин(?:ь|ьте|ете)/i,
  /отправ(?:ь|ьте)/i,
  /на\s+почту/i,
  /на\s+(?:e-?mail|имейл|емейл)/i,
  /коммерческ\p{L}*\s+предложени/iu,
  /(?:^|[^\p{L}])кп(?:[^\p{L}]|$)/iu,
  /[\w.+-]+@[\w-]+\.[\w.-]+/,
  // Узбекский: «пришлите», «скиньте», «на почту».
  /yubor(?:ing|ib|asiz|sangiz)/i,
  /tashlab\s*(?:bering|yubor)/i,
  /pochta/i,
  /(?:^|[^а-яё])юборинг/i,
];

/**
 * Сколько слов делают ответ понятным.
 *
 * Меньше — и мы не знаем, что нам сказали. «Kerskmas» с сайта
 * alfraganus.uz — одно слово с опечаткой, и ни одно правило его не ловит:
 * «kerakmas» тут написано через «с». Разобрали как «продолжай разговор», и
 * модель написала ответ человеку, который отказал.
 *
 * Отсюда правило: короткий ответ без вопроса моделью не обрабатывается.
 * В холодной переписке два слова без вопросительного знака — это почти
 * всегда отговорка, а не начало разговора, и цена ошибки несимметрична:
 * промолчать и отдать человеку стоит минуты его времени, а написать в ответ
 * на отказ стоит аккаунта.
 */
const SHORT_WORDS = 3;

export function readInbound(text: string): InboundVerdict {
  const body = text.trim();
  if (STOP_WORDS.some((re) => re.test(body))) return "stop";
  if (HUMAN_WORDS.some((re) => re.test(body))) return "human";
  if (SEND_WORDS.some((re) => re.test(body))) return "send";

  // Вопрос — это начало разговора на любом языке и любой длины: «Qancha
  // turadi?» короче трёх слов, но отвечать на него надо.
  if (body.includes("?") || body.includes("؟")) return "talk";

  const words = body.split(/\s+/).filter(Boolean).length;
  return words <= SHORT_WORDS ? "unclear" : "talk";
}

