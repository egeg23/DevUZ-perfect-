export type ReplyProblem = { code: string; text: string };

/**
 * Проверка ответа модели перед отправкой.
 *
 * Правила первого касания здесь не годятся: домен и адрес студии в третьей
 * реплике диалога выглядят как повтор заученного. А вот две вещи остаются
 * ровно теми же. Число, которого нет ни в анализе, ни в разговоре, ни в
 * прайсе, — это выдумка, и адресат поймает её первым же уточнением. И
 * запрещённые обороты запрещены не в первом сообщении, а вообще: «выведем
 * в топ» одинаково врёт и в первой реплике, и в десятой.
 *
 * Не прошло — не отправляем и зовём человека. Молча проглотить плохой
 * ответ нельзя: разговор оборвётся на нашей реплике, и клиент решит, что
 * им перестали заниматься.
 */
export function replyProblems(reply: string, facts: string): ReplyProblem[] {
  const problems: ReplyProblem[] = [];
  const body = reply.trim();

  if (!body) {
    problems.push({ code: "empty", text: "Модель не написала ответа." });
    return problems;
  }
  if (body.length > MAX_REPLY_CHARS) {
    problems.push({ code: "long", text: `Ответ длиннее ${MAX_REPLY_CHARS} знаков — на телефоне такое не читают.` });
  }

  const invented = inventedNumbers(body, facts);
  if (invented.length) {
    problems.push({ code: "invented", text: `Числа, которых нет ни в анализе, ни в разговоре: ${invented.join(", ")}.` });
  }
  if (bannedPhrase(body)) {
    problems.push({ code: "banned", text: "В ответе есть обещание или знак, которых у нас не бывает: «в топ», «гарантируем», проценты, «комплексный подход», эмодзи." });
  }
  return problems;
}

/**
 * Приписка к системному промпту под этот канал.
 *
 * Движок первички один на все каналы — сайт, бот и теперь касания. Разница
 * между ними и живёт в этой приписке. Для касания она отвечает на четыре
 * вопроса, без которых модель неизбежно соврёт: кто написал первым (мы, а
 * не клиент), что мы уже сказали, от чьего имени идёт переписка и кому
 * достанется разговор дальше.
 */
export function talkNote(input: {
  host: string;
  label: string | null;
  findings: readonly { title: string; impact: string }[];
  firstMessage: string;
  managerName: string;
  repliesSoFar: number;
}): string {
  const findings = input.findings.length
    ? input.findings.map((f) => `- ${f.title}: ${f.impact}`).join("\n")
    : "- разбор не сохранился, новых находок не выдумывай";

  return `## Этот разговор — ответ на наше письмо, а не обращение клиента

Первыми написали мы. Человек ничего у нас не спрашивал и заявку не оставлял: мы разобрали его сайт ${input.host}${input.label ? ` (${input.label})` : ""} и написали ему в Telegram с рабочего аккаунта студии. Он ответил — этот ответ ты и читаешь.

Что это меняет:

- Не здоровайся как с новым человеком и не представляйся заново: он уже прочитал наше письмо и знает, кто пишет.
- Не благодари за обращение. Обращения не было.
- Первый вопрос — не «чем можем помочь», а продолжение того, о чём мы ему написали.
- Он может ответить холодно, коротко или раздражённо. Это нормально для письма, которого не ждали. Не дави и не уговаривай: одна попытка объяснить, зачем мы написали, и дальше по его реакции.

### Что мы нашли на его сайте

${findings}

Эти находки — единственные проверенные факты о его сайте, которые у тебя есть. Ничего, кроме них, ты не измеряла. Не называй ни одной цифры про его сайт, которой нет выше.

### Что мы ему уже написали

"""
${input.firstMessage}
"""

Не повторяй это своими словами — он это читал.

### Кому принадлежит разговор

Лид закреплён за менеджером по имени ${input.managerName}. Ты ведёшь первичку вместо него и от общего имени студии — «мы», а не «я, ассистент». Своё имя не называй и менеджера по имени не называй тоже: для человека по ту сторону это один и тот же собеседник. Когда первичка закончится, разговор продолжит ${input.managerName} с этого же аккаунта.

Ты написала в этом разговоре реплик: ${input.repliesSoFar} из ${MAX_AI_REPLIES}. Разговор, который не сошёлся за это число, дальше не сойдётся — заканчивай и передавай человеку.`;
}
