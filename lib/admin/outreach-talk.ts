/**
 * Просьба что-то прислать — разбор, смету, предложение, на почту.
 *
 * Разбор заглохших переписок: человек написал, куда прислать разбор, модель
 * ответила «хорошо, подготовлю и пришлю» — и не прислал никто. Модель сама
 * ничего не отправит, а обещание, которое не сдержали, хуже молчания.
 * Поэтому такая просьба сразу уходит менеджеру, как просьба позвонить.
 */
const SEND_WORDS = [
  /пришл(?:и|ите)/i,
  /скин(?:ь|ьте|ете)/i,
  /отправ(?:ь|ьте)/i,
  /на\s+почту/i,
  /на\s+(?:e-?mail|имейл|емейл)/i,
  /коммерческ\p{L}*\s+предложени/iu,
  /(?:^|[^\p{L}])кп(?:[^\p{L}]|$)/iu,
  /[\w.+-]+@[\w-]+\.[\w.-]+/,
  // Узбекский: «пришлите», «скиньте», «на почту».
  /yubor(?:ing|ib|asiz|sangiz)/i,
  /tashlab\s*(?:bering|yubor)/i,
  /pochta/i,
  /(?:^|[^а-яё])юборинг/i,
];

/**
 * Ответ на предложение прототипа.
 *
 * Первое письмо заканчивается вопросом «собрать вам прототип за 12 часов?»
 * (lib/admin/outreach.ts, PROTOTYPE_HOURS). Модель прототип не соберёт, а
 * «да, соберём» от неё — обещание, которое некому сдержать. Поэтому любое
 * упоминание прототипа и «соберите» сразу уходят человеку: отсчёт двенадцати
 * часов пошёл с этой минуты. Стоит раньше «пришлите»: «пришлите прототип» —
 * это согласие, а не просьба о файле.
 */
const PROTO_WORDS = [
  /прототип/i,
  /prototip/i,
  /prototype/i,
  // Макет предлагает письмо с разбором — так его и называют в ответ.
  /макет/i,
  /maket/i,
  /mock-?up/i,
  /собер(?:и|ите|ёте|ете)(?!\p{L})/iu,
  /yig['ʻ‘`]?ib\s*ber/i,
];

/**
 * Сколько слов делают ответ понятным.
 *
 * Меньше — и мы не знаем, что нам сказали. «Kerskmas» с сайта
 * alfraganus.uz — одно слово с опечаткой, и ни одно правило его не ловит:
 * «kerakmas» тут написано через «с». Разобрали как «продолжай разговор», и
 * модель написала ответ человеку, который отказал.
 *
 * Отсюда правило: короткий ответ без вопроса моделью не обрабатывается.
 * В холодной переписке два слова без вопросительного знака — это почти
 * всегда отговорка, а не начало разговора, и цена ошибки несимметрична:
 * промолчать и отдать человеку стоит минуты его времени, а написать в ответ
 * на отказ стоит аккаунта.
 */
const SHORT_WORDS = 3;

/**
 * «+» — согласие на макет.
 *
 * Письмо с разбором кончается предложением собрать макет. Плюсом не
 * отказывают и не задают вопросов, поэтому он значит «да». Плюс на кружок —
 * другое: кружок макета не предлагает, а обещает расписать ошибки, и плюс на
 * него — «распишите» (afterCircle).
 */
const PLUS = /^[\s+＋➕]*(?:\+|＋|➕|плюс|plus)[\s+＋➕!.)]*$/iu;

/**
 * Короткое «да» в ответ на письмо с разбором.
 *
 * Сам по себе короткий ответ модели не отдаётся (SHORT_WORDS): «да» может
 * значить что угодно. Но письмо после «Здравствуйте» кончается одним
 * вопросом — собрать ли макет, — и «да», «давайте», «ha» на него — согласие.
 * С вопросительным знаком («да?») — уже вопрос, его разбирает человек.
 */
const YES =
  "да|дa|давайте|давай|хочу|хотим|интересно|согласен|согласна|согласны|конечно|ок|окей|ok|okay|yes|sure|ha|xa|xo['ʻ‘`]?p|mayli|albatta|qiziq|ҳа|ха|хоп|майли|албатта" +
  // «Делайте» — тоже «да» на кружок (enotmebel.uz, 11.10.2026: ответ ушёл
  // человеку как «коротко и непонятно»). И узбекское «qiling» — «сделайте».
  "|делайте|делай|сделайте|сделай|делаем|можно|хорошо|отлично|жду|ждём|ждем|нужно|надо|го|погнали" +
  "|qiling|qilinglar|qilavering|tayyorlang|kerak|mumkin|қилинг|қилаверинг|керак|мумкин";
const YES_WORDS = new RegExp(`^(?:${YES})(?:[\\s,!.)]+(?:${YES}|пожалуйста|iltimos))*[\\s!.)]*$`, "iu");

/** Адрес почты в ответе: разбор туда модель не пришлёт — это человеку. */
const EMAIL_WORDS = /на\s+почту|e-?mail|имейл|емейл|pochta|[\w.+-]+@[\w-]+\.[\w.-]+/iu;

/** «Расскажите», «слушаю», «какие ошибки» — просьба расписать, обещанное в кружке. */
const GO_ON =
  /слуша|расскаж|рассказыв|распиш|расписыв|(?:^|[^\p{L}])(?:на)?пишите|покаж|показыв|ошибк|(?:^|[^\p{L}])какие|xato|eshit|ayt(?:ing|ib)|yoz(?:ing|ib\s*ber)|ko['ʻ‘`]?rsat/iu;

/**
 * Ответ на кружок, пока разбора не было.
 *
 * Владелец, 22.10.2026: в кружке сказано, что на сайте нашли пару ошибок и
 * что мы их распишем, а бот на «да» и «+» отвечал «Принято, готовим макет» с
 * условиями. Человек ждал, где ошибки, и получал обещание макета. Теперь
 * ответ на кружок — «да», «+», 👍, «ок», «слушаю», «какие ошибки?», любой
 * вопрос, «пришлите», «передам руководству», развёрнутый ответ — получает разбор:
 * письмо по проверке сайта по факту, в конце которого предложение макета
 * (outreach-talk-store → answerCircle). Макет сразу — только если о нём
 * попросили словами. «Бесплатно?», «продаём через Инстаграм» и прочие
 * возражения — разговор, как и раньше. Короткое непонятное без вопроса
 * («нет», «позже», «спасибо») разбора не получает: это чаще отговорка, чем
 * «распишите» (SHORT_WORDS).
 */
function afterCircle(body: string): InboundVerdict {
  const objection = objectionOf(body);
  if (objection === "what" || objection === "boss") return "breakdown";
  if (objection) return "talk";
  if (PROTO_WORDS.some((re) => re.test(body))) return "proto";
  if (EMAIL_WORDS.test(body)) return "send";
  if (PLUS.test(body) || YES_WORDS.test(body) || GO_ON.test(body) || SEND_WORDS.some((re) => re.test(body))) return "breakdown";
  if (body.includes("?") || body.includes("؟")) return "breakdown";
  // 👍 или стикер на «распишем?» — «да»: без слов не отказывают.
  if (!/[\p{L}\p{N}]/u.test(body)) return "breakdown";
  const words = body.split(/\s+/).filter(Boolean).length;
  return words <= SHORT_WORDS ? "unclear" : "breakdown";
}

export function readInbound(text: string, opts: { stage?: PitchStage | null } = {}): InboundVerdict {
  const body = text.trim();
  if (STOP_WORDS.some((re) => re.test(body))) return "stop";
  if (HUMAN_WORDS.some((re) => re.test(body))) return "human";
  if (opts.stage === "circle") return afterCircle(body);
  if (PLUS.test(body)) return "proto";
  if (opts.stage === "letter" && YES_WORDS.test(body)) return "proto";
  // «Что значит прототип?», «О каком макете речь?» — вопрос, а не согласие
  // (разбор переписок 07–17.10.2026): раньше слово «прототип» в нём звало
  // всю команду «Нужен прототип» и слало «Принято, готовим макет».
  if (objectionOf(body) === "what") return "talk";
  if (PROTO_WORDS.some((re) => re.test(body))) return "proto";
  if (SEND_WORDS.some((re) => re.test(body))) return "send";

  // Вопрос — это начало разговора на любом языке и любой длины: «Qancha
  // turadi?» короче трёх слов, но отвечать на него надо.
  if (body.includes("?") || body.includes("؟")) return "talk";

  const words = body.split(/\s+/).filter(Boolean).length;
  return words <= SHORT_WORDS ? "unclear" : "talk";
}

