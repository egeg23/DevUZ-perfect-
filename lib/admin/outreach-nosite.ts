export const NOSITE_TOOL = {
  name: "nosite_message",
  description: "Первое сообщение компании без сайта.",
  input_schema: {
    type: "object" as const,
    properties: {
      message: { type: "string", minLength: 120, maxLength: 1200 },
    },
    required: ["message"],
  },
};

export type NositeInput = {
  /** Название компании, как его записал менеджер. */
  label: string | null;
  /** Ниша словами: «стоматология», «доставка еды», «автосервис». */
  niche: string;
  /** Имя менеджера — оно встанет в приветствие и подпись. */
  sender: string;
};

export function nositePrompt(input: NositeInput): string {
  const proof = proofFor(input.niche, [input.label ?? "", input.niche]);
  const brief = nicheBrief(input.niche, proof.reference);

  return [
    `Компания: ${input.label?.trim() || "название не записано"}.`,
    `Чем занимается: ${input.niche.trim()}.`,
    "Сайта нет — ни одного адреса мы не нашли и разбирать нечего. Это и есть повод написать.",
    brief,
    `Что человек ищет в поиске: «${input.niche.trim()} Ташкент» и близкие запросы. Находит тех, у кого сайт есть.`,
    proofLines(proof),
    `Отправитель: ${input.sender}. Представься этим именем и подпишись им же.`,
    "Пиши по-русски.",
  ]
    .filter(Boolean)
    .join("\n\n");
}

/**
 * Проверка письма без сайта.
 *
 * Та же, что у обычного касания, минус две вещи: домен проверять нечего, и
 * крючков с баллами здесь нет — их даёт анализ, которого не было. Остальное
 * держится: выдуманное число в письме к тому, о ком мы не знаем ничего, —
 * самый быстрый способ закончить разговор.
 */
export function nositeProblems(message: string, prompt: string): MessageProblem[] {
  const problems: MessageProblem[] = [];
  const words = message.trim().split(/\s+/).filter(Boolean).length;

  if (words < 40) problems.push({ code: "short", text: "Сообщение короче сорока слов — в нём не поместится ни мысль, ни повод ответить." });
  if (words > 190) problems.push({ code: "long", text: "Сообщение длиннее ста девяноста слов — на телефоне такое не читают." });
  if (!/devuz\.studio/i.test(message)) {
    problems.push({ code: "no_us", text: "В сообщении нет devuz.studio — непонятно, кто пишет." });
  }

  const invented = inventedNumbers(message, prompt);
  if (invented.length) {
    problems.push({ code: "invented", text: `Числа, которых нет в задании: ${invented.join(", ")}. Проверьте или уберите.` });
  }
  const alien = foreignScript(message);
  if (alien.length) {
    problems.push({
      code: "foreign_script",
      text: `В сообщении есть знаки чужого письма: ${alien.join(" ")}. Уберите их — это сбой модели, а не текст.`,
    });
  }
  if (bannedPhrase(message)) {
    problems.push({
      code: "banned",
      text: "В сообщении есть обещание или знак, которых в первом касании быть не должно: «в топ», «гарантируем», любые проценты, эмодзи.",
    });
  }
  return problems;
}
