/**
 * Пределы размера загружаемых файлов — в одном месте.
 *
 * Их не два, а четыре, и лежат они в разных слоях: nginx на сервере, лимит
 * server action в next.config, и вот эти проверки в коде. Работает всегда
 * самый маленький, поэтому порядок обязан быть таким:
 *
 *     nginx  >  server action  >  эти числа
 *
 * Иначе отказ приходит раньше, чем до файла добирается код, — и приходит он
 * кодом 413 без единого слова. Встроенный браузер Telegram показывает на
 * это «This page couldn't load», и человек ищет причину в файле. Ровно так
 * и вышло: nginx стоял на 128 килобайтах, а подпись весила 271.
 *
 * Проверка `tests/upload-limits.test.ts` сверяет все три слоя между собой.
 */

/** Подпись — несколько десятков килобайт. Мегабайты означают фото стола. */
export const MAX_SIGNATURE_BYTES = 2 * 1024 * 1024;

/** Смета — таблица, а не картинка. */
export const MAX_ESTIMATE_BYTES = 5 * 1024 * 1024;

/** Скан договора — фотографии страниц, они тяжелее всего остального. */
export const MAX_SIGNED_SCAN_BYTES = 20 * 1024 * 1024;
