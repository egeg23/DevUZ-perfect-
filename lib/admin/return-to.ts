/**
 * Имена кук панели и память о том, куда человек шёл.
 *
 * Отдельным модулем ради middleware: он исполняется в окружении без
 * node:crypto и без клиента базы, то есть импортировать lib/admin/session
 * оттуда нельзя. Повторить имя куки строкой было бы проще — и однажды одна
 * из двух строк поменялась бы, а расхождение проявилось бы не поломкой, а
 * тихо переставшей работать мелочью. Поэтому имя живёт здесь, а session.ts
 * берёт его отсюда же.
 */

/**
 * Кука сессии. Путь у неё — /admin, а не корень: на публичных страницах она
 * не нужна ни разу, а всё, что не отправляется, невозможно и перехватить.
 */
export const SESSION_COOKIE = "devuz_admin";

/**
 * Куда человек шёл, когда его развернуло на вход.
 *
 * Кука, а не «?next=» в адресе: адрес входа приходит из Telegram, и
 * дописать в него что-либо оттуда нельзя.
 */
export const NEXT_COOKIE = "devuz_admin_next";

/** Столько же, сколько живёт сама ссылка входа. */
export const NEXT_TTL_SECONDS = 15 * 60;

/** Из чего состоят наши собственные адреса в панели. Чужого не пускаем. */
const ADMIN_PATH = /^\/admin(\/[A-Za-z0-9._-]{1,64})*\/?$/;

/**
 * Точка и две точки — тоже «наши буквы», и это ровно та дыра, которую
 * посимвольная проверка обычно и пропускает: /admin/../etc/passwd
 * проходит её целиком, а ведёт наружу панели.
 */
const DOTS = /(^|\/)\.{1,2}(\/|$)/;

/**
 * Запоминать ли этот адрес как «куда он шёл».
 *
 * Возвращает путь без параметров: в них бывает «?contact=1», то есть
 * раскрытие контакта клиента. Такое должно происходить от нажатия
 * человека, а не само собой после входа.
 */
export function wantedPath(pathname: string): string | null {
  if (!ADMIN_PATH.test(pathname) || DOTS.test(pathname)) return null;
  if (pathname === "/admin" || pathname === "/admin/") return null;
  // Иначе вход после входа вёл бы на вход.
  if (pathname.startsWith("/admin/login") || pathname.startsWith("/admin/enter")) return null;
  // Служебные адреса — не страницы: маячок просмотров и возврат из Google.
  // Истёкшая сессия не должна после входа приводить человека туда.
  if (pathname.startsWith("/admin/beacon") || pathname.startsWith("/admin/google")) return null;
  return pathname;
}

/**
 * Куда вести после входа: значение куки, если оно всё ещё похоже на наш
 * адрес, иначе — главная панели.
 *
 * Значение писали мы сами и только из проверенного пути, но обратно оно
 * приходит от браузера, а всё, что приходит от браузера, — чужой ввод,
 * даже если мы его туда и положили.
 */
export function returnTo(value: string | null | undefined): string {
  const path = (value ?? "").trim();
  return path !== "/admin" && wantedPath(path) ? path : "/admin";
}
