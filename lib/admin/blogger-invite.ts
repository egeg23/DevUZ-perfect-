export function inviteRows(): Button[][] {
  return [
    [
      { text: "✅ Принять", callback_data: `${INVITE_CALLBACK}:${BLOGGER_INVITE.id}:yes` },
      { text: "✖ Отклонить", callback_data: `${INVITE_CALLBACK}:${BLOGGER_INVITE.id}:no` },
    ],
  ];
}

/** Нажатие: `binv:<приглашение>:yes|no`. Чужое или битое — null. */
export function parseInviteCallback(parts: readonly string[]): { inviteId: string; answer: InviteAnswer } | null {
  if (parts.length !== 3 || parts[0] !== INVITE_CALLBACK) return null;
  if (parts[1] !== BLOGGER_INVITE.id) return null;
  if (parts[2] !== "yes" && parts[2] !== "no") return null;
  return { inviteId: parts[1], answer: parts[2] };
}

/** Строка под приглашением вместо кнопок. */
export function statusLine(answer: InviteAnswer, role: Role): string {
  if (answer === "no") return "<i>✖ Вы отказались. Передумаете — напишите Александру или мне.</i>";
  return role === "manager"
    ? "<i>✅ Вы приняли. Вкладка «Блогеры» в «ИИ-сотрудниках» открыта, памятка — ниже.</i>"
    : "<i>✅ Вы приняли. Памятка — ниже.</i>";
}

export const ALREADY_ANSWERED = "Ответ уже записан";

/** Строка владельцу и руководителю на каждый ответ. */
export function answerLine(name: string, answer: InviteAnswer): string {
  return answer === "yes"
    ? `✅ ${name} принял приглашение работать с блогерами.`
    : `✖ ${name} отказался от работы с блогерами.`;
}

export type Tally = { yes: string[]; no: string[]; silent: string[] };

/** Итог владельцу: кто принял, кто отказался, кто молчит. */
export function tallyText(t: Tally, title = "<b>Приглашение «Работа с блогерами» — итог</b>"): string {
  const list = (names: string[]) => (names.length ? names.join(", ") : "—");
  return [
    title,
    `✅ Приняли (${t.yes.length}): ${list(t.yes)}`,
    `✖ Отказались (${t.no.length}): ${list(t.no)}`,
    `… Молчат (${t.silent.length}): ${list(t.silent)}`,
  ].join("\n");
}

/** Копия владельцу: что ушло от его имени. */
export function ownerCopy(): string {
  return [
    "<i>Копия: это приглашение ушло менеджерам и руководителю от вашего имени, с кнопками «✅ Принять» и «✖ Отклонить». Ниже — текст менеджера. Ответы придут сюда по одному, итог — в 18:00.</i>",
    "",
    inviteText("manager"),
  ].join("\n");
}

/**
 * Галочки после «Принять»: менеджеру — раздел открыт. Остальные галочки как
 * были. Руководителю раздел положен по роли — галочка не нужна.
 */
export function accessAfterYes(role: Role, access: Readonly<Record<string, boolean>>): Record<string, boolean> | null {
  if (role !== "manager") return null;
  if (access[INVITE_SECTION] === true) return null;
  return { ...access, [INVITE_SECTION]: true };
}
