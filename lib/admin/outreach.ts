/**
 * Можно ли писать этому сайту.
 *
 * Предела здесь нет намеренно: он про очередь, а не про сайт. Исчерпанный
 * час не делает касание неуместным — он только отодвигает отправку, и
 * менеджер об этом узнаёт словами, а не запертой кнопкой.
 */
export function canContact(input: {
  contacts: Contacts;
  findings: readonly Finding[];
  status: string;
}): Reason {
  if (input.status !== "new" && input.status !== "contacting") return "already";
  if (!input.findings.length) return "nothing_to_say";
  if (!routeFor(input.contacts)) return "no_way";
  return "ok";
}

/* ── Очередь ───────────────────────────────────────────────────────────── */

export type QueueView = {
  /** Сколько заданий стоит перед этим, считая с нуля. */
  ahead: number;
  /** Когда примерно уйдёт — миллисекунды от «сейчас». */
  waitMs: number;
};

/**
 * Через сколько дойдёт очередь.
 *
 * Считается по двум числам: сколько уже ушло за последний час и сколько
 * заданий стоит впереди. Оценка грубая и намеренно не приукрашенная —
 * менеджеру нужно решить «ждать или написать самому», а для этого хватает
 * порядка величины.
 */
export function queueView(input: {
  ahead: number;
  sentLastHour: number;
  /** Сколько миллисекунд назад ушло самое старое из отправленных за час. */
  oldestSentAgoMs: number | null;
}): QueueView {
  const slotsNow = Math.max(0, HOURLY_CAP - input.sentLastHour);
  if (input.ahead < slotsNow) return { ahead: input.ahead, waitMs: input.ahead * MIN_GAP_MS };

  // Место освобождается, когда самое старое сообщение часа выпадает из окна.
  const freesIn = input.oldestSentAgoMs === null ? 0 : Math.max(0, HOUR_MS - input.oldestSentAgoMs);
  const extraHours = Math.floor((input.ahead - slotsNow) / HOURLY_CAP);
  return { ahead: input.ahead, waitMs: freesIn + extraHours * HOUR_MS };
}

/** «через 40 минут», «через 2 часа» — так, как это скажет человек. */
export function waitText(ms: number): string {
  const minutes = Math.round(ms / 60_000);
  if (minutes <= 1) return "вот-вот";
  if (minutes < 60) return `примерно через ${minutes} мин.`;
  const hours = Math.round(minutes / 60);
  const word = hours === 1 ? "час" : hours >= 2 && hours <= 4 ? "часа" : "часов";
  return `примерно через ${hours} ${word}`;
}

/* ── Что видит модель ──────────────────────────────────────────────────── */

export type OutreachInput = {
  host: string;
  label: string | null;
  niche: string | null;
  findings: readonly Finding[];
  /** Черновик аудитора: тон и структура, от которых отталкиваться. */
  draft: string | null;
  sender: string;
};

/**
 * Что модель видит, когда пишет первое сообщение.
 *
 * Находки передаются без «что делаем» намеренно. Владелец: «не выдавай
 * чёткие ответы, просто укажи 1-2 проблемы и дальше — в разборе с нашим
 * менеджером». Модель не станет придумывать починку, которой ей не дали, —
 * а дав её, мы бы отдали в первом же сообщении то, ради чего человек и
 * должен ответить.
 *
 * Балл видимости в поиске идёт отдельной строкой: он короче любой находки и
 * понятнее — «47 из 100» человек прочитает быстрее, чем абзац про карту
 * сайта. Числа из промпта разрешены проверкой `inventedNumbers`, поэтому
 * балл можно называть, а выдуманный процент — по-прежнему нет.
 */
/**
 * Два числа, ради которых письмо вообще открывают.
 *
 * До этого первое сообщение состояло из описаний: «нет карты сайта», «нет
 * заголовка». Владелец их читает как придирки — у него таких писем десять в
 * неделю. Числа читаются иначе: «58 из 100» и «теряете 31–48 из каждых ста»
 * — это уже про его деньги, и проверить их он идёт сам.
 *
 * Считаются здесь, а не в промпте, потому что их проверяет машина: письмо, в
 * котором крючка не оказалось, до отправки не доходит. Полагаться на то, что
 * модель не забудет, нельзя — она забывает.
 */
export type Hooks = {
  /** Балл видимости в поиске; null — сайт не открылся, считать нечего. */
  seo: number | null;
  /** Сколько обращений из ста теряется на найденных местах. */
  lost: readonly [number, number] | null;
};

export function outreachHooks(findings: readonly Finding[]): Hooks {
  const seo = seoReport({ findings });
  const loss = forecast(findings);
  return {
    seo: seo.measured && seo.total > 0 ? seo.score : null,
    // Ноль потерь — это не крючок, а строка «у вас всё хорошо»: такую в
    // письмо ставить незачем.
    lost: loss.counted.length && loss.lostPer100[1] > 0 ? loss.lostPer100 : null,
  };
}

export function outreachPrompt(input: OutreachInput): string {
  const seo = seoReport({ findings: input.findings });
  const hooks = outreachHooks(input.findings);

  // Показываем модели столько же, сколько она вправе назвать: дав больше,
  // мы полагались бы на то, что она удержится.
  const named = new Set(seo.shown.map((f) => f.code));
  const findings = [
    ...seo.shown,
    // Одна находка не про поиск: сайт, у которого с Google всё хорошо, иначе
    // получил бы письмо ни о чём.
    ...input.findings.filter((f) => !named.has(f.code)).slice(0, 1),
  ]
    .map((f, i) => `${i + 1}. [${f.severity}] ${f.title}\n   Чем оборачивается: ${f.impact}`)
    .join("\n");

  const search =
    hooks.seo === null
      ? ""
      : `Видимость в поиске: ${hooks.seo} из 100 — это число обязано прозвучать в письме.${seo.hidden > 0 ? ` Ещё ${seo.hidden} замечаний по этой части оставлены для разбора с менеджером — их не перечисляй.` : ""}`;

  const losing = hooks.lost
    ? `Потери: на найденных местах из каждых ста человек, дошедших до сайта и готовых обратиться, теряются примерно ${hooks.lost[0]}–${hooks.lost[1]}. Оба числа обязаны прозвучать в письме, и рядом — что это оценка на сто посетителей, а не замер его статистики.`
    : "";

  return [
    `Сайт: ${input.host}`,
    input.label ? `Компания: ${input.label}` : "Название компании неизвестно.",
    input.niche ? `Ниша: ${input.niche}` : "",
    `Отправитель: ${input.sender}.`,
    search,
    losing,
    "",
    "Что нашёл анализ (починку не называй — она обсуждается на разборе):",
    findings,
    "",
    input.draft
      ? `Черновик, собранный без модели, — как образец тона и длины. Он писался до того, как починку перестали называть в первом письме: бери из него интонацию, а не «делаем то-то за столько-то».\n\n${input.draft}`
      : "",
    "",
    "Напиши первое сообщение в Telegram по этому сайту.",
  ]
    .filter(Boolean)
    .join("\n");
}

