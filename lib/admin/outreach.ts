/**
 * Касание: от находки на сайте до сообщения, которое отправит сотрудник.
 *
 * Владелец: «там, где менеджеры отсмотрели и нажали „связаться", ИИ
 * подготавливает сообщение и начинает с того, что выдал анализ; дать
 * возможность редакции первого сообщения перед отправкой. Тот сотрудник,
 * который нажал отправить, — лид автоматически закрепляется за ним».
 *
 * Пишет рабочий аккаунт студии, а не бот: бот в Telegram не может написать
 * первым. Отсюда и главное ограничение этого файла — не текст, а счётчик.
 * За рассылку из личного аккаунта Telegram ограничивает аккаунт целиком, а
 * этим же аккаунтом скаут читает чаты: потеряв его, студия теряет сразу два
 * канала. Поэтому здесь живут пределы, и они не декоративные.
 */

/* ── Предохранители ────────────────────────────────────────────────────── */

/**
 * Сколько первых писем в час с одного аккаунта.
 *
 * Владелец: «выстави лимит написаний 2 контакта в час; остальные ставь в
 * очередь или предложи менеджеру не ждать очередь, а написать с личного
 * аккаунта». 04.10.2026 — поднял: «3 сообщения новым пользователям в час. В
 * рабочие часы. С теми, с кем уже общаемся, лимита нет». Предел — не отказ:
 * сообщение всё равно принимается и уходит, когда подойдёт его черёд.
 * Переписка с ответившими через эту очередь не идёт и предела не знает.
 */
export const HOURLY_CAP = 3;

/**
 * Когда уходят первые письма: каждый день с 07:30 до 20:30 по Ташкенту
 * (владелец, 04.10.2026). Незнакомому человеку в одиннадцать вечера пишут
 * только рассылки — и жалуются на них тоже чаще. Письмо, поставленное ночью,
 * ждёт в очереди и уходит утром первым. Ответы тем, кто уже пишет нам, —
 * в любое время: это разговор, а не первое касание.
 */
export const SEND_FROM_MINUTE = 7 * 60 + 30;
export const SEND_TO_MINUTE = 20 * 60 + 30;
const TASHKENT_SHIFT_MS = 5 * 3600_000;

function tashkentMinute(now: number): number {
  const shifted = new Date(now + TASHKENT_SHIFT_MS);
  return shifted.getUTCHours() * 60 + shifted.getUTCMinutes();
}

/** Можно ли сейчас отправлять первые письма. */
export function sendWindowOpen(now = Date.now()): boolean {
  const minute = tashkentMinute(now);
  return minute >= SEND_FROM_MINUTE && minute < SEND_TO_MINUTE;
}

/** Через сколько откроется окно отправки; 0 — уже открыто. */
export function untilSendWindow(now = Date.now()): number {
  if (sendWindowOpen(now)) return 0;
  const minute = tashkentMinute(now);
  const minutes = minute < SEND_FROM_MINUTE ? SEND_FROM_MINUTE - minute : 24 * 60 - minute + SEND_FROM_MINUTE;
  const intoMinute = (now + TASHKENT_SHIFT_MS) % 60_000;
  return minutes * 60_000 - intoMinute;
}

/**
 * С какого балла видимость перестаёт быть находкой.
 *
 * Выше этого числа говорить «у вас проблемы с поиском» нельзя: адресат
 * откроет свою статистику и увидит, что его находят. Такой балл подаётся
 * как комплимент и как разворот к тому, что действительно болит.
 */
export const HIGH_SEO = 85;

/** Час, в котором считается предел. */
export const HOUR_MS = 3600_000;

/**
 * Пауза между отправками внутри часа: два сообщения подряд в одну секунду
 * — это подпись рассылки, даже когда их всего два.
 */
export const MIN_GAP_MS = 8 * 60_000;
export const MAX_GAP_MS = 20 * 60_000;

/** Ошибки Telegram, после которых отправлять нельзя до конца суток. */
export const STOP_ERRORS = ["PEER_FLOOD", "USER_PRIVACY_RESTRICTED", "FLOOD_WAIT", "USER_BANNED_IN_CHANNEL"];

export function isStopError(message: string): boolean {
  const upper = message.toUpperCase();
  return STOP_ERRORS.some((code) => upper.includes(code));
}

/* ── Маршрут: чем именно мы дотянемся ──────────────────────────────────── */

/**
 * Первые полсотни касаний показали, что писать в телеграм по адресу с сайта
 * почти некому. Из четырнадцати адресатов девять оказались каналами (все
 * отбились с CHAT_WRITE_FORBIDDEN — в канал нельзя написать в личку), три
 * ботами (все три «дошли» в автоответчик), и только два были обычными
 * аккаунтами. Живой человек не ответил ни разу.
 *
 * Дело не в текстах: ссылка t.me на сайте компании — это её канал или её
 * бот, потому что именно их компания и публикует. Личный аккаунт, в который
 * можно постучаться, на сайте не печатают.
 *
 * Отсюда три маршрута вместо одного.
 */
export type RouteKind = "handle" | "phone" | "manual";

export type Route = { kind: RouteKind; target: string };

/**
 * Бот ли это по имени.
 *
 * Телеграм требует, чтобы имя бота кончалось на «bot», — но обратное неверно,
 * и живой человек может назваться @talbot. Ошибка здесь стоит одного
 * упущенного адресата, а пропущенный бот стоит места в очереди и письма в
 * пустоту, поэтому отсеиваем по имени. Настоящую проверку всё равно делает
 * скаут: у телеграма есть флаг, и он не ошибается.
 */
export function isBotHandle(handle: string): boolean {
  return /bot$/i.test(handle.replace(/^@/, ""));
}

/**
 * Коды мобильных операторов Узбекистана.
 *
 * Городской номер телеграм по определению не найдёт: аккаунты заводят на
 * мобильные. Незнакомый код уводит карточку в ручной маршрут — и это верная
 * сторона ошибки: там на неё посмотрит человек, а не сгорит место в очереди.
 */
const UZ_MOBILE = new Set(["20", "33", "50", "55", "77", "88", "90", "91", "93", "94", "95", "97", "98", "99"]);

export function isMobile(phone: string): boolean {
  const uz = phone.match(/^\+998(\d{2})/);
  // Чужая страна — кодов не знаем и решать за телеграм не беремся.
  return uz ? UZ_MOBILE.has(uz[1]) : /^\+\d{10,15}$/.test(phone);
}

/**
 * Каким путём идти к этой компании.
 *
 * Порядок не случайный. @адрес — единственный путь, где мы заведомо пишем
 * туда, куда собирались. Номер с кнопки WhatsApp идёт раньше номера из
 * подвала: на первом заведомо читают сообщения, второй может оказаться
 * стойкой администратора. Городской номер — последний: аккаунта в телеграме
 * на нём не будет никогда, но по нему звонят, и это тоже касание.
 */
export function routeFor(contacts: Contacts): Route | null {
  const handle = contacts.telegram.find((h) => !isBotHandle(h));
  if (handle) return { kind: "handle", target: handle };

  const hand = handTargetFrom(contacts);
  if (!hand) return null;
  // Мобильный скаут ещё попробует найти в телеграме; городской — нет, по
  // нему только звонят.
  return { kind: isMobile(hand) ? "phone" : "manual", target: hand };
}

/**
 * Чем дотянуться, когда телеграм отпал.
 *
 * Нужно там, где маршрут «телеграм» рухнул уже на отправке: адрес оказался
 * каналом, номер не нашёлся. Карточка после этого уходит человеку — и в ней
 * обязан стоять номер, а не @адрес. Иначе выходит то, что и вышло: карточка
 * с маршрутом «дальше руками» предлагала позвонить по `tel:@muradbuildings`
 * и открыть WhatsApp по ссылке, собранной из букв.
 *
 * Порядок тот же, что и в маршрутах: номер с кнопки WhatsApp идёт раньше
 * номера из подвала — на первом заведомо читают сообщения. Городской
 * последний: писать туда некуда, но позвонить можно, и это тоже касание.
 *
 * Принимает не весь `Contacts`, а только то, что читает: этой же функцией
 * пользуется очередь касаний, куда тащить весь разбор контактов незачем.
 */
export function handTargetFrom(contacts: {
  whatsapp: readonly string[];
  phones: readonly string[];
}): string | null {
  return [...contacts.whatsapp, ...contacts.phones].find(isMobile) ?? contacts.phones[0] ?? null;
}

