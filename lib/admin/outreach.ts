/**
 * Числа в сообщении обязаны быть из анализа.
 *
 * Та же проверка, что у рекомендаций, и по той же причине: выдуманная
 * секунда в «сайт отвечает за 4.2 секунды» превращает проверяемое
 * наблюдение в ложь, которую адресат поймает первым же обновлением страницы.
 */
/**
 * Длительность созвона — не утверждение о сайте.
 *
 * Проверка стоит здесь, чтобы ловить выдуманные замеры: «сайт отвечает за
 * 4.2 секунды», когда в анализе такого числа нет. «Созвонимся на 20 минут»
 * под это правило попадало формально и дважды на живых прогонах отбивало
 * годное письмо — менеджер, нажав «Связаться», получал бы отказ вместо
 * текста.
 *
 * Вырезаем ровно этот оборот и ровно в этой форме: с предлогом «на» и с
 * минутами. Замер скорости так не пишут — там «за 4 секунды», — поэтому
 * лазейки для выдумки о сайте здесь не открывается.
 */
/*
 * Границы слова здесь через \p{L}, а не \b: `\b` и `\w` в JavaScript знают
 * только латиницу, и `\bна` перед кириллицей не срабатывает. В этом файле на
 * те же грабли уже наступали — см. список запрещённых оборотов ниже.
 */
/**
 * Длительность созвона — не замер о сайте, а оборот речи.
 *
 * «Созвонимся на 20 минут» дважды отбивалось проверкой на выдуманные числа,
 * и менеджер, нажав «Связаться», получал отказ вместо письма. Оборот
 * разрешён ровно в этой форме — выдуманный замер так не пишут.
 *
 * Узбекский вариант добавлен вместе с письмами на узбекском: «20 daqiqaga»
 * — то же самое, и без этой строки первое же узбекское письмо отбивалось бы
 * на ровном месте. Апостроф в «yo‘q» тут ни при чём, а вот падежное
 * окончание «-ga/-lik» приклеивается к слову, поэтому хвост открытый.
 */
const CALL_LENGTH =
  /(?<!\p{L})(?:на\s+\d+(?:\s*[–—-]\s*\d+)?\s*минут\p{L}*|\d+(?:\s*[–—-]\s*\d+)?\s*(?:daqiqa|минут)\p{L}*)/giu;

export function inventedNumbers(message: string, prompt: string): string[] {
  const allowed = new Set((prompt.match(/\d+(?:[.,]\d+)?/g) ?? []).map((n) => n.replace(",", ".")));
  const out: string[] = [];
  for (const n of message.replace(CALL_LENGTH, " ").match(/\d+(?:[.,]\d+)?/g) ?? []) {
    const norm = n.replace(",", ".");
    if (!allowed.has(norm)) out.push(n);
  }
  return [...new Set(out)];
}

/**
 * Границы слова здесь не ставятся, а классы пишутся кириллицей вручную:
 * `\b` и `\w` в JavaScript знают только латиницу, поэтому «в топ\b» не
 * срабатывает после «топ», а «комплексн\w* подход» не видит «комплексный».
 */
const BANNED = [
  /в топ/i,
  /гарантиру/i,
  /первое место/i,
  // Проценты в первом касании запрещены целиком, а не в паре с
  // «продажами»: «рост конверсии 40 %» и «40 % продаж» — одно и то же
  // обещание, записанное в разном порядке, и проверить его адресат не
  // может. Замеры анализа процентами не выражаются — терять нечего.
  /\d+\s*%/,
  /комплексн[а-яё]*\s+подход/i,
  /[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}]/u,
];

/**
 * Есть ли в тексте оборот, которого у нас не бывает.
 *
 * Отдельной функцией, потому что запреты одинаковы для первого сообщения и
 * для любой реплики дальше: «выведем в топ» одинаково врёт и в первом
 * касании, и в десятом ответе. Список один — разъехавшись, он разрешил бы
 * в переписке ровно то, что запрещено в письме.
 */
/**
 * Иероглиф посреди русской фразы.
 *
 * Живой случай: «Видимость в поиске у вас高 — 92 из 100». Модель уронила
 * в текст знак чужого письма, и письмо ушло бы адресату с ним: ни одна
 * проверка на это не смотрела, а человек, вычитывая своё сообщение в
 * двадцатый раз за день, такой знак не видит.
 *
 * Письма мы пишем по-русски, по-узбекски (латиница) и по-английски —
 * см. язык в промпте. Ни в одном из трёх этих знаков не бывает, поэтому
 * правило простое: нашлось — значит сбой.
 */
const ALIEN =
  /[\u0590-\u05ff\u0600-\u06ff\u0900-\u097f\u0e00-\u0e7f\u3040-\u30ff\u3400-\u4dbf\u4e00-\u9fff\uac00-\ud7af]/gu;

export function foreignScript(text: string): string[] {
  return [...new Set(text.match(ALIEN) ?? [])];
}

export function bannedPhrase(text: string): boolean {
  return BANNED.some((re) => re.test(text));
}

export type MessageProblem = { code: string; text: string };

/**
 * Что не даёт отправить сообщение как есть. Пусто — можно отправлять.
 *
 * `hooks` проверяются машиной, а не доверием к модели. Просьба в системном
 * промпте «назови балл» выполняется в девяти письмах из десяти, и именно
 * десятое уходит без того единственного, ради чего письмо открывают.
 */
/**
 * Имена наших проектов — те, которые нельзя называть не в своей нише.
 *
 * Собственное имя студии сюда не попадает: «devuz.studio» в письме стоять
 * обязано, это подпись, а не пример работы.
 */
function caseNames(): string[] {
  return cases.filter((c) => c.slug !== "devuz").map((c) => c.name);
}

export function messageProblems(
  message: string,
  prompt: string,
  host: string,
  hooks: Hooks = { seo: null, lost: null, reference: null },
): MessageProblem[] {
  const problems: MessageProblem[] = [];
  const words = message.trim().split(/\s+/).filter(Boolean).length;

  if (words < 40) problems.push({ code: "short", text: "Сообщение короче сорока слов — в нём не поместится ни находка, ни её последствие." });
  if (words > 200) problems.push({ code: "long", text: "Сообщение длиннее двухсот слов — на телефоне такое не читают." });
  if (!message.includes(host)) problems.push({ code: "no_host", text: `В сообщении нет домена ${host} — адресат не поймёт, что письмо про его сайт.` });
  if (!/devuz\.studio/i.test(message)) problems.push({ code: "no_us", text: "В сообщении нет devuz.studio — непонятно, кто пишет." });

  const invented = inventedNumbers(message, prompt);
  if (invented.length) {
    problems.push({ code: "invented", text: `Числа, которых нет в анализе: ${invented.join(", ")}. Проверьте или уберите.` });
  }
  const alien = foreignScript(message);
  if (alien.length) {
    problems.push({
      code: "foreign_script",
      text: `В сообщении есть знаки чужого письма: ${alien.join(" ")}. Уберите их — это сбой модели, а не текст.`,
    });
  }
  if (bannedPhrase(message)) {
    problems.push({ code: "banned", text: "В сообщении есть обещание или знак, которых в первом касании быть не должно: «в топ», «гарантируем», любые проценты, «комплексный подход», эмодзи." });
  }

  // Числа ищем как отдельные слова: «58» не должно засчитаться, потому что
  // в письме где-то стоит «258».
  const hasNumber = (n: number) => new RegExp(`(?<!\\d)${n}(?!\\d)`).test(message);

  if (hooks.seo !== null && !hasNumber(hooks.seo)) {
    problems.push({
      code: "no_seo_score",
      text: `В сообщении не назван балл видимости в поиске (${hooks.seo} из 100) — а это первое, за что цепляется взгляд.`,
    });
  }
  if (hooks.lost && !(hasNumber(hooks.lost[0]) && hasNumber(hooks.lost[1]))) {
    problems.push({
      code: "no_loss",
      text: `В сообщении не сказано, сколько обращений это стоит (${hooks.lost[0]}–${hooks.lost[1]} из ста). Без этого письмо читается как список придирок.`,
    });
  }
  /**
   * Чужой проект в письме — хуже, чем никакого.
   *
   * Правило «называй только проект из его ниши» стоит в промпте, и обычно
   * его хватает. Владелец поймал десятый случай: логистическим компаниям
   * ушли письма с MAVERA — нашим застройщиком. Подбор тогда ошибся сам, но
   * ошибиться может и модель: имена наших проектов лежат в том же промпте,
   * и взять оттуда не то — один неверный токен.
   *
   * Сравнение чувствительно к регистру намеренно: «USTA» — имя проекта, а
   * «usta» по-узбекски значит «мастер» и встречается в обычном тексте.
   */
  const foreign = caseNames().filter((n) => n !== hooks.reference && message.includes(n));
  if (foreign.length) {
    problems.push({
      code: "foreign_reference",
      text: `В сообщении назван наш проект не из его ниши: ${foreign.join(", ")}. «Делали в вашей нише» про чужую нишу адресат проверяет одним переходом по ссылке — и на этом письмо заканчивается.`,
    });
  }

  if (hooks.reference && !message.includes(hooks.reference)) {
    problems.push({
      code: "no_reference",
      text: `В сообщении не назван «${hooks.reference}» — наш проект в его же нише. Это самая сильная строка письма: её адресат проверяет за десять секунд, и после неё разговор идёт иначе.`,
    });
  }
  return problems;
}
