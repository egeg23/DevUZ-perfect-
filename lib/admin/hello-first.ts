import { detectLang } from "@/lib/talk/language";

/**
 * Касание в два шага: сначала «Здравствуйте», письмо — только тем, кто ответил.
 *
 * Владелец, 07.10.2026: «Сначала мы пишем просто — „Здравствуйте“. Если
 * ответ есть — тут уже пишем сообщение. Короткое. Либо кружок отправляем,
 * который ранее записали. Я сохраню его в избранные на каждом аккаунте…
 * Потому что отлетают по спаму аккаунты». На вопрос, что слать после
 * ответа, — «кружок + короткий текст»; если на «Здравствуйте» не ответили —
 * «ничего не шлём».
 *
 * Почему так. Telegram ограничивает аккаунт за жалобы «спам» от людей,
 * которым мы написали первыми. Длинное письмо о сайте от незнакомца
 * жалобу и получает, а «Здравствуйте» — нет: на него отвечают «да?» или
 * молчат. Тот, кто ответил, сам начал разговор, и письмо в нём — уже не
 * рассылка.
 *
 * Владелец, 08.10.2026, о записанном кружке: «если после „Здравствуйте“
 * нам ответили на русском — „Здравствуйте“ или аналогично на русском, — то
 * уходит кружок. Если ответили на другом языке — мы отвечаем на этом языке,
 * как обычно пишем». Кружок сам и есть предложение: бесплатный макет
 * главной за 12 часов и «отправьте плюс», — поэтому письмо за ним не идёт,
 * а «+» в ответ значит «да, хочу макет» (outreach-talk → readInbound).
 *
 * Как это устроено:
 * - скаут отправляет из очереди `helloFor(письмо)` вместо письма и ставит
 *   `hello_at` (outreach-queue → markSent);
 * - клиент ответил по-русски (или без слов — стикером, «+» — на русское
 *   «Здравствуйте») — в очередь ответов ложится кружок из «Избранного»
 *   рабочего аккаунта, `pitch_at`. Кружок не ушёл (его нет, получатель
 *   запретил голосовые и видео) — вместо него уходит письмо на языке ответа
 *   (outreach-talk-store → markCircleSkipped);
 * - ответил на другом языке — письмо без приветствия на языке ответа: было
 *   на другом — его переводит модель (letter-translate), кружка нет;
 * - ответил отказом или просит человека — ничего не уходит, разговор
 *   человеку;
 * - не ответил — ничего: дожима по «Здравствуйте» нет (outreach-followup).
 */

/** Первое сообщение — на языке письма: узбекскому сайту по-узбекски. */
export const HELLO_TEXT = {
  ru: "Здравствуйте",
  uz: "Assalomu alaykum",
  en: "Hello",
} as const;

export type HelloLang = keyof typeof HELLO_TEXT;

/** На каком языке письмо, а значит и «Здравствуйте» перед ним. */
export function letterLang(letter: string, lang?: string | null): HelloLang {
  // Язык письма решает обход сайта (walked.lang) — им же писалось и письмо.
  if (lang === "ru" || lang === "uz" || lang === "en") return lang;
  // Нет обхода — по тексту, без адресов: «almazmed.uz» и «devuz.studio» —
  // латиница, но не узбекский.
  return detectLang(letter.replace(/\S*[./]\S*/g, " "));
}

export function helloFor(letter: string, lang?: string | null): string {
  return HELLO_TEXT[letterLang(letter, lang)];
}

/**
 * На каком языке ответили на «Здравствуйте».
 *
 * Без единой буквы — стикер, «+», «?», «👍» — языка у ответа нет: человек
 * отвечает на то, что ему написали, значит, на языке приветствия.
 */
export function replyLang(body: string, helloLang: HelloLang): HelloLang {
  return /\p{L}/u.test(body) ? detectLang(body) : helloLang;
}

/** Кружок — тем, кто ответил по-русски: он записан на русском. */
export const CIRCLE_LANG: HelloLang = "ru";

/**
 * Письмо без приветствия в начале: «Здравствуйте» уже ушло отдельным
 * сообщением, и клиент на него ответил. Новые письма пишутся без него
 * (OUTREACH_SYSTEM), а это — для писем, написанных раньше.
 */
const GREETING =
  /^\s*(?:здравствуйте|добрый\s+(?:день|вечер)|доброе\s+утро|приветствую|assalomu\s+al[ae]y?kum|salom|hello|hi|good\s+(?:morning|afternoon|day))(?![\p{L}\p{N}])[\s,.!]*/iu;

export function withoutGreeting(letter: string): string {
  const rest = letter.replace(GREETING, "").trimStart();
  if (!rest) return letter.trim();
  return rest.charAt(0).toUpperCase() + rest.slice(1);
}

/**
 * Через сколько после ответа на «Здравствуйте» уходит кружок (ответили
 * по-русски) или письмо (на другом языке): ответ через секунду выглядит как
 * робот. Кружок не ушёл — письмо вместо него уходит сразу.
 */
export const CIRCLE_AFTER_MS = 2 * 60_000;
export const PITCH_AFTER_MS = 3 * 60_000;

/**
 * Что ложится в ленту разговора вместо кружка: его читает и модель, и
 * менеджер. Видео модель не видит — поэтому здесь сказано, что в нём:
 * иначе на «а что за макет?» ей нечем ответить.
 */
export const CIRCLE_BODY =
  "🎥 Кружок от студии (из «Избранного» рабочего аккаунта): представляемся, предлагаем бесплатно за 12 часов собрать рабочий макет главной страницы их сайта, ни к чему не обязывает; если интересно — просим отправить «+»";

/**
 * Почему кружок не ушёл — словами для ленты разговора, а не кодом Telegram.
 * VOICE_MESSAGES_FORBIDDEN: человек запретил голосовые и видеосообщения, а
 * кружок Telegram считает таким же (09.10.2026, superbody.uz).
 */
export function circleFailText(why: string): string {
  return /VOICE_MESSAGES_FORBIDDEN/.test(why)
    ? "Кружок не ушёл: получатель запретил голосовые и видеосообщения — вместо него письмо на языке ответа"
    : why;
}

/** Кружок не ушёл — вместо него уходит письмо, текстом. */
export const NO_CIRCLE = "Кружок не отправлен: в «Избранном» этого рабочего аккаунта нет кружка — вместо него ушло письмо";

/**
 * Что делать с ответом на «Здравствуйте». Отказ и просьба позвать человека —
 * человеку, письма нет: после «не пишите» следующее сообщение и есть то, за
 * что аккаунты блокируют. Всё остальное — «да?», «кто это?», «слушаю»,
 * «Assalomu alaykum» — повод для письма: короткий ответ на приветствие —
 * норма, а не непонятный ответ на письмо.
 */
export function pitchAfter(verdict: string): boolean {
  return verdict !== "stop" && verdict !== "human";
}

/** Ждёт ли касание письма: «Здравствуйте» ушло, письмо — ещё нет. */
export function waitsForPitch(p: { hello_at?: unknown; pitch_at?: unknown }): boolean {
  return Boolean(p.hello_at) && !p.pitch_at;
}
