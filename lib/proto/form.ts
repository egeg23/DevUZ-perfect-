/**
 * Разбор полей формы прототипа.
 *
 * Живёт отдельно от серверных действий по двум причинам: из файла с
 * «use server» нельзя экспортировать ничего, кроме асинхронных действий, и
 * разбор строки прайса стоит проверить тестом, а не глазами на боевой форме.
 */
import type { ProtoService } from "@/lib/proto/facts";

/** Сколько услуг берём из формы. Больше двенадцати — это уже прайс, а не страница. */
const LIMIT = 12;

/**
 * Услуги: по строке на услугу, цена после тире.
 *
 * Цена остаётся строкой, как написано у клиента: «от 50 000 сум». Числом её
 * делать нельзя — ни валюта, ни «от», ни диапазон «50–80 тысяч» в число не
 * влезают, а округлять чужой прайс мы не вправе.
 *
 * Разделителем считается тире с пробелами, а не любой дефис: «Шиномонтаж
 * R16-R18» — это название услуги, а не услуга «Шиномонтаж R16» по цене
 * «R18».
 */
export function parseServices(raw: string): ProtoService[] {
  return raw
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => {
      const split = line.match(/^(.+?)\s+(?:—|–|\||-)\s+(.+)$/);
      return split ? { name: split[1].trim(), price: split[2].trim() } : { name: line, price: null };
    })
    .slice(0, LIMIT);
}
