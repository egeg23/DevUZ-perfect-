/**
 * Кнопка прототипа на сайте студии: страница кейса и ролик на главной.
 *
 * Владелец, 24.10.2026, когда пароль Александра к SamAuto закрыл прототип и
 * для посетителей кейса: «я бы не хотел, чтобы выданный пароль к самому
 * макету ограничивал то, что видит пользователь, когда он переходит в
 * кейсы». Прототип, который кейс показывает без пароля (`prototype.open`),
 * открывается по `?from=case`: сервер ставит пропуск кейса и уводит на
 * чистый адрес (lib/proto/case-pass). Пароль закрывает только прямую ссылку,
 * которую получил клиент.
 *
 * Модуль клиентский (ролик на главной): без списка кейсов и без node.
 */
import type { Case } from "@/content/cases";

/** Значение `from` в адресе, по которому сервер выдаёт пропуск кейса. */
export const CASE_FROM = "case";

/** Куда ведёт кнопка: открытый кейс — с пропуском, остальные — прямо, на пароль. */
export function caseProtoHref(proto: Pick<NonNullable<Case["prototype"]>, "href" | "open">): string {
  return proto.open ? `${proto.href}?from=${CASE_FROM}` : proto.href;
}
