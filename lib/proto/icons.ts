const BY_MEANING: readonly (readonly [RegExp, string])[] = [
  [/шин|колес|диск|балансир|прокол|вулканиз|запаск/i, "wheel"],
  [/кузов|вмятин|покрас|дтп/i, "car"],
  [/фильтр|расходник/i, "filter"],
  // Граница слова своя: \b в JS считает словом только латиницу, и «ТО» бы
  // не совпало ни разу.
  [/(?<![\p{L}-])то(?![\p{L}])|техобслуж|диагност/iu, "gauge"],
  [/масл|жидкост|антифриз|тормозн/i, "droplet"],
  [/мойк|химчист|полир|детейлинг|подкачк|пылес/i, "spray"],
  [/стриж|бород|брит|причёск|причес/i, "scissors"],
  [/маникюр|педикюр|ногт|бров|ресниц|макияж|окрашив|уход/i, "sparkle"],
  [/электр|двигател|акпп|инжектор|генератор|аккумул/i, "bolt"],
  [/защит|плёнк|пленк|антикор|шумоизол|хранен/i, "shield"],
];

/** Какая иконка подходит услуге. Не подобралась — ключ: он подходит всему. */
export function iconFor(name: string): string {
  return BY_MEANING.find(([pattern]) => pattern.test(name))?.[1] ?? "wrench";
}

export function icon(key: string): string {
  return ICONS[key] ?? ICONS.wrench;
}

